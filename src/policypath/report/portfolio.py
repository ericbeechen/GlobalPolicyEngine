def _key(ch):
    return "_".join([ch.construction, *(["rv"] if ch.sleeves else []), "shrunk" if ch.shrink else "unshrunk",
                     *([] if ch.correlations else ["diagonal"]), *(["drawdown"] if ch.overlay else [])])


def comparisons(b):
    """Every book-against-book difference the report quotes: {"a - b": `difference`}."""
    book = b.setup.book
    h = headline(book)
    cons = [Choice(c) for c in order(book)]
    rv = Choice(h.construction, sleeves=b.rv)
    pairs = [*itertools.combinations(cons, 2), *((Choice(c), Choice(c, shrink=False)) for c in order(book)),
             *((replace(ch, overlay=True), ch) for ch in [*cons, rv]), (rv, h),
             (Choice("mean_variance"), DIAGONAL), (DIAGONAL, Choice("inverse_vol"))]
    out = {f"{_key(x)} - {_key(y)}": difference(b.books[x], b.books[y]) for x, y in pairs
           if x in b.books and y in b.books}
    if b.free is not None:
        out[f"uncapped - {_key(h)}"] = difference(b.free, b.books[h])
    return out


def results(b):
    """reports/results/portfolio.json: the numbers the note quotes, to six significant figures."""
    st = b.setup
    book, capital = st.book, st.book["book"]["capital"]
    h = headline(book)
    hb = b.books[h]
    rk = b.risks[None]
    grid = book["costs"]["sensitivity_bp"]
    _, lag = _lag_table(b)
    return _plain({
        "spec": {"headline": _key(h), "construction": h.construction, "vol_target": book["book"]["vol_target"],
                 "capital": capital, "max_gross_dv01_per_capital": book["risk"]["max_gross_dv01_per_capital"],
                 "rule": st.spec.rule, "enter": st.spec.enter, "exit": st.spec.exit, "treatment": st.spec.treatment,
                 "first_decision": st.days[rk.first], "rv_sleeves": list(b.rv)},
        "books": {_key(ch): {k: v for k, v in s.items() if k != "halves"} | {"halves": s["halves"]}
                  for ch, s in b.summaries.items()},
        "uncapped_headline": b.uncapped,
        "paired": comparisons(b),
        "without_windows": without(hb, book["evaluation"]["exclude"], capital),
        "week8_sum": b.week8,
        "curves": {_key(ch): {"round_trip_bp": grid, "net_sr": list(sleeves.curve(x.run, grid)),
                              "assumed_only_net_sr": list(sleeves.curve(x.run, grid, "assumed"))}
                   for ch, x in b.books.items() if not ch.overlay and ch.shrink},
        "covariance": {"n_eff": rk.cov.n_eff[-1], "delta_mean": float(np.nanmean(rk.cov.delta[rk.first:])),
                       "by_year": cov_by_year(rk, rk.first).to_dict("index"), "lag": lag,
                       "mean_correlation_s0": mean_correlations(rk, rk.first, "s0").to_dict(),
                       "mean_correlation_s": mean_correlations(rk, rk.first, "s").to_dict()},
        "by_year_pct_capital": by_year(hb, capital).to_dict("index"),
        "vol_by_year": vol_by_year(hb, capital).set_index("year").to_dict("index"),
        "net_dv01_by_year": dv01_by_year(hb).to_dict("index"),
        "share_of_exante_variance": hb.targets.share[hb.targets.exante > 0].mean().to_dict(),
        "outright_share_of_exante_variance": _outright_share(b),
        "stale": stale(hb).to_dict("index"),
    })


def write(b, root):
    """Every output of the build under repo `root`. Returns the paths."""
    root = Path(root)
    out = {"report": root / "reports" / "portfolio.md", "json": root / "reports" / "results" / "portfolio.json"}
    for p in out.values():
        p.parent.mkdir(parents=True, exist_ok=True)
    out["report"].write_text(markdown(b), encoding="utf-8")
    out["json"].write_text(json.dumps(results(b), indent=1) + "\n", encoding="utf-8")
    figures = root / "reports" / "figures"
    figures.mkdir(parents=True, exist_ok=True)
    for theme in THEMES:
        p = figures / f"book_equity_{theme}.png"
        figure(b, p, theme)
        out[f"figure_{theme}"] = p
    return out
