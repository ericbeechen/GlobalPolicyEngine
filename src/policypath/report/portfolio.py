def _head(b):
    """The one-line verdict, from what the numbers say."""
    st = b.setup
    capital = st.book["book"]["capital"]
    h = headline(st.book)
    hs = b.summaries[h]
    years = by_year(b.books[h], capital)["book"]
    good = years[years > 0]
    rs = b.summaries[Choice(h.construction, sleeves=b.rv)]
    if hs["net_sr"] > 0:
        first = "the book earns net of costs" + (", within two SEs of zero" if hs["net_sr"] < 2 * hs["net_se"] else "")
    else:
        first = "the book loses money, net of costs" + (" and before them" if hs["gross_sr"] <= 0 else "")
    rest = []
    if all(not b.summaries[Choice(c)]["net_sr"] > 0 for c in order(st.book)):
        rest.append("every construction loses money net")
    if len(good) and years.sum() <= 0:
        rest.append(f"its {len(good)} good year{'s' if len(good) > 1 else ''} ({_and(str(y) for y in good.index)}) "
                    f"{'do' if len(good) > 1 else 'does'} not make up the other {len(years) - len(good)}")
    if not rs["gross_sr"] > 0:
        rest.append("the relative-value sleeves lose before costs on their own")
    words = _and(rest) if rest else ""
    return f"**In one line: {first}.**" + (f" {words[:1].upper()}{words[1:]}." if words else "")


