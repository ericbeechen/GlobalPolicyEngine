"""The portfolio report: what the book earns net of costs, how fragile that is, and what carries it.

Generated by `scripts/build_portfolio.py`, never hand-edited: every number
comes from the books run here, and every sentence is a template filled from
them. The answer comes first: what the book earns net, how fragile that is
(the cost curve and its breakeven, week 8's closed form), and what carries it
(the sleeves and the years).

**What is run.** Week 8's sleeves, unchanged: their legs, unit P&L, rules
(``positions.rule`` at (``positions.enter``, ``positions.exit``)), ELB
treatment (``evaluation.elb.chosen``) and costs (`report/costs.py`'s
`inputs`, built once). The book (`strategy/portfolio.py`) sizes their sides
together; `simulate` hands each sleeve the positions decided at the book's
closes, runs it through `expression.run` and `costs.traded` (the week 7 and 8
seams, so marks, instruments and costs are theirs to the bit), and credits
its flows to the book calendar. A book is a `Choice`: the construction, the
sleeves (all, or the RV-only book of the curve and cross sleeves), shrinkage
on or off, the drawdown overlay on or off. The headline (`headline`) is the
configured construction (``portfolio.headline``, inverse-vol, proposed),
shrunk, every sleeve, no overlay: the book the robustness grid and the cost
curves use.

**The sample.** A book decides from the first close with
``portfolio.min_history`` complete sessions of unit P&L behind it and is
evaluated from the first session a position decided there is held. A book
session counts where any sleeve's treatment counts a session credited to it
(`positions.samples`, as week 8's sum), so under the flat treatment the
sessions every sleeve spends in the ELB state are left out. Sharpe, its SE,
the breakeven and the cost curve are week 8's (`report/costs.py` `stats`,
`curve`), on the book's own daily frame.

**Turnover by cause** (`CAUSES`): a close's trade on a sleeve is an entry or
exit where the sleeve's own side moved, a resize where another sleeve's did
(the active set changed, so every weight moved), a rescale where neither did
(the covariance, the vol target, the cap, the overlay, and for mean-variance
its z), and maintenance where week 8 says so (rolls, re-strikes).

**Comparing two books** (`difference`): they share most of their positions
(daily net P&L correlations 0.91 to 0.997 on the build of 2026-09-29), so a
difference between them is judged against the SE of the difference, paired on
the sessions both count, never a single book's SE, which is 3 to 15 times
larger. Mean-variance's difference from inverse-vol is split into its two
channels by `DIAGONAL`, mean-variance on the covariance's diagonal.

**The drawdown overlay's fixed point** (`run_book`): the state at a close
reads the equity before it, which depends only on the scale at earlier
closes, so the scale path is causal and has one fixed point. It is found by
rerunning the book on the state machine's scale until the scale stops moving
(two rounds on the headline).
"""

