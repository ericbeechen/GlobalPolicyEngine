def _curve_table(b):
    grid = b.setup.book["costs"]["sensitivity_bp"]
    h = headline(b.setup.book)
    rows = []
    for ch in [Choice(c) for c in order(b.setup.book)] + [Choice(h.construction, sleeves=b.rv)]:
        x, s = b.books[ch], b.summaries[ch]
        for mode in ("uniform", "assumed"):
            if mode == "assumed" and ch != h:
                continue
            vals = sleeves.curve(x.run, grid, mode)
            key = "cstar_bp" if mode == "uniform" else "cstar_assumed_bp"
            rows.append({"book": _name(ch) + (" (headline)" if ch == h else "") +
                         (", only the assumed legs varied" if mode == "assumed" else ""),
                         **{f"{c:g}bp": sr(v) for c, v in zip(grid, vals)},
                         "configured": sr(s["net_sr"], s["net_se"]), "c*": cstar(s[key])})
    return pd.DataFrame(rows)


