def figure(b, path, theme="light"):
    """Left: the book's net equity by construction (and RV only). Right: the headline's net P&L by sleeve."""
    t = _style(theme)
    colors = CATEGORICAL[theme]
    st = b.setup
    capital = st.book["book"]["capital"]
    h = headline(st.book)
    fig, (left, right) = plt.subplots(1, 2, figsize=(12, 4.6), gridspec_kw={"wspace": 0.28})
    books = [Choice(c) for c in order(st.book)] + [Choice(h.construction, sleeves=b.rv)]
    for ch, color in zip(books, colors):
        x = net(b.books[ch]).cumsum() / capital * 100
        name = _name(ch) + (" (headline)" if ch == h else "")
        left.plot(x.index, x, color=color, lw=2.4 if ch == h else 1.6, ls=(0, (4, 2)) if ch.sleeves else "-",
                  label=f"{name} {x.iloc[-1]:+.1f}%")
    left.axhline(0, color=t["axis"], lw=1)
    left.set_ylabel("cumulative net P&L, % of capital", fontsize=8)
    left.legend(fontsize=8, labelcolor=t["secondary"], loc="lower left")
    left.set_title("Net equity by construction", loc="left", fontsize=10, fontweight="bold", color=t["ink"])
    hb = b.books[h]
    k = hb.run.daily["kept"]
    for (n, part), color in zip(hb.parts.items(), colors):
        x = (part["gross"] - part["cost"])[k].cumsum() / capital * 100
        right.plot(x.index, x, color=color, lw=1.8, label=f"{n} {x.iloc[-1]:+.1f}%")
    right.axhline(0, color=t["axis"], lw=1)
    right.legend(fontsize=8, labelcolor=t["secondary"], loc="lower left", ncols=2)
    right.set_title(f"What carries it: the headline's net P&L by sleeve, % of capital", loc="left", fontsize=10,
                    fontweight="bold", color=t["ink"])
    for ax in (left, right):
        ax.tick_params(labelsize=8, length=0)
        ax.xaxis.set_major_locator(mdates.YearLocator(2))
        ax.xaxis.set_major_formatter(mdates.DateFormatter("%Y"))
        ax.margins(x=0.02)
    s = b.summaries[h]
    fig.text(0.125, 1.04, f"The book's net Sharpe is {sr(s['net_sr'])} ({pc(s['return_pct'])} of capital a year) "
             f"at {s['exante_pct']:.1f}% mean ex-ante vol ({st.book['book']['vol_target']:.0%} target); its worst "
             f"drawdown is {s['max_dd_pct']:.0f}% of capital",
             fontsize=12, fontweight="bold", color=t["ink"], va="bottom")
    fig.text(0.125, 1.0, f"Net of costs, counted sessions only (flat stretches: the ELB state), "
             f"{st.spec.words(sizing=False)}, shrunk covariance, no drawdown control.", fontsize=9,
             color=t["secondary"], va="bottom")
    fig.savefig(path, dpi=150, bbox_inches="tight")
    plt.close(fig)


