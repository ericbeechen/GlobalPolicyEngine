def _losing_years(years):
    """'Every year but 2022 and 2023 lost money. ' where most years lost; empty otherwise."""
    good = years.index[years > 0]
    if len(good) > len(years) / 2:
        return ""
    return "Every year lost money. " if not len(good) else f"Every year but {_and(str(y) for y in good)} lost money. "


def _cost_words(b):
    """Costs over the sample, and the sleeve that pays most of them."""
    capital = b.setup.book["book"]["capital"]
    hb = b.books[headline(b.setup.book)]
    k = hb.run.daily["kept"]
    paid = pd.Series({n: p["cost"][k].sum() for n, p in hb.parts.items()})
    top = paid.idxmax()
    return (f"Costs come to {paid.sum() / capital * 100:.1f}% of capital over the sample, {paid[top] / paid.sum():.0%} "
            f"of them {top}'s ({paid[top] / capital * 100:.1f}%).")


def _concentration_words(b):
    """The vol target is the whole book's: where few sleeves have a side, they carry all of it."""
    book = b.setup.book
    capital = book["book"]["capital"]
    hb = b.books[headline(book)]
    vy = vol_by_year(hb, capital)
    vy = vy[vy["with a position"] > 0]
    few = vy.loc[vy["sleeves sized (mean)"].idxmin()]
    y = int(few["year"])
    years = by_year(hb, capital).drop(columns="book")
    top = years.loc[y].abs().idxmax()
    cap = f", the cap binding on {few['cap binds']:.0%} of its sessions" if few["cap binds"] > 0.25 else ""
    return (f"- **The vol target is the whole book's, so the few sleeves with a side carry all of it.** In {y} the "
            f"book sized {few['sleeves sized (mean)']:.1f} sleeves on average, at {few['ex-ante']:.1f}% ex-ante{cap}, "
            f"and netted {pc(few['net'])}, {pc(years.loc[y, top])} of it {top}'s. The sleeves sized average "
            f"{vy['sleeves sized (mean)'].min():.1f} to {vy['sleeves sized (mean)'].max():.1f} a year: the book "
            "diversifies only as far as the sleeves with a side on the day allow.")


def head_words(b):
    """The headline book in words: construction, covariance, target, cap, rules."""
    book = b.setup.book
