# ---- what every book shares --------------------------------------------------------

@dataclass
class Setup:
    """Built once: the sleeves' week 8 inputs, the side each decides, and both on the book calendar.

    `side` is {name: the rule's side at each of the sleeve's closes} under the
    book's spec (rule, pair, ELB treatment, carry filter); `g` and `z` are the
    side and z as of each book close; `units` the unit P&L credited to each
    book session (`portfolio.unit_pnl`).
    """
    book: dict
    days: pd.DatetimeIndex
    inputs: dict
    side: dict
    g: pd.DataFrame
    z: pd.DataFrame
    units: pd.DataFrame
    spec: sleeves.Spec


def setup(world=None):
    """The `Setup` from `world` (the real one by default)."""
    world = expression.World() if world is None else world
    book = world.book
    built = expression.build(world)
    inp = {n: sleeves.inputs(s, world, book) for n, s in built.items()}
    return from_inputs(book, sleeves._book_days(world, book), inp)


def from_inputs(book, days, inp):
    """The `Setup` from the sleeves' week 8 `Inputs` ({name: Inputs}) on the book calendar `days`.

    A signal variant (week 9's robustness) replaces each sleeve's component
    (and, where the model moves it, its ELB state) in `inp` and calls this: the
    unit P&L, and so the covariance (`risk_of`), are the baseline's.
    """
    spec = sleeves.chosen(book)
    side = {n: positions.decide(i.sleeve.component["z"], spec.rule, spec.enter, spec.exit, i.state, spec.treatment,
                                i.allow if spec.carry_filter else None) for n, i in inp.items()}
    g = pd.DataFrame({n: portfolio.asof(s, days) for n, s in side.items()}).fillna(0.0)
    z = pd.DataFrame({n: portfolio.asof(i.sleeve.component["z"], days) for n, i in inp.items()})
    units = portfolio.unit_pnl({n: i.u.groupby("session")["total"].sum(min_count=1).reindex(i.sleeve.sessions)
                                for n, i in inp.items()}, days)
    return Setup(book, days, inp, side, g, z, units, spec)


@dataclass
class Risk:
    """One set of sleeves' covariance (`risk.ewma_cov` on their unit P&L), and where their book may first decide.

    `first` is the first book session with ``portfolio.min_history`` complete
    rows of the sleeves' unit P&L before it; `floored` is {shrink: (sd,
    matrices)}, `portfolio.floored`.
    """
    names: list
    cov: risk.Cov
    first: int
    floored: dict


def risk_of(st, names):
    """The `Risk` of sleeves `names` in `st`."""
    r = st.book["risk"]
    cov = risk.ewma_cov(st.units[names], r["ewma_lambda"], r["nonsynchronous_lag"])
    enough = np.flatnonzero(cov.observations >= st.book["portfolio"]["min_history"])
    if not len(enough):
        raise RuntimeError(f"{names}: fewer than portfolio.min_history sessions of unit P&L")
    return Risk(names, cov, int(enough[0]), {k: portfolio.floored(cov, k, r["sigma_floor"]) for k in (True, False)})


# ---- one book ----------------------------------------------------------------------

@dataclass(frozen=True)
class Choice:
    """One book: its construction, sleeves (None: all), shrinkage, the drawdown overlay, and whether the
    construction reads the covariance's correlations (False: its diagonal only, so mean-variance is |z|-weighted
    inverse-vol, the split of mean-variance's difference from inverse-vol into its two channels)."""
    construction: str
    sleeves: tuple | None = None
    shrink: bool = True
    overlay: bool = False
    correlations: bool = True

    def words(self):
        out = [WORDS[self.construction], "shrunk" if self.shrink else "unshrunk"]
        out += [] if self.correlations else ["no correlations"]
        return ", ".join(out + (["drawdown control"] if self.overlay else []))


@dataclass
class Book:
    """One book run: its `Targets`, the positions decided, the overlay's scale, and what it earned.

    `run` is a `report.costs.Run` on the book calendar (the columns `FLOWS`,
    ``kept`` and ``gross_dv01``, book currency), so week 8's `stats` and
    `curve` read it. `parts` is {sleeve: its flows on the book calendar};
    `net_dv01` the book DV01 on after each close, by currency; `credits` the
    sleeve sessions credited to each book session; `episodes` the sessions the
    overlay triggered on.
    """
    choice: Choice
    targets: portfolio.Targets
    decided: pd.DataFrame
    scale: pd.Series
    episodes: list
    run: sleeves.Run
    parts: dict
    net_dv01: pd.DataFrame
    credits: pd.DataFrame
    rounds: int


def limit(book):
    """The gross DV01 cap in book currency per bp (``risk.max_gross_dv01_per_capital`` x capital), or None."""
    x = book["risk"]["max_gross_dv01_per_capital"]
    return None if x is None else x * book["book"]["capital"]


def _legs(st, names):
    return [len(st.inputs[n].sleeve.legs) for n in names]


def target_of(st, rk, choice):
    """The construction's `portfolio.Targets` for `choice` on the sleeves of `rk`."""
    book = st.book
    sd, m = rk.floored[choice.shrink]
    if not choice.correlations:
        m = np.where(np.eye(m.shape[1], dtype=bool)[None], m, 0.0)
    target = book["book"]["vol_target"] * book["book"]["capital"]
    return portfolio.targets(choice.construction, st.g[rk.names], st.z[rk.names], sd, m, _legs(st, rk.names),
                             SESSIONS_PER_YEAR, target, limit(book), rk.first, book["portfolio"]["z_cap"])


def _sleeve(st, name, decided, start):
    """One sleeve's flows by its own session, the book's decisions executed on its calendar, and its levels.

    The position decided at a book close reaches the sleeve at its next own
    session and executes ``lag`` of its sessions later (`expression.run`); a
    close's trade is split by cause: its own side moved (``signal``), another
    sleeve's side moved (``resize``), neither (``rescale``: the covariance, the
    vol target, the cap or the overlay), and maintenance (`costs.traded`).
    """
    i = st.inputs[name]
    s, treatment = i.sleeve, st.spec.treatment
    days = s.sessions
    q = portfolio.asof(decided[name], days).fillna(0.0)
    side = portfolio.asof(st.g[name], days).fillna(0.0)
    others = pd.DataFrame({n: portfolio.asof(st.g[n], days) for n in decided.columns if n != name}, index=days)
    moved = (others.fillna(0.0).diff().fillna(0.0) != 0).any(axis=1).shift(s.lag, fill_value=False).to_numpy()
    legs, sessions = expression.run(s, q, i.u)
    trades = costs.traded(s, legs, side, i.costs)
    per_leg = costs.by_leg(trades)
    rates = costs.configured(i.costs)
    observed = [c.leg for c in i.costs if c.observed]
    rescale = trades["rescale"].sum(axis=1)
    kept, pnl, paid, _ = positions.samples(i.state, treatment, s.lag)
    daily = pd.DataFrame({
        "gross": sessions["pnl"], "cost": costs.charge(trades, rates), "traded": per_leg.sum(axis=1),
        "assumed": per_leg.drop(columns=observed).sum(axis=1),
        "observed_cost": sum((per_leg[leg] * rates[leg] for leg in observed), pd.Series(0.0, index=days)),
        "signal": trades["signal"].sum(axis=1), "resize": rescale.where(moved, 0.0),
        "rescale": rescale.where(~moved, 0.0), "roll": trades["roll"].sum(axis=1),
        "restrike": trades["restrike"].sum(axis=1)}, index=days)
    daily["gross"] = daily["gross"].where(pnl, 0.0)
    daily[FLOWS[1:]] = daily[FLOWS[1:]].where(paid, 0.0, axis=0)
    ccy = {label: leg.ccy for label, _, leg in s.legs}
    on = legs.pivot(index="session", columns="leg", values="q").reindex(days).fillna(0.0)
    held = (sessions["position"].fillna(0.0).abs() * len(s.legs)).where(pnl, 0.0)
    return daily, (kept & (days >= start)), on.T.groupby(ccy).sum().T, held


def simulate(st, rk, choice, tg, scale):
    """The book for `choice` with the targets `tg` scaled by `scale` at each close: a `Book` (no overlay rounds)."""
    book, days = st.book, st.days
    names = rk.names
    legs = _legs(st, names)
    decided = portfolio.band(tg.q.mul(scale, axis=0), book["risk"]["no_trade_band"], legs, limit(book))
    lag = max(st.inputs[n].sleeve.lag for n in names)
    start = days[min(rk.first + lag + 1, len(days) - 1)]
    parts, kept, dv01, held = {}, [], [], []
    for n in names:
        daily, k, on, h = _sleeve(st, n, decided, start)
        parts[n] = portfolio.to_book(daily, days)
        kept.append(portfolio.to_book(k.astype(int), days) > 0)
        dv01.append(pd.DataFrame({c: portfolio.asof(on[c], days) for c in on}).fillna(0.0))
        held.append(portfolio.asof(h, days).fillna(0.0))
    daily = sum(parts.values())
    daily["kept"] = pd.concat(kept, axis=1).any(axis=1) & (days >= start)
    daily["gross_dv01"] = sum(held)
    net = pd.concat(dv01, axis=1).T.groupby(level=0).sum().T
    credited = pd.DataFrame({n: portfolio.credits(st.inputs[n].sleeve.sessions, days) for n in names})
    run = sleeves.Run(choice.words(), None, daily, start, metrics.per_year(days[days >= start]))
    return Book(choice, tg, decided, scale, [], run, parts, net, credited, 1)


def run_book(st, rk, choice, tg=None):
    """One `Book`. With the overlay, the scale is the fixed point of the drawdown state machine on the book's equity.

    The state at a close reads the equity before it, and that equity only the
    scale at earlier closes, so the scale path is causal and its fixed point
    unique: start from 1 everywhere, rerun on the state machine's scale until it
    no longer moves (each round settles at least the first session it changed).
    """
    tg = target_of(st, rk, choice) if tg is None else tg
    ones = pd.Series(1.0, index=st.days)
    b = simulate(st, rk, choice, tg, ones)
    if not choice.overlay:
        return b
    dd = st.book["portfolio"]["drawdown"]
    cap = st.book["book"]["capital"]
    for rounds in range(1, portfolio.OVERLAY_ROUNDS + 1):
        scale, starts = portfolio.overlay(equity(b), cap, dd["trigger"], dd["release"], dd["scale"])
        if np.array_equal(scale.to_numpy(), b.scale.to_numpy()):
            return replace(b, episodes=starts, rounds=rounds)
        b = simulate(st, rk, choice, tg, scale)
    raise RuntimeError(f"the drawdown overlay did not settle in {portfolio.OVERLAY_ROUNDS} rounds")


def equity(b):
    """The book's net equity on the book calendar (book currency): cumulative gross less costs."""
    d = b.run.daily
    return (d["gross"] - d["cost"]).cumsum()


def never_released(b):
    """True when the overlay triggered and its scale stayed below 1 from the first trigger to the last session."""
    if not b.episodes:
        return False
    return bool((b.scale[b.scale.index >= b.episodes[0]] < 1).all())


# ---- the statistics ----------------------------------------------------------------

def kept(b):
    """The book's counted sessions: its daily frame there."""
    return b.run.daily[b.run.daily["kept"]]


def net(b):
    """Net P&L on the counted sessions, book currency."""
    d = kept(b)
    return d["gross"] - d["cost"]


def block_vol(x, periods, h=BLOCK):
    """Realized vol a year from the sums of `x` over consecutive non-overlapping `h`-session blocks (the last,
    incomplete one dropped): sd of the sums x sqrt(periods / h). NaN with fewer than two blocks."""
    k = len(x) // h
    if k < 2:
        return np.nan
    sums = np.asarray(x, dtype=float)[:k * h].reshape(k, h).sum(axis=1)
    return float(sums.std(ddof=1) * np.sqrt(periods / h))


def difference(a, b):
    """Book `a`'s net Sharpe less book `b`'s over the sessions both count, and the SE of that difference.

    Two books over the same sessions share most of their positions, so their
    difference is far less noisy than either Sharpe, and is judged against its
    own SE, not a single book's. Jobson and Korkie's SE with Memmel's (2003)
    correction, iid as `metrics.sharpe_se`: with s_a, s_b the per-session
    Sharpes, rho the correlation of the two daily net P&Ls and n the sessions,
    var = (2 (1 - rho) + (s_a^2 + s_b^2 - 2 s_a s_b rho^2) / 2) / n, annualised by
    the calendar's sessions a year. Where the two books have the same vol it is
    `strategy/robustness.paired_se` to first order (sd(x - x0)^2 / sd(x0)^2 =
    2 (1 - rho) there); unlike it, it is scale-free, so a book at half size (the
    drawdown control) is compared on its Sharpe, not its size.
    """
    ka, kb = a.run.daily["kept"], b.run.daily["kept"].reindex(a.run.daily.index, fill_value=False)
    both = ka & kb
    x = (a.run.daily["gross"] - a.run.daily["cost"])[both]
    y = (b.run.daily["gross"] - b.run.daily["cost"]).reindex(x.index)
    n, per = len(x), a.run.periods
    sx, sy = x.std(ddof=1), y.std(ddof=1)
    if n < 3 or not (sx > 0 and sy > 0):
        return {"diff": np.nan, "se": np.nan, "rho": np.nan, "sessions": n}
    s1, s2 = x.mean() / sx, y.mean() / sy
    rho = float(np.corrcoef(x, y)[0, 1])
    var = (2.0 * (1.0 - rho) + (s1 ** 2 + s2 ** 2 - 2.0 * s1 * s2 * rho ** 2) / 2.0) / n
    return {"diff": float((s1 - s2) * np.sqrt(per)), "se": float(np.sqrt(max(var, 0.0) * per)), "rho": rho,
            "sessions": n}


def window_words(lo, hi):
    """"2022" for a calendar year, "Dec 2021 to Aug 2023" otherwise."""
    if (lo.month, lo.day, hi.month, hi.day) == (1, 1, 12, 31) and lo.year == hi.year:
        return str(lo.year)
    return f"{lo:%b %Y} to {hi:%b %Y}"


def without(b, windows, capital):
    """Each window of `windows` (``evaluation.exclude``, {name: [first, last]}) that holds counted sessions, on the
    book's counted net P&L, the positions not re-run: the net inside and outside it (% of capital, the book and
    each sleeve), the Sharpe with its sessions left out, and the second half's (week 8's `stats` split) likewise."""
    k = b.run.daily["kept"]
    x = net(b)
    per = b.run.periods
    half = len(x) // 2
    out = []
    for name, (lo, hi) in windows.items():
        lo, hi = pd.Timestamp(lo), pd.Timestamp(hi)
        inside = (x.index >= lo) & (x.index <= hi)
        if not inside.any():
            continue
        rest, late = x[~inside], x.iloc[half:][~inside[half:]]
        (sr_, se), (sr2, se2) = sleeves._sharpe(rest, per), sleeves._sharpe(late, per)
        parts = {n: (p["gross"] - p["cost"])[k] for n, p in b.parts.items()}
        out.append({"name": name, "first": lo, "last": hi, "words": window_words(lo, hi),
                    "sessions": int(inside.sum()), "inside_pct": x[inside].sum() / capital * 100,
                    "outside_pct": x[~inside].sum() / capital * 100, "net_sr": sr_, "net_se": se,
                    "second_sr": sr2, "second_se": se2, "second_sessions": len(late),
                    "sleeves_inside_pct": {n: p[inside].sum() / capital * 100 for n, p in parts.items()}})
    return out


def summary(b, capital):
    """Everything the tables print for one book: week 8's `stats` and the book's own numbers, % of capital a year."""
    s = sleeves.stats(b.run)
    d = kept(b)
    x = net(b)
    per = b.run.periods
    active = d["gross_dv01"] > 0
    traded = d["traded"].sum()
    tg = b.targets
    on = tg.exante.reindex(d.index) > 0
    return s | {
        "return_pct": s["net_year"] / capital * 100, "gross_pct": s["gross_year"] / capital * 100,
        "cost_pct": s["cost_year"] / capital * 100,
        "vol_pct": float(x.std() * np.sqrt(per) / capital * 100),
        "active_vol_pct": float(x[active].std() * np.sqrt(per) / capital * 100),
        "active_vol_block_pct": block_vol(x[active], per) / capital * 100,
        "exante_pct": float(tg.exante.reindex(d.index)[on].mean() / capital * 100),
        "max_dd_pct": float(portfolio.drawdown(x.cumsum(), capital).max() * 100),
        "first_counted": d.index.min(),
        "shares": {c: d[c].sum() / traded if traded > 0 else np.nan for c in CAUSES},
        "capped": float(tg.capped.reindex(d.index)[on].mean()),
        "flipped": float(tg.flipped.reindex(d.index).to_numpy()[(tg.q.reindex(d.index) != 0).to_numpy()].mean()),
        "episodes": [f"{e:%Y-%m-%d}" for e in b.episodes], "halved": float((b.scale.reindex(d.index) < 1).mean()),
        "rounds": b.rounds,
    }


def by_year(b, capital):
    """Net P&L by year on the counted sessions, % of capital: the book and each sleeve."""
    d = b.run.daily["kept"]
    years = {n: (p["gross"] - p["cost"])[d].groupby(p.index[d].year).sum() / capital * 100 for n, p in b.parts.items()}
    out = pd.DataFrame(years)
    return out.assign(book=out.sum(axis=1))


def vol_by_year(b, capital):
    """By year: sessions counted and with a position, ex-ante and realized vol (% of capital, on those with a
    position; realized from daily P&L and from its `BLOCK`-session sums), the share of them the cap binds on, and
    net P&L."""
    d = kept(b)
    x = d["gross"] - d["cost"]
    active = d["gross_dv01"] > 0
    ex = b.targets.exante.reindex(d.index)
    rows = []
    for y, idx in d.groupby(d.index.year).groups.items():
        a = active[idx]
        on = a[a].index
        rows.append({"year": y, "sessions": len(idx), "with a position": int(a.sum()),
                     "sleeves sized (mean)": (b.targets.q.reindex(on) != 0).sum(axis=1).mean() if len(on) else 0.0,
                     "ex-ante": ex[on].mean() / capital * 100 if len(on) else np.nan,
                     "realized": x[on].std() * np.sqrt(b.run.periods) / capital * 100 if len(on) > 1 else np.nan,
                     "realized, block sums": block_vol(x[on], b.run.periods) / capital * 100,
                     "cap binds": b.targets.capped.reindex(on).mean() if len(on) else np.nan,
                     "net": x[idx].sum() / capital * 100})
    return pd.DataFrame(rows)


def dv01_by_year(b):
    """By year, the headline's mean net DV01 by currency and mean |net| summed over currencies against the mean
    gross, book currency per bp, over the counted sessions with a position."""
    d = kept(b)
    on = d.index[d["gross_dv01"] > 0]
    n = b.net_dv01.reindex(on)
    out = n.groupby(on.year).mean()
    out["|net|"] = n.abs().sum(axis=1).groupby(on.year).mean()
    out["gross"] = d.loc[on, "gross_dv01"].groupby(on.year).mean()
    return out


def cov_by_year(rk, first):
    """By year from the book's first decision: delta (mean, min, max), and the correlation matrix's condition
    number unshrunk and shrunk (median, max)."""
    c = rk.cov
    ok = np.arange(len(c.index)) >= first
    days = c.index[ok]
    cs, cu = risk.condition(c.shrunk[ok]), risk.condition(c.s[ok])
    frame = pd.DataFrame({"delta": c.delta[ok], "shrunk": cs, "unshrunk": cu}, index=days)
    g = frame.groupby(days.year)
    return pd.DataFrame({"delta mean": g["delta"].mean(), "delta min": g["delta"].min(),
                         "delta max": g["delta"].max(), "condition unshrunk (median)": g["unshrunk"].median(),
                         "condition unshrunk (max)": g["unshrunk"].max(), "condition shrunk (median)": g["shrunk"].median(),
                         "condition shrunk (max)": g["shrunk"].max()})


def mean_correlations(rk, first, which="s"):
    """The mean over sessions (from the book's first decision) of the correlation matrix of `which` (s0, s, shrunk)."""
    m = getattr(rk.cov, which)[first:]
    return pd.DataFrame(np.nanmean(risk.correlation(m), axis=0), index=rk.names, columns=rk.names)


def stale(b):
    """Per sleeve, from the book's start: book sessions credited nothing (stale) and credited two or more (catch-up)."""
    c = b.credits[b.credits.index >= b.run.start]
    return pd.DataFrame({"stale": (c == 0).sum(), "catch-up": (c > 1).sum()})


def lag_effect(rk, first):
    """The non-synchronous term in numbers, from the book's first decision.

    Each sleeve's lag-1 autocorrelation (the lag term's diagonal over S0's,
    mean and lowest) and what the term does to its inverse-vol size,
    sqrt(S0_ii / S_ii) = 1 / sqrt(1 + rho) (mean and highest); the sessions
    on which the unweighted form, s0 + s1 + s1', is not positive definite, has
    a variance at or below zero (in all and by sleeve), and is not positive
    definite with each sleeve dropped in turn.
    """
    c = rk.cov
    s0 = c.s0[first:]
    s1 = (c.s[first:] - s0)                       # the Bartlett-weighted lag term, (s1 + s1') / 2
    d0 = np.diagonal(s0, axis1=1, axis2=2)
    rho = np.diagonal(s1, axis1=1, axis2=2) / d0
    size = np.sqrt(d0 / np.diagonal(c.s[first:], axis1=1, axis2=2))
    full = s0 + 2.0 * s1
    ok = ~np.isnan(full).any(axis=(1, 2))
    full = full[ok]
    bad = int((np.linalg.eigvalsh(full)[:, 0] <= 0).sum())
    low = np.diagonal(full, axis1=1, axis2=2) <= 0
    drop = {}
    for i, n in enumerate(rk.names):
        keep = [j for j in range(len(rk.names)) if j != i]
        drop[n] = int((np.linalg.eigvalsh(full[:, keep][:, :, keep])[:, 0] <= 0).sum()) if keep else 0
    return {"rho": dict(zip(rk.names, np.nanmean(rho, axis=0))), "rho_min": dict(zip(rk.names, np.nanmin(rho, axis=0))),
            "size": dict(zip(rk.names, np.nanmean(size, axis=0))), "size_max": dict(zip(rk.names, np.nanmax(size, axis=0))),
            "sessions": int(ok.sum()), "not_pd": bad, "negative_variance": int(low.any(axis=1).sum()),
            "negative_by_sleeve": dict(zip(rk.names, low.sum(axis=0).astype(int).tolist())), "not_pd_without": drop,
            "bartlett_not_pd": int((np.linalg.eigvalsh(c.s[first:][ok])[:, 0] <= 0).sum())}


# ---- the build ---------------------------------------------------------------------

def headline(book):
    """The headline book: the configured construction (proposed), shrunk, every sleeve, no overlay."""
    return Choice(book["portfolio"]["headline"])


def order(book):
    """The constructions, the headline first."""
    h = book["portfolio"]["headline"]
    return [h, *[c for c in book["portfolio"]["constructions"] if c != h]]


@dataclass
class Build:
    """Everything the report says.

    `books` is {Choice: Book}: every construction shrunk and unshrunk, with and
    without the overlay (shrunk), mean-variance on the covariance's diagonal
    (no correlations), and the RV-only headline; `summaries` their `summary`;
    `uncapped` the `summary` of `free`, the headline with the gross DV01 cap
    off; `week8` the week 8 equal-risk sums' `stats` ({sizing: stats}); `rv`
    the RV sleeves.
    """
    setup: Setup
    risks: dict
    books: dict
    summaries: dict
    uncapped: dict
    week8: dict
    rv: tuple
    free: Book | None = None


DIAGONAL = Choice("mean_variance", correlations=False)      # |z|-weighted inverse-vol: mean-variance's |z| channel


def choices(book, rv):
    """Every book the report runs (`Build.books`)."""
    out = []
    for c in order(book):
        out += [Choice(c), Choice(c, shrink=False), Choice(c, overlay=True)]
    out += [DIAGONAL] if DIAGONAL.construction in book["portfolio"]["constructions"] else []
    h = book["portfolio"]["headline"]
    return out + [Choice(h, sleeves=rv), Choice(h, sleeves=rv, overlay=True)]


def build(world=None):
    """Every book the report reads, from `world`'s sleeves (week 8's inputs, built once)."""
    world = expression.World() if world is None else world
    st = setup(world)
    book, capital = st.book, st.book["book"]["capital"]
    names = list(st.inputs)
    rv = tuple(n for n in names if st.inputs[n].sleeve.kind in RV_KINDS)
    risks = {None: risk_of(st, names), rv: risk_of(st, list(rv))}
    made, books = {}, {}
    for ch in choices(book, rv):
        rk = risks[ch.sleeves]
        key = (ch.construction, ch.sleeves, ch.shrink, ch.correlations)
        if key not in made:
            made[key] = target_of(st, rk, ch)
        books[ch] = run_book(st, rk, ch, made[key])
    free = copy_book(book)
    free["risk"]["max_gross_dv01_per_capital"] = None
    loose = replace(st, book=free)
    free_book = run_book(loose, risks[None], headline(book))
    uncapped = summary(free_book, capital)
    week8 = {}
    for sz in positions.SIZING:
        runs = sleeves.run_all(st.inputs, sleeves.chosen(book, sz), book, st.days)
        week8[sz] = sleeves.stats(runs[sleeves.SUM])
    week8["vol_scaled"]["vol_pct"] = sleeves._realized(
        sleeves.run_all(st.inputs, sleeves.chosen(book), book, st.days)[sleeves.SUM], capital)
    b = Build(st, risks, books, {ch: summary(x, capital) for ch, x in books.items()}, uncapped, week8, rv, free_book)
    check(b)
    return b


def copy_book(book):
    """A deep copy of the book config, to vary one key."""
    return json.loads(json.dumps(book))


def check(b, tol=1e-8):
    """Raise if the build's own invariants fail.

    On every book: DV01 traded by cause adds up; nothing is on a session the
    treatment leaves out (flat and exclude); the cap holds on every close; the
    book's P&L is its sleeves'. ERC's risk contributions are equal on every
    session it sizes two or more sleeves, and ERC is inverse-vol where it sizes
    one. A breakeven is its curve's zero. The overlay's scale is its own state
    machine's on the book's equity. Every book on the headline's sleeves counts
    the headline's sessions, so the paired differences between them add up.
    """
    st = b.setup
    cap = limit(st.book)
    base = b.books[headline(st.book)].run.daily["kept"]
    for ch, x in b.books.items():
        d = x.run.daily
        where = ch.words() + ("" if ch.sleeves is None else ", RV only")
        if ch.sleeves is None and not d["kept"].equals(base):
            raise RuntimeError(f"{where}: counts other sessions than the headline, so paired differences do not add up")
        if not np.allclose(d[list(CAUSES)].sum(axis=1), d["traded"], atol=tol):
            raise RuntimeError(f"{where}: DV01 traded by cause does not add up")
        if st.spec.treatment != "hold":
            left = d.loc[~d["kept"] & (d.index >= x.run.start), FLOWS].abs().to_numpy().sum()
            if left > tol:
                raise RuntimeError(f"{where}: {left:g} of P&L or cost on sessions the treatment leaves out")
        if cap is not None:
            legs = np.asarray(_legs(st, list(x.decided.columns)), dtype=float)
            worst = float((x.decided.abs().to_numpy() @ legs).max())
            if worst > cap * (1 + 1e-9):
                raise RuntimeError(f"{where}: gross DV01 {worst:,.0f} over the cap {cap:,.0f}")
        parts = sum(p["gross"] for p in x.parts.values())
        if not np.allclose(parts, d["gross"], atol=tol):
            raise RuntimeError(f"{where}: the book's gross P&L is not its sleeves'")
        s = b.summaries[ch]
        if s["cstar_bp"] is not None and np.isfinite(s["cstar_bp"]) and abs(sleeves.curve(x.run, [s["cstar_bp"]])[0]) > 1e-6:
            raise RuntimeError(f"{where}: the net Sharpe at c* is not 0")
        if ch.overlay:
            dd = st.book["portfolio"]["drawdown"]
            again, _ = portfolio.overlay(equity(x), st.book["book"]["capital"], dd["trigger"], dd["release"], dd["scale"])
            if not np.array_equal(again.to_numpy(), x.scale.to_numpy()):
                raise RuntimeError(f"{where}: the overlay's scale is not its fixed point")
    e, i = b.books[Choice("erc")].targets, b.books[Choice("inverse_vol")].targets
    n = (st.g[e.q.columns] != 0).sum(axis=1)
    sh = e.share[n > 1]
    spread = sh.where(sh > 0).max(axis=1) - sh.where(sh > 0).min(axis=1)
    if spread.max() > 1e-8:
        raise RuntimeError(f"ERC risk contributions differ by {spread.max():.1e}")
    one = n == 1
    rel = ((e.q[one] - i.q[one]).abs().sum(axis=1) / i.q[one].abs().sum(axis=1)).max() if one.any() else 0.0
    if rel > 1e-8:
        raise RuntimeError(f"ERC with one sleeve is not inverse-vol (relative difference {rel:.1e})")


# ---- the words ---------------------------------------------------------------------

sr, cstar, pct = sleeves.sr, sleeves.cstar, sleeves.pct


def pc(x, digits=2):
    """"+1.23%": a signed percent of capital."""
    return "n/a" if pd.isna(x) else f"{x:+.{digits}f}%"


def _verdict(s):
    if not s["net_sr"] > 0:
        return "loses money"
    return "earns, but within two SEs of zero" if s["net_sr"] < 2 * s["net_se"] else "earns"


def gap(d):
    """"-0.15 (paired SE 0.12)": a Sharpe difference and its paired SE (`difference`)."""
    return f"{d['diff']:+.2f} (paired SE {d['se']:.2f})"


def _apart(d, k=1.0):
    """True when a `difference` is at least `k` of its paired SEs."""
    return bool(abs(d["diff"]) >= k * d["se"])


def _constructions_words(b):
    """The constructions bullet: each against the others on the paired SE, and mean-variance's two channels."""
    book = b.setup.book
    h = headline(book)
    hs = b.summaries[h]
    cons = [Choice(c) for c in order(book)]
    others = cons[1:]
    pairs = [(y, x, difference(b.books[y], b.books[x])) for x, y in itertools.combinations(cons, 2)]
    apart = [(x, y) for x, y, d in pairs if _apart(d)]
    far = [(x, y) for x, y, d in pairs if _apart(d, 2.0)]
    title = ("The construction does not change the answer" if not apart else
             "The construction moves the net Sharpe, by less than two paired SEs" if not far else
             "The construction moves the answer")
    both = lambda xy: f"{WORDS[xy[0].construction]} with {WORDS[xy[1].construction]}"
    count = lambda x: "one pair is" if len(x) == 1 else f"{NUMBERS.get(len(x), len(x))} pairs are"
    rhos = [d["rho"] for *_, d in pairs]
    verdict = ("Every pair is within a paired SE of each other." if not apart else
               f"{count(apart).capitalize()} more than a paired SE apart ({_and(both(p) for p in apart)})"
               + ((", not two." if len(apart) == 1 else ", neither by two." if len(apart) == 2 else ", none by two.")
                  if not far else f"; {count(far)} more than two ({_and(both(p) for p in far)})."))
    out = (f"- **{title}.** "
           + _and(f"{WORDS[o.construction]} nets {sr(b.summaries[o]['net_sr'], b.summaries[o]['net_se'])} "
                  f"({sr(b.summaries[o]['gross_sr'])} gross, {b.summaries[o]['turns_year']:.1f} turns a year)"
                  for o in others)
           + f", against the headline's {sr(hs['net_sr'])} ({hs['turns_year']:.1f} turns). The books share most of "
           f"their positions (their daily net P&Ls correlate {min(rhos):.2f} to {max(rhos):.2f}), so a difference is "
           "judged against the SE of the difference on the same sessions, not a single Sharpe's: "
           + _and(f"{WORDS[x.construction]} against {WORDS[y.construction]} {gap(d)}" for x, y, d in pairs)
           + f". {verdict}")
    mv, iv = Choice("mean_variance"), Choice("inverse_vol")
    if DIAGONAL in b.books and mv in b.books and iv in b.books:
        ds, ms, vs = b.summaries[DIAGONAL], b.summaries[mv], b.summaries[iv]
        total, z, corr = (difference(b.books[x], b.books[y]) for x, y in ((mv, iv), (DIAGONAL, iv), (mv, DIAGONAL)))
        out += (f" Mean-variance differs from inverse-vol by its |z| weights and by its correlations. On the diagonal of "
                f"the same Sigma (|z|-weighted inverse-vol) it nets {sr(ds['net_sr'], ds['net_se'])} "
                f"({sr(ds['gross_sr'])} gross, {ds['turns_year']:.1f} turns): of mean-variance's {total['diff']:+.2f} "
                f"against inverse-vol, {gap(z)} is the |z| weights' and {gap(corr)} the correlations'; of its "
                f"{ms['turns_year'] - vs['turns_year']:.1f} extra turns a year, {ds['turns_year'] - vs['turns_year']:.1f} "
                f"are the |z| weights' and {ms['turns_year'] - ds['turns_year']:.1f} the correlations'.")
    return (out + f" Mean-variance puts {pct(b.summaries[mv]['flipped'])} of its active sleeve-sessions on the other "
            "side from their own signal, where the correlations say hedge.") if mv in b.summaries else out


def _carries_words(b):
    """What carries it: the sleeves and the years, and the `evaluation.exclude` window the book earns in, if any."""
    book, capital = b.setup.book, b.setup.book["book"]["capital"]
    hb = b.books[headline(book)]
    years = by_year(hb, capital)
    total = years["book"].sum()
    best = years["book"].idxmax()
    parts = years.drop(columns="book").sum()
    winners = parts[parts > 0]
    ws = without(hb, book["evaluation"]["exclude"], capital)
    win = max(ws, key=lambda w: w["inside_pct"]) if ws else None
    one = win is not None and win["inside_pct"] > 0 >= win["outside_pct"]
    if one:
        title = f"What carries it: {win['words']}"
        where = (f"; the book {pc(total, 1)}, {pc(win['inside_pct'], 1)} of it from {win['words']} and "
                 f"{pc(win['outside_pct'], 1)} outside it")
        sleeve = lambda n, v: (f"{n} {pc(v, 1)} ({pc(win['sleeves_inside_pct'][n], 1)} inside)" if n in winners.index
                               else f"{n} {pc(v, 1)}")
        head = f"Net over the sample, % of capital (for a sleeve that earns, how much of it is from {win['words']}): "
    else:
        title = (f"What carries it: {_and(winners.index) if len(winners) else 'no sleeve'}"
                 f"{', and ' + str(best) if years['book'].max() > 0 else ''}")
        where = f"; the book {pc(total, 1)}"
        sleeve = lambda n, v: f"{n} {pc(v, 1)}"
        head = "Net over the sample, % of capital: "
    return (f"- **{title}.** {head}" + _and(sleeve(n, v) for n, v in parts.sort_values(ascending=False).items())
            + f"{where}. Its best year, {best}, made {pc(years['book'].max(), 1)}; the other {len(years) - 1} years "
            f"{pc(total - years['book'].max(), 1)}. {_losing_years(years['book'])}" + _cost_words(b))


def _halves_words(b):
    """The halves bullet: the two halves against the SE of their difference, and each exclude window left out."""
    book, capital = b.setup.book, b.setup.book["book"]["capital"]
    h = headline(book)
    hs = b.summaries[h]
    halves = hs["halves"]
    d = halves["second_sr"] - halves["first_sr"]
    se = float(np.hypot(halves["first_se"], halves["second_se"]))
    apart = abs(d) > se
    out = (f"- **The two halves {'disagree' if apart else 'agree within an SE'}.** To {halves['split']:%b %Y} the "
           f"headline nets {sr(halves['first_sr'], halves['first_se'])}, after it "
           f"{sr(halves['second_sr'], halves['second_se'])}: a difference of {d:+.2f}, against an SE of {se:.2f} for "
           "two independent halves.")
    n = hs["sessions"]
    ws = [w for w in without(b.books[h], book["evaluation"]["exclude"], capital) if w["second_sessions"] < n - n // 2]
    if not ws:
        return out
    out += (" With each `evaluation.exclude` window's P&L left out (the positions not re-run): "
            + "; ".join(f"without {w['words']} the headline nets {sr(w['net_sr'], w['net_se'])} and its second half "
                        f"{sr(w['second_sr'], w['second_se'])}" for w in ws) + ".")
    w = min(ws, key=lambda w: w["second_sr"])
    if abs(halves["second_sr"]) < halves["second_se"] and w["second_sr"] < -w["second_se"]:
        out += (f" The second half is near zero only with {w['words']} in it: without it, it loses more than an SE "
                f"over {w['second_sessions']:,} sessions.")
    return out


def _vol_words(b):
    """Realized against ex-ante vol: daily and from `BLOCK`-session sums, what the gap is consistent with, and the
    years the cap holds ex-ante under the target."""
    book, capital = b.setup.book, b.setup.book["book"]["capital"]
    h = headline(book)
    hs = b.summaries[h]
    vy = vol_by_year(b.books[h], capital)
    over = vy[vy["realized"] > vy["ex-ante"]]
    above = hs["active_vol_pct"] > hs["exante_pct"]
    blk = hs["active_vol_block_pct"]
    lam = book["risk"]["ewma_lambda"]
    out = (f"- **Realized vol runs {'above' if above else 'below'} ex-ante.** {hs['active_vol_pct']:.1f}% realized on "
           f"the sessions with a position against {hs['exante_pct']:.1f}% ex-ante, higher in {len(over)} of {len(vy)} "
           f"years; from non-overlapping {BLOCK}-session sums it is {blk:.1f}%"
           + (", so the daily figure understates the miss." if above and blk > hs["active_vol_pct"] else "."))
    if above:
        out += (f" The gap is consistent with the EWMA lagging a rise in vol (its weights' mean age is "
                f"{1 / (1 - lam):.0f} sessions), with the noise of a {b.risks[None].cov.n_eff[-1]:.0f}-session "
                "effective sample, which alone pushes realized above ex-ante, and with fat tails; the report does not "
                "separate them.")
    return out + f" Ex-ante is under the {book['book']['vol_target']:.0%} target where the cap binds: {_cap_years(vy)}."


