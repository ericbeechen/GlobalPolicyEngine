# ---- the headline, split -----------------------------------------------------------

def outrights(st):
    """{ccy: the outright sleeve's name} in `st` (a `report.portfolio.Setup`)."""
    return {i.sleeve.ccys[0]: n for n, i in st.inputs.items() if i.sleeve.kind == "outright"}


def unit_total(i, part="total"):
    """A sleeve's unit P&L component (`part`) by its own session, bp: its legs summed."""
    return i.u.groupby("session")[part].sum(min_count=1).reindex(i.sleeve.sessions)


def betas(st):
    """{sleeve: (betas {outright name: beta}, R^2, sessions)}: each sleeve's unit P&L on its currencies' outrights.

    An outright is its own level (beta 1, R^2 1); the others are
    `metrics.factor` from the sleeve's first counted session.
    """
    out, level = {}, outrights(st)
    for n, i in st.inputs.items():
        on = [level[c] for c in i.sleeve.ccys if c in level]
        if n in on:
            out[n] = ({n: 1.0}, 1.0, int(unit_total(i).loc[i.start:].notna().sum()))
            continue
        xs = pd.DataFrame({o: unit_total(st.inputs[o]).reindex(i.sleeve.sessions) for o in on})
        out[n] = metrics.factor(unit_total(i).loc[i.start:], xs.loc[i.start:])
    return out


def split(st, b, fits):
    """{sleeve: its flows in book `b` on the book calendar}: gross, cost, traded, carry, roll, rate, level, held
    (signed first-leg DV01 held), gross_dv01 and kept (the book's). `fits` is `betas`."""
    level = outrights(st)
    days, kept = st.days, b.run.daily["kept"]
    out = {}
    for n, i in st.inputs.items():
        s = i.sleeve
        q = portfolio.asof(b.decided[n], s.sessions).fillna(0.0)
        _, sessions = expression.run(s, q, i.u)
        _, pnl, _, _ = positions.samples(i.state, st.spec.treatment, s.lag)
        held = sessions["position"].fillna(0.0).where(pnl, 0.0)
        coef = fits[n][0]
        x = sum(unit_total(st.inputs[o]).reindex(s.sessions) * beta for o, beta in coef.items())
        own = sessions[["carry", "roll", "rate"]].where(pnl, 0.0, axis=0)
        own["level"] = (held * x).fillna(0.0) if n not in level.values() else sessions["pnl"].where(pnl, 0.0)
        f = portfolio.to_book(own, days)
        part = b.parts[n]
        f["gross"], f["cost"], f["traded"] = part["gross"], part["cost"], part["traded"]
        f["held"] = portfolio.asof(held, days).fillna(0.0)
        f["gross_dv01"] = f["held"].abs() * len(s.legs)
        f["kept"] = kept
        out[n] = f
    return out


def contribution(f, periods):
    """One part's `metrics.Result` in the book (its flows, the book's counted sessions)."""
    return metrics.Result(f, periods)


def group_of(st):
    """{sleeve: its component group}: level, slope, cross-country."""
    return {n: GROUPS[i.sleeve.kind] for n, i in st.inputs.items()}


def _sum(parts, names, cols):
    return sum(parts[n][cols] for n in names)


def components(st, b, parts, capital):
    """Per component group and the book: net, gross, cost, carry and roll, rate, % of capital a year; the share of
    the book's net P&L variance (cov(part, book) / var(book)); the Sharpe of the group's net contribution."""
    k = b.run.daily["kept"]
    per = b.run.periods
    years = k.sum() / per
    book_net = (b.run.daily["gross"] - b.run.daily["cost"])[k]
    groups = group_of(st)
    rows = []
    for g in [*dict.fromkeys(groups.values()), "book"]:
        names = [n for n, x in groups.items() if g in (x, "book")]
        f = _sum(parts, names, ["gross", "cost", "carry", "roll", "rate", "level"])[k]
        net = f["gross"] - f["cost"]
        sr = metrics.sharpe(net, per)
        rows.append({"group": g, "sleeves": names, "net": net.sum() / years / capital * 100,
                     "gross": f["gross"].sum() / years / capital * 100, "cost": f["cost"].sum() / years / capital * 100,
                     "carry_roll": (f["carry"] + f["roll"]).sum() / years / capital * 100,
                     "rate": f["rate"].sum() / years / capital * 100,
                     "variance_share": float(np.cov(net, book_net)[0, 1] / book_net.var()),
                     "net_sr": sr, "net_se": metrics.sharpe_se(sr, years)})
    return rows


def level_view(st, b, parts, fits, capital):
    """The level-factor view: per sleeve its betas, R^2, and gross P&L split into level and the rest (% of capital a
    year); for the book the same split and the level part's share of the gross P&L variance."""
    k = b.run.daily["kept"]
    years = k.sum() / b.run.periods
    rows = []
    for n, f in parts.items():
        coef, r2, obs = fits[n]
        g, lv = f.loc[k, "gross"], f.loc[k, "level"]
        rows.append({"sleeve": n, "betas": coef, "r2": r2, "sessions": obs,
                     "level": lv.sum() / years / capital * 100, "rest": (g - lv).sum() / years / capital * 100})
    g = b.run.daily.loc[k, "gross"]
    lv = sum(f.loc[k, "level"] for f in parts.values())
    share = float(np.cov(lv, g)[0, 1] / g.var())
    return rows, {"level": lv.sum() / years / capital * 100, "rest": (g - lv).sum() / years / capital * 100,
                  "gross": g.sum() / years / capital * 100, "variance_share": share,
                  "corr": float(np.corrcoef(lv, g)[0, 1]), "dominates": bool(share >= LEVEL_DOMINATES)}


def z_agreement(st):
    """Per currency with an outright and a curve sleeve: corr(level z, slope z) and the share of sessions their signs
    agree, for the traded (orthogonal) slope and the raw 8-minus-1; and the share of book sessions both sleeves hold a
    side on which the sides agree."""
    rows = []
    for c, o in outrights(st).items():
        for n, i in st.inputs.items():
            if i.sleeve.kind != "curve" or i.sleeve.ccys[0] != c:
                continue
            lz, comp = st.inputs[o].sleeve.component["z"], i.sleeve.component
            row = {"ccy": c, "level": o, "slope": n}
            for name, z in (("orthogonal", comp["z"]), ("raw", comp.get("raw_z"))):
                if z is None:
                    continue
                both = pd.concat([lz, z], axis=1).dropna()
                row[name] = {"corr": float(both.corr().iloc[0, 1]),
                             "same_sign": float((np.sign(both.iloc[:, 0]) == np.sign(both.iloc[:, 1])).mean()),
                             "sessions": len(both)}
            g = st.g[[o, n]]
            on = (g != 0).all(axis=1)
            row["sides"] = {"same": float((g[on].iloc[:, 0] == g[on].iloc[:, 1]).mean()) if on.any() else np.nan,
                            "sessions": int(on.sum())}
            rows.append(row)
    return rows


def check(b, parts, tol=TOL):
    """Raise unless the split adds up: carry + roll + rate is each part's gross, and the parts are the book's."""
    for n, f in parts.items():
        off = (f["carry"] + f["roll"] + f["rate"] - f["gross"]).abs().max()
        if off > tol:
            raise RuntimeError(f"{n}: carry + roll + rate is {off:g} off its gross P&L in the book")
    total = sum(f["gross"] for f in parts.values())
    if (total - b.run.daily["gross"]).abs().max() > tol:
        raise RuntimeError("the parts' gross P&L is not the book's")


# ---- the other books: carry benchmark and ELB treatments ---------------------------

def carry_inputs(st, h, min_pairs):
    """The sleeves' `Inputs` with each z replaced by the sign of the receive's carry and roll ahead (CR_h)."""
    out = {}
    for n, i in st.inputs.items():
        a = expression.ahead(i.sleeve, h, min_pairs)
        cr = a["cr_h_bp"] * a["side"]            # the receive's CR_h: ahead signs it for sign(z)
        comp = i.sleeve.component.copy()
        comp["z"] = np.sign(cr).where(cr.notna() & (cr != 0))
        out[n] = replace(i, sleeve=replace(i.sleeve, component=comp))
    return out


def carry_book(pb):
    """The carry benchmark (module docstring): its `Setup` and headline book, on the headline's covariance."""
    st = pb.setup
    c = st.book["carry"]
    cs = books.from_inputs(st.book, st.days, carry_inputs(st, c["horizon_days"], c["closure_min_pairs"]))
    return cs, books.run_book(cs, pb.risks[None], books.headline(st.book))


def with_treatment(book, treatment):
    """A copy of the book config with ``evaluation.elb.chosen`` = `treatment`."""
    out = books.copy_book(book)
    out["evaluation"]["elb"]["chosen"] = treatment
    return out


def elb_books(pb):
    """{treatment: (Setup, Book)}: the headline under each ELB treatment, the configured one being the headline."""
    st = pb.setup
    h = books.headline(st.book)
    out = {}
    for tr in positions.TREATMENTS:
        if tr == st.spec.treatment:
            out[tr] = (st, pb.books[h])
            continue
        s = books.from_inputs(with_treatment(st.book, tr), st.days, st.inputs)
        out[tr] = (s, books.run_book(s, pb.risks[None], h))
    return out


def elb_split(st, b, capital):
    """One treatment's book against the ELB state, % of capital where P&L.

    On each sleeve session, the position held into it was decided in the state
    where the state shifted lag + 1 is (``line``), and the one put on at its
    close where the state shifted lag is (``put``). The P&L of positions decided
    in the state is the gross on ``line`` sessions less the cost of trades on
    sessions both are; the boundary trades are the trades on sessions exactly
    one is: the close on entering the state and the re-open on leaving it,
    which the flat treatment forces (under hold and exclude they are ordinary
    trades, so the count is the flat treatment's only). Also the net Sharpe on
    every counted session and on those no sleeve holds a position decided in
    the state.
    """
    days = st.days
    d = b.run.daily
    k = d["kept"]
    net = (d["gross"] - d["cost"])
    in_state = pd.Series(0.0, index=days)
    touched = pd.Series(False, index=days)
    closes, reopens, boundary_cost = 0, 0, 0.0
    for n, i in st.inputs.items():
        s = i.sleeve
        daily, _, _, _ = books._sleeve(st, n, b.decided, b.run.start)
        state = i.state.reindex(s.sessions, fill_value=False)
        line = state.shift(s.lag + 1, fill_value=False)
        put = state.shift(s.lag, fill_value=False)
        live = s.sessions >= b.run.start
        held = portfolio.asof(b.decided[n], s.sessions).fillna(0.0).shift(s.lag + 1, fill_value=0.0)
        mine = daily["gross"].where(line, 0.0) - daily["cost"].where(line & put, 0.0)
        in_state += portfolio.to_book(mine, days)
        touched |= portfolio.to_book((line & (held != 0)).astype(int), days) > 0
        if st.spec.treatment == "flat":
            traded = (daily["traded"] > 0) & live
            closes += int((traded & put & ~line).sum())
            reopens += int((traded & line & ~put).sum())
            boundary_cost += float(daily["cost"][traded & (put != line)].sum())
    per = b.run.periods
    out_sr = metrics.sharpe(net[k & ~touched], per)
    ev = metrics.evaluate(b, capital=capital)
    forced = st.spec.treatment == "flat"
    return {"treatment": st.spec.treatment, **ev,
            "state_sessions": int((k & touched).sum()),
            "in_state": float(in_state[k].sum() / capital * 100),
            "outside": float((net[k].sum() - in_state[k].sum()) / capital * 100),
            "outside_sr": out_sr, "outside_se": metrics.sharpe_se(out_sr, (k & ~touched).sum() / per),
            "closes": closes if forced else None, "reopens": reopens if forced else None,
            "boundary_cost": boundary_cost / capital * 100 if forced else None,
            "ex_2022": metrics.ex_2022(b, st.book, capital), "ex_2022_23": metrics.ex_2022_23(b, st.book, capital)}


def elb_episodes(world, book):
    """{ccy: [(first, last, sessions)]}: each currency's runs in the ELB state (`regimes.elb_state`)."""
    out = {}
    for c in dict.fromkeys(c for s in book["sleeves"] for c in ([s["ccy"]] if "ccy" in s else s["pair"])):
        e = regimes.episodes(regimes.elb_state(world.panel(c, "model")))
        e = e[e["state"]]
        out[c] = [(r["first"], r["last"], int(r["sessions"])) for _, r in e.iterrows()]
    return out


# ---- regimes -----------------------------------------------------------------------

def states_on(world, ccys, days):
    """{ccy: its regime (`regimes.states`) on each of `days`: the latest on or before it}."""
    out = {}
    for c in ccys:
        s = regimes.states(world.panel(c, "model")).sort_index()
        at = s.index.searchsorted(days, side="right") - 1
        out[c] = pd.Series(np.where(at >= 0, s.to_numpy()[np.maximum(at, 0)], None), index=days)
    return out


def regime_rows(net, kept, active, entries, state, groups, periods, capital):
    """One row per group of states in `groups` (tuples of `regimes.STATES`, or collapsed names): counted and active
    sessions, trades entered, net P&L (% of capital, and a year), net Sharpe (SE)."""
    rows = []
    for g in groups:
        on = kept & state.isin(g)
        x = net[on]
        n = len(x)
        sr = metrics.sharpe(x, periods) if n > 1 else np.nan
        rows.append({"regime": g, "sessions": n, "active": int((active & on).sum()),
                     "trades": int(entries[on].sum()),
                     "net": x.sum() / capital * 100, "net_year": x.sum() / (n / periods) / capital * 100 if n else np.nan,
                     "net_sr": sr, "net_se": metrics.sharpe_se(sr, n / periods) if pd.notna(sr) else np.nan})
    return rows


def entries_of(f):
    """The trades a part puts on, by book session: 1 at each entry close (`metrics.trades`)."""
    k = f["kept"]
    t = metrics.trades(f.loc[k, "gross"], f.loc[k, "cost"], f.loc[k, "held"])
    return pd.Series(1, index=t.index).reindex(f.index, fill_value=0)


def regime_tables(world, st, b, parts, capital):
    """The regime tables: the book by the book currency's state (every state and the collapsed regimes), each
    sleeve by its own currency's collapsed regime (the cross sleeve by the book currency's), and the book by
    whether the currencies are in the same collapsed regime."""
    home = st.book["book"]["currency"]
    ccys = list(dict.fromkeys([home, *(c for i in st.inputs.values() for c in i.sleeve.ccys)]))
    on = states_on(world, ccys, st.days)
    per = b.run.periods
    d = b.run.daily
    k, net, active = d["kept"], d["gross"] - d["cost"], d["gross_dv01"] > 0
    entries = {n: entries_of(f) for n, f in parts.items()}
    every = sum(entries.values())
    book_rows = regime_rows(net, k, active, every, on[home], REGIME_ROWS, per, capital)
    coll = {c: s.map(COLLAPSED) for c, s in on.items()}
    by_sleeve = {}
    for n, f in parts.items():
        i = st.inputs[n]
        c = i.sleeve.ccys[0] if len(i.sleeve.ccys) == 1 else home
        by_sleeve[n] = {"ccy": c, "rows": regime_rows(f["gross"] - f["cost"], k, f["gross_dv01"] > 0, entries[n],
                                                      coll[c], [(g,) for g in COLLAPSED_ORDER], per, capital)}
    others = [c for c in ccys if c != home]
    pair = None
    if others:
        same = pd.Series(np.where(coll[home] == coll[others[0]], "same", "different"), index=st.days)
        pair = {"pair": [home, others[0]], "rows": regime_rows(net, k, active, every, same, [("same",), ("different",)],
                                                               per, capital)}
    return {"book": book_rows, "book_ccy": home, "sleeves": by_sleeve, "pair": pair}


# ---- the IC ------------------------------------------------------------------------

def ics(st):
    """{sleeve: {part: {sample: `metrics.ic_table` rows}}}: rate and total unit P&L, outside the ELB state and all."""
    hs = st.book["evaluation"]["ic_horizons"]
    out = {}
    for n, i in st.inputs.items():
        z = i.sleeve.component["z"]
        samples = {"ex_elb": z.notna() & ~i.state.reindex(z.index, fill_value=False), "all": z.notna()}
        out[n] = {part: {name: metrics.ic_table(z, unit_total(i, part), hs, i.sleeve.lag, m)
                         for name, m in samples.items()} for part in ("rate", "total")}
    return out


# ---- the current signal ------------------------------------------------------------

def current(st, b):
    """Each sleeve on the book's last session: its session, z, the rule's side, the book DV01 decided (book
    currency per bp), the instruments selected, and for the side z points to the edge, CR_h and E_h (bp)."""
    c = st.book["carry"]
    day = st.days[-1]
    rows = []
    for n, i in st.inputs.items():
        a = expression.ahead(i.sleeve, c["horizon_days"], c["closure_min_pairs"])
        a = a[a.index <= day].dropna(subset=["z"])
        r = a.iloc[-1]
        rows.append({"sleeve": n, "session": a.index[-1], "z": r["z"], "side": float(st.side[n].loc[a.index[-1]]),
                     "dv01": float(b.decided.loc[day, n]), "instrument": r["selected"], "edge_bp": r["edge_bp"],
                     "cr_h_bp": r["cr_h_bp"], "expected_bp": r["expected_bp"]})
    return rows


# ---- the build ---------------------------------------------------------------------

@dataclass
class Build:
    """Everything the report and the tear sheet say (module docstring)."""
    world: object
    portfolio: books.Build
    headline: books.Book
    fits: dict
    parts: dict
    carry: tuple
    elb: dict
    numbers: dict


def build(world=None, log=None):
    """The headline split, the carry benchmark, the ELB books and every table, from `world` (the real one)."""
    world = expression.World() if world is None else world
    say = log or (lambda *_: None)
    pb = books.build(world)
    say("books built")
    st = pb.setup
    book, capital = st.book, st.book["book"]["capital"]
    hb = pb.books[books.headline(book)]
    fits = betas(st)
    parts = split(st, hb, fits)
    check(hb, parts)
    cb = carry_book(pb)
    say("carry benchmark built")
    elb = elb_books(pb)
    say("ELB books built")
    b = Build(world, pb, hb, fits, parts, cb, elb, {})
    b.numbers = numbers(b)
    return b


def performance(b):
    """The performance rows: the book (trades pooled over sleeves), then each sleeve's contribution; `metrics.evaluate`
    on the whole sample, without 2022 and without 2022-23, % of capital."""
    st = b.portfolio.setup
    book, capital = st.book, st.book["book"]["capital"]
    per = b.headline.run.periods
    rows = []
    for name, x in [("book", b.headline), *((n, contribution(f, per)) for n, f in b.parts.items())]:
        ev = metrics.evaluate(x, capital=capital)
        if name == "book":
            k = b.headline.run.daily["kept"]
            t = pd.concat([metrics.trades(f.loc[k, "gross"], f.loc[k, "cost"], f.loc[k, "held"])
                           for f in b.parts.values()])
            ev |= {"trades": len(t), "hit_trade": float((t > 0).mean()) if len(t) else np.nan}
            ev |= {"cstar_bp": sleeves.stats(b.headline.run)["cstar_bp"]}
        rows.append({"name": name, **ev, "ex_2022": metrics.ex_2022(x, book, capital),
                     "ex_2022_23": metrics.ex_2022_23(x, book, capital)})
    return rows


def cost_curve(b):
    """The headline's net Sharpe against a uniform round trip (and the assumed legs only), its c* and cost mix."""
    run = b.headline.run
    s = sleeves.stats(run)
    c = s["cstar_bp"]
    top = max(sleeves.MIN_X_BP, sleeves.PAST_BREAKEVEN * c) if c is not None and np.isfinite(c) else sleeves.MIN_X_BP
    xs = np.linspace(0.0, top, sleeves.STEPS)
    return {"round_trip_bp": xs, "net_sr": sleeves.curve(run, xs), "assumed_net_sr": sleeves.curve(run, xs, "assumed"),
            "cstar_bp": c, "mix_bp": s["mix_bp"], "net_sr_at_mix": float(sleeves.curve(run, [s["mix_bp"]])[0]),
            "net_se": s["net_se"]}


def equity_curves(b):
    """Cumulative net P&L, % of capital, on the counted sessions: the book, its gross, and each component group."""
    st = b.portfolio.setup
    capital = st.book["book"]["capital"]
    d = b.headline.run.daily
    k = d["kept"]
    out = {"book": ((d["gross"] - d["cost"])[k].cumsum() / capital * 100),
           "book gross": (d["gross"][k].cumsum() / capital * 100)}
    groups = group_of(st)
    for g in dict.fromkeys(groups.values()):
        f = _sum(b.parts, [n for n, x in groups.items() if x == g], ["gross", "cost"])[k]
        out[g] = (f["gross"] - f["cost"]).cumsum() / capital * 100
    return out


def numbers(b):
    """Every number the report, the tear sheet and reports/results/metrics.json print."""
    st, pb = b.portfolio.setup, b.portfolio
    book, capital = st.book, st.book["book"]["capital"]
    rows, level = level_view(st, b.headline, b.parts, b.fits, capital)
    cs, cb = b.carry
    k = b.headline.run.daily["kept"] & cb.run.daily["kept"]
    x = (b.headline.run.daily["gross"] - b.headline.run.daily["cost"])[k]
    y = (cb.run.daily["gross"] - cb.run.daily["cost"])[k]
    both = (st.g != 0) & (cs.g != 0)
    agree = (st.g == cs.g) & both
    carry = {"summary": metrics.evaluate(cb, capital=capital), "corr": float(np.corrcoef(x, y)[0, 1]),
             "same_side": float(agree.to_numpy().sum() / both.to_numpy().sum()) if both.to_numpy().any() else np.nan,
             "same_side_by_sleeve": {n: float(agree[n].sum() / both[n].sum()) if both[n].any() else np.nan
                                     for n in st.g.columns},
             "ex_2022": metrics.ex_2022(cb, book, capital), "difference": books.difference(b.headline, cb)}
    carry["words"] = next(w for lim, w in CARRY_WORDS if abs(carry["corr"]) >= lim)
    elb = {tr: elb_split(s, bk, capital) for tr, (s, bk) in b.elb.items()}
    for tr, (s, bk) in b.elb.items():
        if tr != st.spec.treatment:
            elb[tr]["difference"] = books.difference(bk, b.headline)
    return {"days": (st.days[0], st.days[-1]), "first_counted": b.headline.run.daily.index[
                b.headline.run.daily["kept"]].min(),
            "performance": performance(b), "components": components(st, b.headline, b.parts, capital),
            "level_sleeves": rows, "level": level, "z_agreement": z_agreement(st), "carry": carry,
            "regimes": regime_tables(b.world, st, b.headline, b.parts, capital), "elb": elb,
            "elb_episodes": elb_episodes(b.world, book), "ic": ics(st), "current": current(st, b.headline),
            "cost_curve": cost_curve(b), "spec": st.spec, "treatment": st.spec.treatment}


