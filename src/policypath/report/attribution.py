def results(b):
    """reports/results/metrics.json: the numbers the note quotes, to six significant figures."""
    n = dict(b.numbers)
    n["spec"] = {"rule": n["spec"].rule, "enter": n["spec"].enter, "exit": n["spec"].exit,
                 "treatment": n["spec"].treatment}
    n["cost_curve"] = {k: (list(v) if isinstance(v, np.ndarray) else v) for k, v in n["cost_curve"].items()}
    reg = dict(n["regimes"])
    reg["book"] = [r | {"regime": "+".join(r["regime"])} for r in reg["book"]]
    reg["sleeves"] = {s: v | {"rows": [r | {"regime": r["regime"][0]} for r in v["rows"]]}
                      for s, v in reg["sleeves"].items()}
    if reg["pair"]:
        reg["pair"] = reg["pair"] | {"rows": [r | {"regime": r["regime"][0]} for r in reg["pair"]["rows"]]}
    n["regimes"] = reg
    n["elb_episodes"] = {c: [list(e) for e in v] for c, v in n["elb_episodes"].items()}
    n["filter"] = {s: {"entries": v[0], "skipped": v[1]} for s, v in n["filter"].items()}
    return _plain(n)


def figure(b, path, theme="light"):
    """reports/figures/attribution_{theme}.png: equity by component, the cost curve, IC bars, regime bars."""
    t = _style(theme)
    n = b.numbers
    fig, axes = plt.subplots(2, 2, figsize=(12, 8.4), gridspec_kw={"hspace": 0.5, "wspace": 0.25})
    colors = books.CATEGORICAL[theme]
    charts.equity_by_component(axes[0, 0], equity_curves(b), t, colors, windows=_windows(b))
    charts.cost_curve(axes[0, 1], n["cost_curve"], t, colors)
    charts.ic_bars(axes[1, 0], {s: v["rate"]["ex_elb"] for s, v in n["ic"].items()}, t, theme)
    book_rows, sleeve_rows = regime_bars_data(n)
    charts.regime_bars(axes[1, 1], book_rows, sleeve_rows, t, marks(b.portfolio.setup, colors))
    fig.savefig(path, dpi=150, bbox_inches="tight")
    plt.close(fig)


MARKERS = ["o", "s", "^", "v"]      # by a sleeve's currency, in the book's order; a cross sleeve is a diamond


def marks(st, colors):
    """{sleeve: (colour, marker)}: its component group's colour (as `equity_curves` draws it), its currency's marker."""
    groups = list(dict.fromkeys(group_of(st).values()))
    ccys = list(dict.fromkeys(i.sleeve.ccys[0] for i in st.inputs.values() if len(i.sleeve.ccys) == 1))
    return {n: (colors[groups.index(GROUPS[i.sleeve.kind])],
                "D" if len(i.sleeve.ccys) > 1 else MARKERS[ccys.index(i.sleeve.ccys[0]) % len(MARKERS)])
            for n, i in st.inputs.items()}


def regime_bars_data(n):
    """({collapsed regime: the book's row}, {sleeve: its rows}) in `COLLAPSED_ORDER`, for `charts.regime_bars`."""
    rows = {r["regime"]: r for r in n["regimes"]["book"]}
    whole = {"hiking": ("early_hiking", "late_hiking"), "on hold": ("hold_after_hikes", "hold_after_cuts"),
             "cutting": ("cutting",), "ELB": (regimes.ELB,)}
    return ({g: rows[whole[g]] for g in COLLAPSED_ORDER},
            {s: v["rows"] for s, v in n["regimes"]["sleeves"].items()})


def _windows(b):
    lo, hi = metrics.window("ex_2022", b.portfolio.setup.book)
    return [(lo, hi, "2022")]


def write(b, root):
    """reports/metrics.md, reports/results/metrics.json and the figures under repo `root`. Returns the paths."""
    root = Path(root)
    out = {"report": root / "reports" / "metrics.md", "json": root / "reports" / "results" / "metrics.json"}
    for p in out.values():
        p.parent.mkdir(parents=True, exist_ok=True)
    out["report"].write_text(markdown(b), encoding="utf-8")
    out["json"].write_text(json.dumps(results(b), indent=1) + "\n", encoding="utf-8")
    figures = root / "reports" / "figures"
    figures.mkdir(parents=True, exist_ok=True)
    for theme in THEMES:
        p = figures / f"attribution_{theme}.png"
        figure(b, p, theme)
        out[f"figure_{theme}"] = p
    return out
