"""Attribution and evaluation: where the headline book's P&L comes from, and what it depends on. Week 10.

Generated by `scripts/build_tearsheet.py`, never hand-edited: every number comes
from the books run here, and every sentence is a template filled from them.
The book is week 9's headline (`report/portfolio.py`, `headline`), run once;
nothing here re-sizes it or picks a better one.

**By component** (`split`). Each sleeve's positions, as the book decided them,
go back through `expression.run` on its own calendar, so the P&L splits into
carry, roll and rate change (`strategy/carry.py`) exactly as week 7 marks it,
and is credited to the book calendar as week 9 credits it (`check`: the parts
add up to the book's gross to 1e-8). The component groups are the sleeves'
kinds: level (the outrights), slope (the 2s10s) and cross-country (the
differential).

**The level factor** (`factor_split`). The groups are not independent: a 2s10s
receive gains in a bull steepening, when the front end rallies too. So each
sleeve's unit P&L is regressed on the outright unit P&L of its currencies
(`metrics.factor`, full sample, ex post), and its P&L split into its
position times its betas times the outrights' unit P&L (what its level
exposure earned) and the rest (the relative value). For an outright it is all
level. The share of the book's daily gross P&L variance the level part
explains, cov(level, book) / var(book), decides the verdict: at half or more,
the report says the level dominates, and that the book is closer to a
duration timer than to relative value.

**Carry against rate** (`carry_book`). The same split into carry and roll
against the rate change, and a benchmark: the same sleeves, rule, ELB
treatment, sizing and costs, with the z replaced by the sign of each
sleeve's carry and roll ahead (`expression.ahead`, CR_h for a receive). Its
daily net P&L's correlation with the headline's says whether the book is a
carry trade in costume: `CARRY_WORDS` words it.

**By sleeve** (`carry_by_sleeve`). The book-level split can hide which
sleeves carry it, so each sleeve's carry and roll, rate change and cost are
reported with a reading of their signs (right or wrong on the rate, bleeding
or collecting carry), the share of held sessions whose carry and roll ahead
runs against the side, and the side's correlation with the sign of carry and
roll: the test of "the signal cannot be right without the trade being
expensive", sleeve by sleeve. What the rate calls would have had to earn is
the rate change needed for a net of zero, and as a correlation of position
and move (`information`, an exact identity, no model). The carry filter's
bite at entry (`filter_entries`) is counted beside it.

**Where the costs go** (`cost_sources`). The cost a year is turns x mean
gross DV01 x the one-way cost; the table gives each factor, per sleeve and
cause, so the cost can be checked by hand (`check_costs` holds the causes to
the charge). A reader's first check is today's DV01s against the cost, and
today's are well below the sample's mean: the words say so when they are.

**The level the z removes** (`level_gap`). The z trades the gap's deviation
from its trailing mean; the level it removes is reported by regime and year,
with the r* it rests on, as a measurement, not a signal.

**Regimes** (`regime_table`): `regimes.states` for each currency, real time. A
sleeve is keyed by its own currency's state, the cross sleeve and the book by
the book currency's, and the book also by whether the two currencies are in
the same collapsed regime (hiking, on hold, cutting, ELB). Every Sharpe carries
its counted and active sessions and the trades put on in the regime.

**The ELB** (`elb_books`). The book run under each treatment of
`strategy/positions.py` (flat, the configured one; exclude; hold), on the same
sizing and costs: the P&L of positions decided in the state, the rest, the
Sharpe with and without the state's sessions, and the boundary trades (the
positions a flat treatment closes on entering the state, and their cost).

**The IC** (`ics`): `metrics.ic_table` per sleeve, z against the next h
sessions of the rate-change component of unit P&L (and of the total), at
``evaluation.ic_horizons`` (a week, a month, a quarter), on the sessions
outside the ELB state and on all.

**Without 2022** (`metrics.ex_2022`, `metrics.ex_2022_23`): for the book, each
sleeve's contribution, each ELB treatment and the carry benchmark.
"""

