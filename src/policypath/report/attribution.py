            f"and costs, trading only the sign of each sleeve's carry and roll ahead, nets {sr(cs['net_sr'], cs['net_se'])}; "
            f"the book's daily net P&L correlates {c['corr']:+.2f} with it, and {pct(c['same_side'])} of the sleeve-"
