sr, pc, pct = books.sr, books.pc, books.pct


def level_words(n):
    """The level-or-relative-value verdict, in words from the level-factor split."""
    lv = n["level"]
    share, gross = lv["variance_share"], lv["gross"]
    comp = {r["group"]: r for r in n["components"]}
    head = ("The level dominates: this is closer to a duration timer than to relative value" if lv["dominates"] else
            "Relative value dominates: the level exposure is the smaller part")
    return (f"**{head}.** {pct(share)} of the variance of the book's daily gross P&L is its exposure to the front ends "
            f"(the outrights, and the curve and cross sleeves' betas on them); the rest, {pct(1 - share)}, is the "
            f"relative value. In P&L the level exposure made {pc(lv['level'])} of capital a year gross and the rest "
            f"{pc(lv['rest'])}, of a gross {pc(gross)}"
            + (": the risk is mostly the level's, the loss mostly the rest's" if lv["dominates"] and
               lv["rest"] < min(lv["level"], 0.0) else "")
            + f". By sleeve group the level sleeves net {pc(comp['level']['net'])} "
            "a year, " + _and(f"the {g} sleeves {pc(comp[g]['net'])}" for g in comp if g not in ("level", "book"))
            + f", the book {pc(comp['book']['net'])}.")


def carry_words(n):
    """Carry and roll against the rate change, and the carry benchmark."""
    c, comp = n["carry"], {r["group"]: r for r in n["components"]}
    b, cs = comp["book"], c["summary"]
    paid = b["carry_roll"] < 0 < b["rate"]
    return (f"**The book is {c['words']}.** Of its gross {pc(b['gross'])} of capital a year, carry and roll are "
            f"{pc(b['carry_roll'])} and the rate change {pc(b['rate'])}"
            + (": its calls on the rate earn, and it pays more than that to hold them" if paid and b["gross"] < 0 else
               ": its calls on the rate earn, and it pays carry to hold them" if paid else "")
            + ". A benchmark on the same sleeves, rule, sizing "
            f"and costs, trading only the sign of each sleeve's carry and roll ahead, nets {sr(cs['net_sr'], cs['net_se'])}; "
            f"the book's daily net P&L correlates {c['corr']:+.2f} with it, and {pct(c['same_side'])} of the sleeve-"
            "sessions both hold a side are on the same side.")


def elb_words(n):
    """The ELB decision in words: the chosen treatment and what the others would have given."""
    e, chosen = n["elb"], n["treatment"]
    c = e[chosen]
    others = [t for t in positions.TREATMENTS if t != chosen]
    forced = (f", {c['closes']} positions closed on entering the state and {c['reopens']} re-opened on leaving it, "
              f"at {c['boundary_cost']:.2f}% of capital" if c["closes"] is not None else "")
    return (f"**The ELB: {sleeves.TREATMENT_WORDS[chosen]} (proposed).** The book nets {sr(c['net_sr'], c['net_se'])}"
            + forced + ". " + "; ".join(
                f"{sleeves.TREATMENT_WORDS[t]} it would net {sr(e[t]['net_sr'], e[t]['net_se'])} "
                f"({books.gap(e[t]['difference'])} against {chosen}), {pc(e[t]['in_state'], 1)} of capital from "
                f"positions decided in the state" for t in others) + ".")


def ex_words(n):
    """The book without 2022 and without the 2022-23 cycle."""
    p = n["performance"][0]
    a, b = p["ex_2022"], p["ex_2022_23"]
    return (f"**Without 2022.** The book nets {sr(p['net_sr'], p['net_se'])} over the sample, {sr(a['net_sr'], a['net_se'])} "
            f"without 2022 and {sr(b['net_sr'], b['net_se'])} without Dec 2021 to Aug 2023 (the positions not re-run: "
            "the rest of the sample's P&L).")


def regime_words(n):
    """Where the book earns by regime of the book currency."""
    rows = {r["regime"]: r for r in n["regimes"]["book"]}
    coll = [rows[g] for g in REGIME_ROWS if len(g) == 2] + [rows[("cutting",)], rows[(regimes.ELB,)]]
    name = lambda g: "hiking" if g == ("early_hiking", "late_hiking") else \
        "on hold" if g == ("hold_after_hikes", "hold_after_cuts") else STATE_WORDS[g[0]]
    return (f"**By {n['regimes']['book_ccy']} regime** the book nets "
            + _and(f"{sr(r['net_sr'], r['net_se'])} {name(r['regime'])} ({r['sessions']:,} sessions)" for r in coll)
            + ".")


def ic_words(n):
    """The level sleeves' IC at each horizon, on the rate change outside the ELB state."""
    hs = [r["h"] for r in next(iter(n["ic"].values()))["rate"]["ex_elb"]]
    parts = []
    for s, v in n["ic"].items():
        parts.append(f"{s} " + ", ".join(f"{r['ic']:+.2f} (t {r['t']:+.1f})" for r in v["rate"]["ex_elb"]))
    return (f"**The IC** of z against the next {', '.join(map(str, hs))} sessions' rate change, outside the ELB state: "
            + "; ".join(parts) + ".")


def _num(x, spec):
    """`x` formatted by `spec`, or n/a where there is no number."""
    return "n/a" if x is None or pd.isna(x) else format(x, spec)


def _ic_table(n):
    head = ["sleeve", "part", "sample", *[f"IC({r['h']}) t" for r in next(iter(n["ic"].values()))["rate"]["all"]],
            "non-overlapping mean [range]"]
    rows = []
    for s, v in n["ic"].items():
        for part, samples in v.items():
            for name, rs in samples.items():
                rows.append([s, part, "outside the ELB" if name == "ex_elb" else "all",
                             *[f"{_num(r['ic'], '+.3f')} ({_num(r['t'], '+.1f')})" for r in rs],
                             "; ".join(f"{_num(r['offsets_mean'], '+.3f')} [{_num(r['offsets_min'], '+.2f')}, "
                                       f"{_num(r['offsets_max'], '+.2f')}]" for r in rs)])
    return table(pd.DataFrame(rows, columns=head))


def _perf_table(n):
    rows = []
    for r in n["performance"]:
        rows.append([r["name"], sr(r["gross_sr"], r["gross_se"]), sr(r["net_sr"], r["net_se"]), pc(r["net_year"]),
                     f"{r['vol']:.1f}%", f"{r['max_dd']:.1f}%", pct(r["hit_daily"]), pct(r["hit_trade"]),
                     f"{r['trades']:,}", f"{r['turns_year']:.1f}", pct(r["time_in_market"]),
                     sr(r["ex_2022"]["net_sr"], r["ex_2022"]["net_se"]),
                     sr(r["ex_2022_23"]["net_sr"], r["ex_2022_23"]["net_se"])])
    return table(pd.DataFrame(rows, columns=["", "gross SR", "net SR", "net a year", "vol", "worst dd", "hit (days)",
                                             "hit (trades)", "trades", "turns a year", "in market", "ex-2022",
                                             "ex-2022-23"]))


def _components_table(n):
    rows = [[r["group"], _and(r["sleeves"]) if r["group"] != "book" else "every sleeve", pc(r["gross"]),
             pc(-r["cost"]), pc(r["net"]), pc(r["carry_roll"]), pc(r["rate"]), pct(r["variance_share"]),
             sr(r["net_sr"], r["net_se"])] for r in n["components"]]
    return table(pd.DataFrame(rows, columns=["group", "sleeves", "gross a year", "costs", "net a year",
                                             "carry and roll", "rate change", "share of net variance",
                                             "net SR of the contribution"]))


def _level_table(n):
    rows = [[r["sleeve"], "; ".join(f"{o} {v:+.2f}" for o, v in r["betas"].items()), f"{r['r2']:.2f}",
             f"{r['sessions']:,}", pc(r["level"]), pc(r["rest"])] for r in n["level_sleeves"]]
    lv = n["level"]
    rows.append(["book", "", "", "", pc(lv["level"]), pc(lv["rest"])])
    return table(pd.DataFrame(rows, columns=["sleeve", "beta on the outright(s)", "R^2", "sessions",
                                             "level part, gross a year", "the rest, gross a year"]))


def _z_table(n):
    rows = []
    for r in n["z_agreement"]:
        for name in ("orthogonal", "raw"):
            if name in r:
                v = r[name]
                rows.append([r["ccy"], f"{r['level']} vs {r['slope']} ({name} slope)", f"{v['corr']:+.2f}",
                             pct(v["same_sign"]), f"{v['sessions']:,}"])
        rows.append([r["ccy"], "the book's sides, both on", "", pct(r["sides"]["same"]), f"{r['sides']['sessions']:,}"])
    return table(pd.DataFrame(rows, columns=["", "what", "corr of z", "same sign", "sessions"]))


