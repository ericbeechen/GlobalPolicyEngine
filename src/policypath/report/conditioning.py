"""The GBP path against the Bank of England's own MPR conditioning path for Bank Rate.

Since August 2009 each Inflation Report / Monetary Policy Report projection is
conditioned on a Bank Rate path built from OIS: a 15-working-day average, to a
cutoff about a week before publication, of instantaneous forward rates, by
calendar quarter. The current quarter averages realized overnight rates to the
cutoff with forwards after it. The levels are SONIA-OIS, with no Bank Rate
adjustment.

The same construction from the solved path: on each window day w, the
quarter's calendar-day average of realized SONIA before w and the step path
from w on, then the mean over the window. It cannot match exactly: the Bank
averages its smooth fitted forward curve, the path is a step function
between meetings with the first regime at the rate in force. Only quarters
that end by the last of the path's meetings are compared.

Generated by `scripts/check_mpr.py`, never hand-edited.
"""

import numpy as np
import pandas as pd
from policypath.calendars import known_daily
from policypath.report.coverage import table

DAY = pd.Timedelta(days=1)


def truth(path):
    """The committed ground truth: one row per report and quarter, with the report's window."""
    df = pd.read_csv(path, comment="#", parse_dates=["published", "window_end"])
    return df.assign(quarter=pd.PeriodIndex(df["quarter"], freq="Q"))


def daily_path(session, sessions, meetings, fixings, bday):
    """Calendar-daily rate as seen on `session`: realized fixings before it, the step path from it.

    Ends on the last meeting's effective date.
    """
    s = sessions.set_index("session").loc[session]
    m = meetings[meetings["session"] == session].sort_values("k")
    steps = pd.Series([s["rate_now"], *m["rate"]], index=pd.DatetimeIndex([session, *m["effective_date"]]))
    ahead = steps.reindex(pd.date_range(session, m["effective_date"].iloc[-1], freq="D")).ffill()
    seen = known_daily(fixings, session, bday)
    return pd.concat([seen[seen.index < session], ahead])


def compare(report_rows, sessions, meetings, fixings, bday):
    """Our quarterly averages over one report's window, next to the Bank's."""
    r = report_rows.iloc[0]
    days = pd.date_range(end=r["window_end"], periods=int(r["window_days"]), freq=bday)
    days = days[days.isin(sessions["session"])]
    paths = {d: daily_path(d, sessions, meetings, fixings, bday) for d in days}
    rows = []
    for q, bank in zip(report_rows["quarter"], report_rows["bank_path"]):
        span = pd.date_range(q.start_time, q.end_time.normalize(), freq="D")
        if any(span[0] < p.index[0] or span[-1] > p.index[-1] for p in paths.values()):
            continue
        last = paths[days[-1]].reindex(span)
        rows.append({"report": r["report"], "window_end": r["window_end"], "window_read": r["window_read"],
                     "quarter": str(q), "bank": bank,
                     "ours": float(np.mean([p.reindex(span).mean() for p in paths.values()])),
                     # a step inside the quarter is where a smooth curve and a step path part
                     "priced_in_quarter_bp": (last.iloc[-1] - last.iloc[0]) * 100})
    out = pd.DataFrame(rows)
    return out.assign(diff_bp=(out["ours"] - out["bank"]) * 100) if len(out) else out


def checks(truth_rows, sessions, meetings, fixings, bday):
    """Every report's comparison, and a summary per report."""
    detail = pd.concat([compare(g, sessions, meetings, fixings, bday)
                        for _, g in truth_rows.groupby("report", sort=False)], ignore_index=True)
    summary = (detail.groupby(["report", "window_end", "window_read"], sort=False)["diff_bp"]
               .agg(quarters="count", mean_bp="mean", max_abs_bp=lambda s: s.abs().max()).reset_index())
    return summary, detail


def markdown(ccy, summary, detail, examples):
    read = summary[summary["window_read"]]
    slope = np.polyfit(detail["priced_in_quarter_bp"], detail["diff_bp"], 1)[0]
    calm = detail["priced_in_quarter_bp"].abs() < 5
    lines = [
        f"# The {ccy} path against the Bank of England's MPR conditioning paths",
        "",
        "Generated by `scripts/check_mpr.py`. Do not edit by hand. Ground truth: "
        "`tests/data/boe/conditioning_paths.csv` (the Bank's Projections Databank, July 2026).",
        "",
        f"- Reports compared: {len(summary)}, {len(detail)} quarters inside the path's eight meetings",
        f"- All reports: mean difference {detail['diff_bp'].mean():+.2f}bp, mean absolute "
        f"{detail['diff_bp'].abs().mean():.2f}bp, worst {detail['diff_bp'].abs().max():.2f}bp",
        f"- Reports whose window was read in the report itself ({len(read)}): worst quarter "
        f"{read['max_abs_bp'].max():.2f}bp",
        "",
        "Where they differ: the Bank averages its smooth instantaneous forward curve, which starts a priced move "
        "before the meeting it belongs to; the path is a step function that moves on the meeting's effective date. "
        "So inside a quarter where a hike is priced the Bank's average comes out higher, and a cut lower: the "
        f"difference correlates {detail['diff_bp'].corr(detail['priced_in_quarter_bp']):+.2f} with the move priced "
        f"inside the quarter ({slope:+.3f}bp per bp). Quarters with less than 5bp priced inside them agree to "
        f"{detail.loc[calm, 'diff_bp'].abs().mean():.2f}bp on average ({int(calm.sum())} quarters), the rest to "
        f"{detail.loc[~calm, 'diff_bp'].abs().mean():.2f}bp. The rest is data: April and July 2026 are stored by the "
        "Bank to one decimal (up to 5bp of rounding), November 2022 used a 7-day window, and windows not read "
        "in the report itself were scraped.",
        "",
        "## By report",
        "",
        table(summary),
        "",
    ]
    for report in examples:
        lines += [f"## {report}", "", table(detail[detail["report"] == report].drop(columns=["report"])), ""]
    return "\n".join(lines)
