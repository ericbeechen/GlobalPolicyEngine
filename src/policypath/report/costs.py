def _two_years(years):
    """'101% (2022, 2023)': the best two years' share of a sleeve's net P&L; n/a where the net is at or below 0."""
    if not years.sum() > 0 or len(years) < 2:
        return "n/a (net <= 0)" if not years.sum() > 0 else "n/a"
    top = years.nlargest(2)
    return f"{top.sum() / years.sum():.0%} ({', '.join(str(int(y)) for y in sorted(top.index))})"


def _realized(run, capital):
    """Realized vol of a run's net P&L over its kept sessions, percent of `capital` a year."""
    d = run.daily[run.daily["kept"]]
    return float((d["gross"] - d["cost"]).std() * np.sqrt(run.periods) / capital * 100.0)


