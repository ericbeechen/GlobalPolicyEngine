def results(b):
    """reports/results/costs.json: the numbers the note quotes, to six significant figures."""
    book = b.book
    grid_bp = book["costs"]["sensitivity_bp"]
    chosen_stats = {sz: {n: stats(r) for n, r in runs.items()} for sz, runs in b.chosen.items()}
    return _plain({
        "spec": {"rule": chosen(book).rule, "enter": book["positions"]["enter"], "exit": book["positions"]["exit"],
                 "treatment": chosen(book).treatment, "primary_sizing": "vol_scaled",
                 "vol_target": book["book"]["vol_target"], "capital": book["book"]["capital"]},
        "legs": leg_words(b).to_dict("records"),
        "chosen": chosen_stats,
        "curves": {sz: {n: {"round_trip_bp": grid_bp, "net_sr": list(curve(r, grid_bp)),
                            "assumed_only_net_sr": list(curve(r, grid_bp, "assumed"))}
                        for n, r in runs.items()} for sz, runs in b.chosen.items()},
        "surface": {sz: {n: surface(b.grid[sz], book, n) for n in [SUM, *b.sleeves]} for sz in b.grid},
        "grid": {sz: {f"{e:g}/{x:g}": {n: {"net_sr": st["net_sr"], "net_se": st["net_se"], "gross_sr": st["gross_sr"],
                                           "turns_year": st["turns_year"], "traded_year": st["traded_year"]}
                                       for n, st in per.items()} for (e, x), per in cells_of.items()}
                 for sz, cells_of in b.grid.items()},
        "rules": b.rules,
        "restrike": {f"{m}_months": by for m, by in b.restrike.items()},
        "band_off": b.band["off"],
        "carry_filter_on": b.carry_filter,
        "elb": b.elb.set_index("sleeve").to_dict("index"),
        "by_year_pct_capital": {n: by_year(r, book["book"]["capital"]).to_dict()
                                for n, r in b.chosen["vol_scaled"].items()},
    })


def write(b, root):
    """Every output of the build under repo `root`. Returns the paths."""
    root = Path(root)
    out = {"report": root / "reports" / "costs.md", "json": root / "reports" / "results" / "costs.json"}
    for p in out.values():
        p.parent.mkdir(parents=True, exist_ok=True)
    out["report"].write_text(markdown(b), encoding="utf-8")
    out["json"].write_text(json.dumps(results(b), indent=1) + "\n", encoding="utf-8")
    figures = root / "reports" / "figures"
    figures.mkdir(parents=True, exist_ok=True)
    for theme in THEMES:
        for stem, draw in (("cost_sensitivity", cost_figure), ("hysteresis_grid", grid_figure)):
            p = figures / f"{stem}_{theme}.png"
            draw(b, p, theme)
            out[f"{stem}_{theme}"] = p
    return out
