# ---- running a sleeve --------------------------------------------------------------

@dataclass(frozen=True)
class Spec:
    """One way of running a sleeve: rule, ELB treatment, sizing, the hysteresis pair, and the options.

    `restrike_months` overrides every par leg's ``roll_every_months``; `band`
    the ``risk.no_trade_band`` (None: the book's).
    """
    rule: str
    treatment: str
    sizing: str
    enter: float
    exit: float
    carry_filter: bool = False
    restrike_months: int | None = None
    band: float | None = None

    def words(self, sizing=True):
        rule = f"hysteresis ({self.enter:g}, {self.exit:g})" if self.rule == "hysteresis" else "linear"
        return f"{rule}, {TREATMENT_WORDS[self.treatment]}" + (f", {SIZING_WORDS[self.sizing]}" if sizing else "")


def chosen(book, sizing="vol_scaled", **kw):
    """The book's own spec: its rule and pair, its ELB treatment, the carry filter as configured."""
    p = book["positions"]
    base = Spec(p["rule"], book["evaluation"]["elb"]["chosen"], sizing, p["enter"], p["exit"], p["carry_filter"])
    return replace(base, **kw)


@dataclass
class Inputs:
    """What every run of one sleeve shares, built once: unit P&L, sigma, the ELB state, the carry gate, the costs.

    `start` is the first session a position decided on the first z is held;
    `periods` the sleeve calendar's sessions a year from there; `raw_sigma` the
    unfloored EWMA sigma.
    """
    sleeve: object
    u: pd.DataFrame
    sigma: pd.Series
    raw_sigma: pd.Series
    state: pd.Series
    allow: pd.Series
    costs: list
    start: pd.Timestamp
    periods: float


def inputs(sleeve, world, book, like=None):
    """One sleeve's `Inputs`, from the world its sleeves were built from.

    `like` is the `Inputs` of the same sleeve on the same legs with another
    signal (the robustness rows): its unit P&L, sigma and costs are
    reused, and only what reads the signal or the model (the ELB state, the
    carry gate, the start) is built again.
    """
    if like is None:
        u = expression.unit(sleeve)
        total = u.groupby("session")["total"].sum(min_count=1).reindex(sleeve.sessions)
        r = book["risk"]
        raw = risk.ewma_sigma(total, r["ewma_lambda"])
        like = Inputs(None, u, risk.sigma_floor(raw, r["sigma_floor"]), raw, None, None, costs.leg_costs(sleeve), None,
                      None)
    state = positions.elb(sleeve, {c: world.panel(c, "model") for c in sleeve.ccys})
    ahead = expression.ahead(sleeve, book["carry"]["horizon_days"], book["carry"]["closure_min_pairs"])
    at = sleeve.sessions.get_loc(sleeve.component["z"].first_valid_index()) + sleeve.lag + 1
    return replace(like, sleeve=sleeve, state=state, allow=positions.pays(ahead), start=sleeve.sessions[at],
                   periods=metrics.per_year(sleeve.sessions[at:]))


@dataclass
class Run:
    """One sleeve (or the sum) under one spec: by session, what it earned, what it traded, which sessions count.

    `daily` columns: gross (P&L before costs), cost (at the configured costs),
    traded (book DV01, every leg), assumed (on the ``observed: false`` legs),
    observed_cost, traded by cause (`costs.CAUSES`), side (the rule's side held
    into the session), held (the first leg's DV01 held), gross_dv01 (every leg's
    |q| held), kept, elb_line. Book currency, bp x DV01. The P&L columns
    (`PNL`) are 0 where the treatment drops the held position's P&L, the cost
    columns (`COSTS`) where it drops the cost of the one put on
    (`positions.samples`).
    """
    name: str
    spec: Spec
    daily: pd.DataFrame
    start: pd.Timestamp
    periods: float


def simulate(inp, spec, book):
    """Run one sleeve under `spec`: decide, size, `expression.run`, charge. Returns a `Run`."""
    s = inp.sleeve
    allow = inp.allow if spec.carry_filter else None
    side = positions.decide(s.component["z"], spec.rule, spec.enter, spec.exit, inp.state, spec.treatment, allow)
    band = book["risk"]["no_trade_band"] if spec.band is None else spec.band
    q = positions.size(side, spec.sizing, inp.sigma, positions.target_sigma(book), band)
    legs, sessions = expression.run(s, q, inp.u)
    lc = inp.costs if spec.restrike_months is None else [
        replace(c, restrike_months=spec.restrike_months) if c.restrike_months else c for c in inp.costs]
    trades = costs.traded(s, legs, side, lc)
    per_leg = costs.by_leg(trades)
    rates = costs.configured(lc)
    observed = [c.leg for c in lc if c.observed]
    kept, pnl, paid, line = positions.samples(inp.state, spec.treatment, s.lag)
    held = sessions["position"].fillna(0.0)
    daily = pd.DataFrame({
        "gross": sessions["pnl"], "cost": costs.charge(trades, rates), "traded": per_leg.sum(axis=1),
        "assumed": per_leg.drop(columns=observed).sum(axis=1),
        "observed_cost": sum((per_leg[leg] * rates[leg] for leg in observed), pd.Series(0.0, index=s.sessions)),
        **{cause: trades[cause].sum(axis=1) for cause in costs.CAUSES},
        "side": side.shift(s.lag + 1).fillna(0.0), "held": held, "gross_dv01": held.abs() * len(s.legs),
        "kept": kept & (s.sessions >= inp.start), "elb_line": line & (s.sessions >= inp.start)}, index=s.sessions)
    daily[PNL] = daily[PNL].where(pnl, 0.0, axis=0)
    daily[COSTS] = daily[COSTS].where(paid, 0.0, axis=0)
    return Run(s.name, spec, daily, inp.start, inp.periods)


PNL = ["gross", "gross_dv01"]
COSTS = ["cost", "traded", "assumed", "observed_cost", *costs.CAUSES]
SUMMED = [*PNL, *COSTS]


def combine(runs, days, name=SUM):
    """The sum of `runs` on the book calendar `days`: each session's P&L and trades into the next book session.

    From the latest start among the runs; a book session is kept where any
    run keeps a session mapped into it, and sums only what the runs keep: a
    session a run's treatment leaves out adds nothing of that run's.
    """
    days = pd.DatetimeIndex(days)
    start = max(r.start for r in runs)
    parts = []
    for r in runs:
        d = r.daily.copy()
        d[SUMMED] = d[SUMMED].where(d["kept"], 0.0, axis=0)
        at = days.searchsorted(d.index)
        ok = at < len(days)
        parts.append(d.loc[ok, SUMMED + ["kept", "elb_line"]].set_axis(days[at[ok]]))
    both = pd.concat(parts)
    summed = both.groupby(level=0)[SUMMED].sum().reindex(days, fill_value=0.0)
    flags = both.groupby(level=0)[["kept", "elb_line"]].any().reindex(days, fill_value=False)
    daily = summed.join(flags)
    daily["kept"] &= days >= start
    daily["elb_line"] &= days >= start
    return Run(name, runs[0].spec, daily, start, metrics.per_year(days[days >= start]))


# ---- statistics --------------------------------------------------------------------

def spells(side):
    """Runs of one non-zero side, in session order: (first session, sessions held) each."""
    v = side.to_numpy(dtype=float)
    starts = np.flatnonzero(v != np.r_[0.0, v[:-1]])
    ends = np.r_[starts[1:], len(v)]
    keep = v[starts] != 0
    return pd.DataFrame({"first": side.index[starts[keep]], "sessions": (ends - starts)[keep]})


def _sharpe(x, periods):
    sr = metrics.sharpe(x, periods)
    return sr, metrics.sharpe_se(sr, len(x) / periods) if pd.notna(sr) else np.nan


def stats(run):
    """The numbers the report prints for one run (module docstring): Sharpe with SE, P&L, turnover, breakevens."""
    d = run.daily[run.daily["kept"]]
    n, per = len(d), run.periods
    years = n / per
    net = d["gross"] - d["cost"]
    gross_sr, gross_se = _sharpe(d["gross"], per)
    net_sr, net_se = _sharpe(net, per)
    active = d["gross_dv01"] > 0
    traded = d["traded"].sum()
    held = d.loc[active, "gross_dv01"].mean() if active.any() else np.nan
    half = n // 2
    first, second = (_sharpe(net.iloc[sl], per) for sl in (slice(0, half), slice(half, n)))
    out = {
        "sessions": n, "active": int(active.sum()), "years": years, "first": d.index.min(), "last": d.index.max(),
        "gross_sr": gross_sr, "gross_se": gross_se, "net_sr": net_sr, "net_se": net_se,
        "gross_year": d["gross"].sum() / years, "cost_year": d["cost"].sum() / years, "net_year": net.sum() / years,
        "traded_year": traded / years, **{f"{c}_year": d[c].sum() / years for c in costs.CAUSES},
        "maintenance_share": d[list(costs.MAINTENANCE)].sum().sum() / traded if traded > 0 else np.nan,
        "turns_year": traded / years / held if held > 0 else np.nan, "mean_gross_dv01": held,
        "cstar_bp": costs.breakeven(d["gross"].sum(), traded),
        "cstar_assumed_bp": costs.breakeven(d["gross"].sum() - d["observed_cost"].sum(), d["assumed"].sum()),
        "mix_bp": 2.0 * d["cost"].sum() / traded if traded > 0 else np.nan,
        "time_in_market": float(active.mean()) if n else np.nan,
        "halves": {"split": d.index[half] if n else pd.NaT, "first_sr": first[0], "first_se": first[1],
                   "second_sr": second[0], "second_se": second[1]},
    }
    if "side" in d:
        sp = spells(run.daily.loc[run.daily.index >= run.start, "side"])
        sp = sp[sp["first"].isin(d.index)]
        out |= {"entries_year": len(sp) / years, "holding_sessions": float(sp["sessions"].mean()) if len(sp) else np.nan}
    return out


def curve(run, cs, mode="uniform"):
    """Net Sharpe at each round trip in `cs` (bp): every leg at c (``uniform``), or only the assumed ones (``assumed``).

    Costs are linear in c, so from the kept sessions' gross P&L x and DV01
    traded t: mean = mean(x) - c/2 mean(t), var = var(x) - c cov(x, t) + c^2/4
    var(t); exactly `backtest.metrics.sharpe` of x - c/2 t.
    """
    d = run.daily[run.daily["kept"]]
    x, t = (d["gross"], d["traded"]) if mode == "uniform" else (d["gross"] - d["observed_cost"], d["assumed"])
    x, t = x.to_numpy(dtype=float), t.to_numpy(dtype=float)
    cs = np.asarray(cs, dtype=float)
    cov = np.cov(x, t)
    mean = x.mean() - cs / 2.0 * t.mean()
    var = cov[0, 0] - cs * cov[0, 1] + cs ** 2 / 4.0 * cov[1, 1]
    with np.errstate(divide="ignore", invalid="ignore"):
        return np.where(var > 0, mean / np.sqrt(var) * np.sqrt(run.periods), np.nan)


def by_year(run, capital=None):
    """Net P&L by calendar year over the kept sessions: book currency, or percent of `capital` if given."""
    d = run.daily[run.daily["kept"]]
    net = (d["gross"] - d["cost"]).groupby(d.index.year).sum()
    return net / capital * 100.0 if capital else net


def cells(book):
    """The grid's cells with exit < enter, as (enter, exit), in grid order."""
    g = book["positions"]["grid"]
    return [(e, x) for e in g["enter"] for x in g["exit"] if x < e]


def neighbours(book, cell):
    """The up-to-8 cells adjacent to `cell` in grid-index space that have exit < enter."""
    g = book["positions"]["grid"]
    i, j = g["enter"].index(cell[0]), g["exit"].index(cell[1])
    out = []
    for a in (i - 1, i, i + 1):
        for b in (j - 1, j, j + 1):
            if (a, b) != (i, j) and 0 <= a < len(g["enter"]) and 0 <= b < len(g["exit"]) \
                    and g["exit"][b] < g["enter"][a]:
                out.append((g["enter"][a], g["exit"][b]))
    return out


def surface(grid, book, name):
    """What the grid says about one sleeve at the chosen cell: its neighbours', the grid's and the halves' Sharpes.

    `grid` is {cell: {name: stats}}. ``stable`` is True only if the range of
    net Sharpe over the chosen cell and its neighbours is under one SE at the
    chosen cell.
    """
    here = (book["positions"]["enter"], book["positions"]["exit"])
    at = grid[here][name]
    near = np.array([grid[c][name]["net_sr"] for c in [here, *neighbours(book, here)]])
    every = np.array([grid[c][name]["net_sr"] for c in grid])
    spread = float(np.nanmax(near) - np.nanmin(near))
    return {"cell": here, "net_sr": at["net_sr"], "net_se": at["net_se"], "gross_sr": at["gross_sr"],
            "neighbours": len(near) - 1,
            "near_min": float(np.nanmin(near[1:])), "near_median": float(np.nanmedian(near[1:])),
            "near_max": float(np.nanmax(near[1:])), "near_range": spread,
            "grid_min": float(np.nanmin(every)), "grid_median": float(np.nanmedian(every)),
            "grid_max": float(np.nanmax(every)), "share_positive": float(np.mean(every > 0)), "cells": len(every),
            "stable": bool(spread < at["net_se"]), "halves": at["halves"]}


# ---- the build ---------------------------------------------------------------------

@dataclass
class Build:
    """Everything the report says. Stats are `stats` dicts keyed by sleeve name (and `SUM`).

    `chosen` is {sizing: {name: Run}}; `rules` {sizing: {treatment: {rule:
    {name: stats}}}}; `grid` {sizing: {cell: {name: stats}}}; `restrike`
    {months: {sizing: {name: stats}}} for the sleeves with par legs; `band`
    {"off": {name: stats}} (vol-scaled, no band); `carry_filter` {name: stats}.
    """
    book: dict
    sleeves: dict
    inputs: dict
    chosen: dict
    rules: dict
    grid: dict
    restrike: dict
    band: dict
    carry_filter: dict
    elb: pd.DataFrame


def _book_days(world, book):
    home = book["book"]["currency"]
    return pd.DatetimeIndex(sorted(world.panel(home, "signal")["session"].unique()))


def run_all(inp, spec, book, days):
    """Every sleeve under `spec`, and their sum: {name: Run}."""
    runs = {name: simulate(i, spec, book) for name, i in inp.items()}
    return {**runs, SUM: combine(list(runs.values()), days)}


def elb_table(inp, runs, book):
    """Per sleeve, the ELB state: its entries and exits, the positions a flat treatment closes, and hold's split.

    `runs` is {treatment: {name: Run}} at the chosen rule and sizing.
    """
    rows = []
    for name, i in inp.items():
        st = i.state[i.state.index >= i.start].astype(int)
        moves = st.diff().fillna(0.0)
        flat, hold = runs["flat"][name].daily, runs["hold"][name].daily
        lag = i.sleeve.lag
        entries = st.index[moves > 0]
        at = [i.sleeve.sessions.get_loc(e) + lag for e in entries if i.sleeve.sessions.get_loc(e) + lag < len(flat)]
        closed = [k for k in at if flat["held"].iloc[k] != 0]
        live = hold[hold.index >= i.start]
        net = live["gross"] - live["cost"]
        rows.append({"sleeve": name, "elb_sessions": int(st.sum()), "entries": int((moves > 0).sum()),
                     "exits": int((moves < 0).sum()), "closed": len(closed),
                     "closing_cost": float(flat["cost"].iloc[closed].sum()) if closed else 0.0,
                     "hold_elb_net": float(net[live["elb_line"]].sum()),
                     "hold_other_net": float(net[~live["elb_line"]].sum())})
    return pd.DataFrame(rows)


def build(world=None):
    """Every run the report reads: the chosen spec both sizings, the rules x treatments, the grid, the sensitivities."""
    world = expression.World() if world is None else world
    book = world.book
    sleeves = expression.build(world)
    inp = {name: inputs(s, world, book) for name, s in sleeves.items()}
    days = _book_days(world, book)
    picked = {sz: run_all(inp, chosen(book, sz), book, days) for sz in positions.SIZING}
    rules, by_treatment = {}, {}
    for sz in positions.SIZING:
        rules[sz] = {}
        for tr in positions.TREATMENTS:
            rules[sz][tr] = {}
            for rule in positions.RULES:
                spec = chosen(book, sz, treatment=tr, rule=rule, carry_filter=False)
                runs = picked[sz] if spec == chosen(book, sz) else run_all(inp, spec, book, days)
                rules[sz][tr][rule] = {n: stats(r) for n, r in runs.items()}
                if rule == book["positions"]["rule"] and sz == "vol_scaled":
                    by_treatment[tr] = runs
    grid = {sz: {cell: {n: stats(r) for n, r in run_all(inp, chosen(book, sz, enter=cell[0], exit=cell[1]),
                                                           book, days).items()}
                 for cell in cells(book)} for sz in positions.SIZING}
    par = {n: i for n, i in inp.items() if any(c.restrike_months for c in i.costs)}
    months = sorted({1, *(c.restrike_months for i in par.values() for c in i.costs if c.restrike_months)})
    restrike = {m: {sz: {n: stats(simulate(i, chosen(book, sz, restrike_months=m), book)) for n, i in par.items()}
                    for sz in positions.SIZING} for m in months}
    band = {"off": {n: stats(r) for n, r in run_all(inp, chosen(book, band=0.0), book, days).items()}}
    carry_on = {n: stats(r) for n, r in run_all(inp, chosen(book, carry_filter=True), book, days).items()}
    check([*picked.values(), *by_treatment.values()], inp, days)
    return Build(book, sleeves, inp, picked, rules, grid, restrike, band, carry_on,
                 elb_table(inp, by_treatment, book))


def check(sets, inp, days, tol=1e-9):
    """Raise if a build's own invariants fail, on each {name: Run} in `sets` (each sleeve and its sum).

    Every trade has one cause; a treatment leaves nothing in the sessions it
    drops; the sum is its runs' kept P&L; each breakeven is the zero of its
    curve; and a sleeve whose legs share one cost nets, at the configured
    costs, what its uniform curve says at that cost.
    """
    for runs in sets:
        parts = [r for n, r in runs.items() if n != SUM]
        for r in runs.values():
            d, st, where = r.daily, stats(r), f"{r.name} ({r.spec.words() if r.spec else ''})"
            if not np.allclose(d[list(costs.CAUSES)].sum(axis=1), d["traded"], atol=tol):
                raise RuntimeError(f"{where}: DV01 traded by cause does not add up to DV01 traded")
            dropped = d.loc[~d["kept"] & (d.index >= r.start), SUMMED].abs().to_numpy().sum()
            if r.spec.treatment != "hold" and dropped > tol:
                raise RuntimeError(f"{where}: {dropped:g} of P&L or cost on sessions the treatment leaves out")
            for key, mode in (("cstar_bp", "uniform"), ("cstar_assumed_bp", "assumed")):
                x = st[key]
                if x is not None and np.isfinite(x) and abs(curve(r, [x], mode)[0]) > 1e-6:
                    raise RuntimeError(f"{where}: the net Sharpe at c* ({key}) is not 0")
            if r.name in inp and len({round(c.round_trip_bp, 12) for c in inp[r.name].costs}) == 1 \
                    and st["traded_year"] > 0 and abs(curve(r, [st["mix_bp"]])[0] - st["net_sr"]) > 1e-6:
                raise RuntimeError(f"{where}: the configured net is off its uniform curve at its one cost")
        kept = sum(float(r.daily.loc[r.daily["kept"] & (r.daily.index <= days[-1]), "gross"].sum()) for r in parts)
        total = float(runs[SUM].daily["gross"].sum())
        if abs(total - kept) > tol * max(1.0, abs(kept)):
            raise RuntimeError(f"the sum's gross {total:g} is not its runs' kept gross {kept:g}")


# ---- the words ---------------------------------------------------------------------

def sr(x, se=None):
    """"+0.42 (0.31)": a Sharpe and, if given, its SE."""
    if pd.isna(x):
        return "n/a"
    return f"{x:+.2f}" + ("" if se is None or pd.isna(se) else f" ({se:.2f})")


def cstar(x):
    """A breakeven cost in words."""
    if x is None or (isinstance(x, float) and np.isnan(x)):
        return "none (gross <= 0)"
    return "any (never trades)" if np.isinf(x) else f"{x:.2f}bp"


def pct(x):
    return "n/a" if pd.isna(x) else f"{x:.0%}"


def leg_words(b):
    """Every leg's cost, one row each: sleeve, leg, instrument, round trip, one way, observed, re-strike, basis."""
    rows = []
    for name, i in b.inputs.items():
        for c, (_, _, leg) in zip(i.costs, i.sleeve.legs):
            cfg = config.currency(leg.ccy)
            spec = cfg["costs"][c.expression]
            if "ticks_round_trip" in spec:
                ct = cfg["contracts"][cfg["expression"][c.expression]["contract"]]
                basis = (f"{spec['ticks_round_trip']:g} ticks of {ct['tick']['other']:g} + {ct['fee_per_side']:g} "
                         f"{leg.ccy} a side a contract")
            else:
                basis = f"{spec['round_trip_bp']:g}bp a round trip"
            rows.append({"sleeve": name, "leg": c.leg, "instrument": _label(i.sleeve, leg),
                         "round trip (bp)": f"{c.round_trip_bp:.3f}", "one way (bp)": f"{c.one_way_bp:.3f}",
                         "from": basis, "cost is": "tick-based (a listed contract)" if c.observed else "assumed",
                         "re-struck": f"every {c.restrike_months} months" if c.restrike_months else "no"})
    return pd.DataFrame(rows)


def futures_lines(b):
    """The tick-based cost of each futures leg, derived from its contract spec, in words."""
    out, seen = [], set()
    for i in b.inputs.values():
        for c, (_, _, leg) in zip(i.costs, i.sleeve.legs):
            if leg.contract is None or c.expression in seen:
                continue
            seen.add(c.expression)
            cfg = config.currency(leg.ccy)
            spec, ct = cfg["costs"][c.expression], leg.contract
            dv01 = instruments.contract_dv01(ct)
            spread = spec["ticks_round_trip"] * ct["tick"]["other"] / costs.BP_PRICE
            fee = 2.0 * ct["fee_per_side"] / dv01
            label = _label(i.sleeve, leg)
            out.append(
                f"{label}, from the contract spec in config: {spec['ticks_round_trip']:g} back-month ticks of "
                f"{ct['tick']['other']:g} (the fourth meeting's month is never the front one) = {spread:.3f}bp, plus "
                f"{ct['fee_per_side']:g} {leg.ccy} a side over {dv01:.4f} {leg.ccy} per bp a contract = {fee:.3f}bp: "
                f"{c.round_trip_bp:.3f}bp a round trip, {c.one_way_bp:.3f}bp one way per unit of DV01. "
                f"{spec['ticks_round_trip']:g} ticks a round trip is {spec['ticks_round_trip'] / 2:g} a side, the "
                f"cost of crossing a market {spec['ticks_round_trip']:g} ticks wide; the floor, crossing a one-tick "
                "market, is one tick a round trip. The tick is "
                f"{ct['exchange']}'s minimum price increment, not a measured bid-offer: the archive holds settles, not "
                "quotes, so there is no spread to measure, and a quote-based estimate would be a data purchase. The fee "
                "is assumed.")
    return out


def _range(per, key, fmt=sr):
    """', from x (a) to y (b)' over {name: stats}; empty with fewer than two known."""
    vals = {n: v[key] for n, v in per.items() if pd.notna(v[key])}
    if len(vals) < 2:
        return ""
    lo, hi = min(vals, key=vals.get), max(vals, key=vals.get)
    return f", from {fmt(vals[lo])} ({lo}) to {fmt(vals[hi])} ({hi})"


def _take(gross, net):
    """What costs did to a Sharpe, in words, from the numbers: halved, took a share, or deepened a loss."""
    if not gross > 0:
        return "the gross Sharpe is already at or below zero, and costs only deepen it"
    share = (gross - net) / gross
    if net <= 0:
        return f"costs take all of it and more ({share:.0%} of the gross Sharpe)"
    return "costs roughly halve it" if 0.4 <= share <= 0.6 else f"costs take {share:.0%} of it"


def _verdict(net, se):
    """The first bullet's head: the sign of a net Sharpe and whether it is two SEs from zero."""
    if not net > 0:
        return "loses money"
    return "earns, but within two SEs of zero" if net < 2 * se else "still earns"


def _row_means(grid, book, name):
    """Mean net Sharpe over each entry threshold's cells: {enter: mean}."""
    out = {}
    for (e, _), per in grid.items():
        out.setdefault(e, []).append(per[name]["net_sr"])
    return {e: float(np.nanmean(v)) for e, v in out.items()}


def _clear(vs, names):
    """The sleeves' breakevens against their configured costs, in words (vol-scaled)."""
    clear = [n for n in names if vs[n]["cstar_bp"] is not None and vs[n]["cstar_bp"] > vs[n]["mix_bp"]]
    short = [n for n in names if vs[n]["cstar_bp"] is not None and vs[n]["cstar_bp"] <= vs[n]["mix_bp"]]
    none = [n for n in names if vs[n]["cstar_bp"] is None]
    parts = [f"{n}: c* {cstar(vs[n]['cstar_bp'])}, {vs[n]['cstar_bp'] / vs[n]['mix_bp']:.1f} times its "
             f"configured {vs[n]['mix_bp']:.2f}bp" for n in clear]
    parts += [f"{n}: c* {cstar(vs[n]['cstar_bp'])}, below its configured {vs[n]['mix_bp']:.2f}bp" for n in short]
    if none:
        parts.append(f"{_and(none)}: no breakeven, {'its' if len(none) == 1 else 'their'} gross P&L at or below "
                     "zero before any cost")
    return clear, "; ".join(parts)


