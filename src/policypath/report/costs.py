"""The costs report: what each sleeve is worth net of costs, how fragile that is, and what it trades to get there.

Generated by `scripts/build_strategy.py`, never hand-edited: every number comes
from the sleeves run under the book's rules (`strategy/positions.py`), charged
by `strategy/costs.py`, and every sentence is a template filled from them.

The question is not "what is the Sharpe" but "how fragile
is it". So the report leads with the net Sharpe as a function of the cost
assumed, and the cost at which it stops working, in closed form.

**What is run.** A sleeve under one `Spec`: the rule (``positions.rule``,
hysteresis at (``positions.enter``, ``positions.exit``) = (1.0, 0.0), or
linear), the ELB treatment (``evaluation.elb.chosen``, flat, or exclude or
hold), and the sizing (vol-scaled, primary: each sleeve alone at the book's
vol target; or unit, one book DV01 a unit of s). Every number the report
prints says which. Each run is `expression.run` on the positions decided:
the expression seam, so the legs, marks and P&L are the expression layer's to the bit.

**The sample.** From the first session a position decided on the sleeve's
first z is held (first z + lag + 1) to its last session; the treatment says
which of those count (`positions.samples`). Sharpe is annualised by the
sleeve calendar's observed sessions a year (`backtest.metrics`), and every
one carries its standard error.

**The equal-risk sum** (`combine`): each sleeve's vol-scaled P&L (each alone at
the book's risk), summed into the next session of the book currency's
calendar, as the book's calendar has it; from the first session every
sleeve has started, and a session counts where any sleeve's treatment counts
it, with only what each sleeve's treatment keeps in it. It is a sum of sleeves, not the book: the covariance, the vol target on
the whole and the drawdown control are the book's. With unit sizing it is the
equal-DV01 sum.

**Turnover** is book DV01 traded, summed over legs. "Turns" divides it by the
mean gross DV01 held on the sessions with a position (every leg's |q|), so a
whole round trip is 2 turns however many legs a sleeve has, and a
vol-scaled sleeve's turnover is comparable with a unit one's.
"""

