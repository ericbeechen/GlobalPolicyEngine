def _leg_marks(b, name, near):
    """(x, words) marks for a sleeve's configured leg costs (every sleeve's for the sum), one per cluster.

    Costs within `near` bp of the cluster's first share one mark at it, named
    together: "gilt 1, ZQ 1.05".
    """
    picks = b.inputs.values() if name == SUM else [b.inputs[name]]
    found = {}
    for i in picks:
        for c, (_, _, leg) in zip(i.costs, i.sleeve.legs):
            found.setdefault(round(c.round_trip_bp, 6), []).append(_label(i.sleeve, leg))
    marks = []
    for x, labels in sorted(found.items()):
        words = f"{'/'.join(dict.fromkeys(labels))} {x:.3g}"
        if marks and x - marks[-1][0] < near:
            marks[-1] = (marks[-1][0], f"{marks[-1][1]}, {words}")
        else:
            marks.append((x, words))
    return marks


