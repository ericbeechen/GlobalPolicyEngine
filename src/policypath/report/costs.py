def grid_figure(b, path, theme="light"):
    """Net Sharpe over the hysteresis grid, per sleeve and for the sum (vol-scaled), the chosen cell outlined."""
    t = _style(theme)
    g = b.book["positions"]["grid"]
    here = (b.book["positions"]["enter"], b.book["positions"]["exit"])
    names = [SUM, *b.sleeves]
    cube = np.full((len(names), len(g["enter"]), len(g["exit"])), np.nan)
    for k, name in enumerate(names):
        for (e, x), per in b.grid["vol_scaled"].items():
            cube[k, g["enter"].index(e), g["exit"].index(x)] = per[name]["net_sr"]
    top = float(np.nanmax(np.abs(cube))) or 1.0
    cmap = LinearSegmentedColormap.from_list("sharpe", t["diverging"][::-1]).with_extremes(bad=t["surface"])   # red below 0, blue above
    fig, axes = plt.subplots(2, 3, figsize=(12, 7.6), gridspec_kw={"hspace": 0.45, "wspace": 0.18})
    for k, (ax, name) in enumerate(zip(axes.ravel(), names)):
        m = np.ma.masked_invalid(cube[k])
        image = ax.imshow(m, cmap=cmap, vmin=-top, vmax=top, origin="lower", aspect="auto")
        for i in range(len(g["enter"])):
            for j in range(len(g["exit"])):
                v = cube[k, i, j]
                if np.isnan(v):
                    continue
                fill = cmap((v + top) / (2 * top))
                ax.text(j, i, f"{v:+.2f}", ha="center", va="center", fontsize=7.5, color=_ink_on(fill[:3]))
        i, j = g["enter"].index(here[0]), g["exit"].index(here[1])
        ax.add_patch(Rectangle((j - 0.5, i - 0.5), 1, 1, fill=False, ec=t["ink"], lw=2))
        ax.set_xticks(range(len(g["exit"])), [f"{x:g}" for x in g["exit"]], fontsize=8)
        ax.set_yticks(range(len(g["enter"])), [f"{e:g}" for e in g["enter"]], fontsize=8)
        ax.set_xlabel("exit (z x side at or below)", fontsize=8)
        ax.set_ylabel("enter (|z| at or above)", fontsize=8)
        ax.grid(False)
        ax.tick_params(length=0)
        s = surface(b.grid["vol_scaled"], b.book, name)
        ax.set_title(name, loc="left", fontsize=10, fontweight="bold", color=t["ink"], pad=18)
        ax.text(0, 1.02, f"chosen {sr(s['net_sr'], s['net_se'])}; {pct(s['share_positive'])} of cells > 0",
                transform=ax.transAxes, fontsize=8, color=t["secondary"], va="bottom")
    bar = fig.colorbar(image, ax=axes.ravel().tolist(), fraction=0.02, pad=0.02)
    bar.set_label("net Sharpe", fontsize=8, color=t["secondary"])
    bar.ax.tick_params(labelsize=7, length=0)
    bar.outline.set_visible(False)
    s = surface(b.grid["vol_scaled"], b.book, SUM)
    spec = chosen(b.book)
    fig.text(0.125, 0.985, f"The hysteresis grid: the sum's net Sharpe runs from {sr(s['grid_min'])} to "
             f"{sr(s['grid_max'])}; the chosen pair {here} is outlined", fontsize=12, fontweight="bold",
             color=t["ink"], va="top")
    fig.text(0.125, 0.952, f"Net Sharpe per (enter, exit) pair, {TREATMENT_WORDS[spec.treatment]}, vol-scaled, "
             "configured costs. Blank: exit >= enter, not a rule. The pair was fixed before the grid was run.",
             fontsize=9, color=t["secondary"], va="top")
    fig.savefig(path, dpi=150, bbox_inches="tight")
    plt.close(fig)


