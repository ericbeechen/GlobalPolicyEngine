# ---- names -------------------------------------------------------------------------

def _label(sleeve, leg):
    return config.currency(leg.ccy)["expression"][config.SLEEVE_EXPRESSION[sleeve.kind]]["label"]


def _name(kind, label, id_):
    """One instrument id in words: "ZQ Apr 2027", "OIS forward 18 Mar-29 Apr 2027", "2y gilt"."""
    if kind == "futures_month":
        return f"{label} {pd.Period(id_, freq='M').start_time:%b %Y}"
    if kind == "curve_forward":
        a, b = (pd.Timestamp(d) for d in id_.split("/"))
        return f"{label} {a.day} {a:%b}{'' if a.year == b.year else f' {a.year}'}-{b.day} {b:%b %Y}"
    return f"{id_} {label}"


def leg_names(sleeve, leg):
    """The instrument `leg` selects on each session, in words (None where it has none)."""
    ids = leg.frame["id"]
    label = _label(sleeve, leg)
    words = {i: _name(leg.kind, label, i) for i in ids.dropna().unique()}
    return ids.map(words)


def names(sleeve):
    """The sleeve's instruments on each session in words: "ZQ Apr 2027", "2y vs 10y Treasury", "2y gilt vs 2y
    Treasury"."""
    legs = [leg for _, _, leg in sleeve.legs]
    labels = list(dict.fromkeys(_label(sleeve, leg) for leg in legs))
    if len(legs) > 1 and len(labels) == 1 and all(leg.funded for leg in legs):
        ids = pd.concat([leg.frame["id"] for leg in legs], axis=1)
        return ids.apply(lambda r: " vs ".join(r) + f" {labels[0]}" if r.notna().all() else None, axis=1)
    words = pd.concat([leg_names(sleeve, leg) for leg in legs], axis=1)
    return words.apply(lambda r: " vs ".join(r) if r.notna().all() else None, axis=1)


# ---- the panel ---------------------------------------------------------------------

def next_quarter(sleeve, parts, side, h):
    """What a unit position on `side`, decided at each session's close, earns over the `h` days after it executes.

    `parts` is the sleeve's unit-receive P&L by session (carry, roll, rate,
    total, bp). The position executes ``lag`` sessions on and is credited on
    every session after that within `h` calendar days of the execution, in
    what the sleeve holds on each. NaN where the window runs past the last
    session or there is no side.
    """
    days = sleeve.sessions
    n = len(days)
    cum = parts.reindex(days).fillna(0.0).cumsum().to_numpy()
    start = np.arange(n) + sleeve.lag
    at = np.minimum(start, n - 1)
    until = days[at] + pd.Timedelta(days=h)
    end = days.searchsorted(until, side="right") - 1
    out = cum[end] - cum[at]
    out[(start >= n) | (until > days[-1])] = np.nan
    return pd.DataFrame(out, index=days, columns=[f"next_{c}" for c in parts.columns]).mul(side, axis=0)


def sleeve_panel(sleeve, book, u=None):
    """One sleeve's rows of the book panel: the breakeven, the unit and linear-rule P&L, the next quarter.

    ``executed`` is the session a decision at the row's close executes on,
    where its next quarter starts.
    """
    h, pairs = book["carry"]["horizon_days"], book["carry"]["closure_min_pairs"]
    u = expression.unit(sleeve) if u is None else u
    ahead = expression.ahead(sleeve, h, pairs)
    parts = u.groupby("session")[PARTS].sum(min_count=1).reindex(sleeve.sessions)
    _, run = expression.run(sleeve, expression.linear(sleeve), u)
    executed = pd.Series(sleeve.sessions, index=sleeve.sessions).shift(-sleeve.lag)
    out = ahead.assign(instrument=names(sleeve), executed=executed)
    out = out.join(parts.add_prefix("unit_")).join(run[["position", *carry.PARTS, "pnl"]])
    out = out.join(next_quarter(sleeve, parts, ahead["side"], h))
    return out.reset_index().assign(sleeve=sleeve.name, kind=sleeve.kind)


def _group(cr_h, pays):
    """One session's breakeven group (`GROUPS`): earns if CR_h >= 0, else by E_h; None if it bleeds before phi_h.

    A session that earns carry and roll is "earns" whatever its E_h: an
    expected quarter below 0 there comes from a negative edge, not a bleed.
    """
    if cr_h >= 0:
        return "earns"
    if pd.isna(pays):
        return None
    return "bleeds_pays" if pays else "no_pay"


def group(frame):
    """Each row's breakeven group (`_group`); None before phi_h is known."""
    out = [_group(c, p) for c, p in zip(frame["cr_h_bp"], frame["pays"])]
    return pd.Series(out, index=frame.index, dtype=object).where(frame["pays"].notna())


def verdict(row):
    """A session's breakeven in words, for the tables: its group (`_group`), or "bleeds" before phi_h is known."""
    g = _group(row["cr_h_bp"], row["pays"])
    return "bleeds" if g is None else GROUPS[g]


def episodes(z, enter, exit):
    """Episodes under the hysteresis pair: entry, side and exit (NaT while open), one row each.

    Flat goes to side = sign(z) where |z| >= `enter`; a held side is out where
    z x side <= `exit` or z is missing, and in again on the other side that
    session if |z| >= `enter`.
    """
    rows, side = [], 0.0
    for day, v in z.items():
        if side and (np.isnan(v) or v * side <= exit):
            rows[-1]["exit"], side = day, 0.0
        if not side and abs(v) >= enter:
            side = float(np.sign(v))
            rows.append({"entry": day, "side": side, "exit": pd.NaT})
    return pd.DataFrame(rows, columns=["entry", "side", "exit"])


def closure_split(sleeve, paths, k, h):
    """An outright's closure over `h` days, whole sample, split into the market's move and the rule's.

    The gap is market - model at meeting `k` (`paths`, percent), so its
    closure -(gap_t+h - gap_t) is the market falling, -(market_t+h -
    market_t), plus the rule rising, model_t+h - model_t. Each is regressed on
    the de-meaned gap without an intercept over every pair (as `carry.closure`,
    unclipped): {"phi", "market", "rule"}, market + rule = phi. Only the
    market's part pays a position in the market's instrument.
    """
    at = paths[paths["k"] == k].set_index("session").reindex(sleeve.sessions)
    days, dev = sleeve.sessions, sleeve.component["dev_bp"].to_numpy()
    end = days.searchsorted(days + pd.Timedelta(days=h))
    inside = np.flatnonzero(end < len(days))
    moves = {"market": -at["market"].to_numpy() * 100.0, "rule": at["model"].to_numpy() * 100.0}
    ys = {name: v[end[inside]] - v[inside] for name, v in moves.items()}
    x = dev[inside]
    ok = ~(np.isnan(x) | np.isnan(ys["market"]) | np.isnan(ys["rule"]))
    out = {name: float(x[ok] @ y[ok] / (x[ok] @ x[ok])) for name, y in ys.items()}
    return {"phi": out["market"] + out["rule"], **out}


@dataclass
class Build:
    """Everything the report says: the book, the sleeves, the panel, and the checks run on them.

    `splits` is `closure_split` for each outright sleeve, by name.
    """
    book: dict
    sleeves: dict
    panel: pd.DataFrame
    units: dict
    checks: pd.DataFrame
    reproduced: list
    episodes: pd.DataFrame
    splits: dict


def build(world=None):
    """The five sleeves, their panel, checks 1 and 2 on every sleeve both ways, the end-to-end check, the episodes."""
    world = expression.World() if world is None else world
    book, sleeves = world.book, expression.build(world)
    units = {name: expression.unit(s) for name, s in sleeves.items()}
    frame = pd.concat([sleeve_panel(s, book, units[name]) for name, s in sleeves.items()], ignore_index=True)
    checks = pd.concat([expression.checks(s) for s in sleeves.values()], ignore_index=True)
    reproduced = [(name, s.ccys[0], *expression.backtest_residual(s, world.panel(s.ccys[0], "backtest")))
                  for name, s in sleeves.items() if s.kind == "outright" and s.legs[0][2].kind in PATH_MARKED]
    enter, exit = book["positions"]["enter"], book["positions"]["exit"]
    found = []
    for name, s in sleeves.items():
        e = episodes(s.component["z"], enter, exit)
        rows = frame[frame["sleeve"] == name].set_index("session").reindex(e["entry"])
        found.append(e.assign(sleeve=name).join(rows.drop(columns=["side", "sleeve"]).reset_index(drop=True)))
    h = book["carry"]["horizon_days"]
    splits = {name: closure_split(s, world.panel(s.ccys[0], "paths"), world.cfg(s.ccys[0])["backtest"]["horizon"], h)
              for name, s in sleeves.items() if s.kind == "outright"}
    return Build(book, sleeves, frame, units, checks, reproduced, pd.concat(found, ignore_index=True), splits)


def failures(b):
    """What the checks found wrong, in words: empty when every sleeve passes (`write` refuses to publish otherwise).

    Check 1 over carry.TOL_BP, check 2 with a session outside its bound, or
    the end-to-end reproduction off by carry.TOL_BP or more.
    """
    c = b.checks[b.checks["direction"] == 1]                  # a pay is the receive negated: the same sizes
    out = [f"{r['sleeve']}, {r['leg']}: identity residual {r['identity_max_bp']:.1e}bp"
           for _, r in c[~(c["identity_max_bp"] < carry.TOL_BP)].iterrows()]
    out += [f"{r['sleeve']}, {r['leg']}: {r['outside_bound']} sessions outside the revaluation bound"
            for _, r in c[c["outside_bound"] > 0].iterrows()]
    out += [f"{name}: {n} sessions, reproduces the {ccy} backtest to {diff:.1e}bp"
            for name, ccy, n, diff in b.reproduced if not (n > 0 and diff < carry.TOL_BP)]
    return out


def load(root=panels.PANEL_DIR):
    """``data/panel/book_expression.parquet``, as `build_expression.py` wrote it."""
    path = Path(root) / PANEL
    if not path.exists():
        raise FileNotFoundError(f"{path} is missing; run scripts/build_expression.py")
    return pd.read_parquet(path)


def latest(frame, date=None):
    """Each sleeve's last row on or before `date` (all rows if None), in the book's sleeve order."""
    rows = frame if date is None else frame[frame["session"] <= pd.Timestamp(date)]
    rows = rows.dropna(subset=["z"]).sort_values("session").groupby("sleeve", sort=False).tail(1)
    order = list(dict.fromkeys(frame["sleeve"]))
    return rows.set_index("sleeve").loc[[s for s in order if s in set(rows["sleeve"])]]


# ---- the numbers -------------------------------------------------------------------

def sample(frame, enter, signals=True):
    """The rows the breakeven statistics are over: a z, a phi_h, a complete next quarter; |z| >= enter if `signals`."""
    ok = frame["z"].notna() & frame["pays"].notna() & frame["next_total"].notna()
    return frame[ok & (frame["z"].abs() >= enter)] if signals else frame[ok]


def _mean(x):
    return float(x.mean()) if len(x) else np.nan


def breakeven(rows):
    """The breakeven statistics of one set of rows: shares, and the next quarter's mean P&L by group."""
    g = group(rows)
    right = rows["next_rate"] > 0
    nxt = rows["next_total"]
    lost = right & (nxt < 0)
    return {
        "sessions": len(rows), "bleeding": float(rows["bleeding"].mean()), "no_pay": float((g == "no_pay").mean()),
        "shares": {k: float((g == k).mean()) for k in GROUPS},
        "right": float(right.mean()), "right_sessions": int(right.sum()),
        "right_but_lost": float((nxt[right] < 0).mean()) if right.any() else np.nan,
        "right_but_lost_sessions": int(lost.sum()), "right_but_lost_rate_bp": _mean(rows.loc[lost, "next_rate"]),
        "right_but_lost_carry_roll_bp": _mean(rows.loc[lost, "next_carry"] + rows.loc[lost, "next_roll"]),
        "expected_bp": _mean(rows["expected_bp"]), "next_bp": _mean(nxt),
        "next_bleeding_bp": _mean(nxt[rows["bleeding"]]), "next_rest_bp": _mean(nxt[~rows["bleeding"]]),
        "next_no_pay_bp": _mean(nxt[g == "no_pay"]), "next_pays_bp": _mean(nxt[g != "no_pay"]),
        "next_by_group_bp": {k: _mean(nxt[g == k]) for k in GROUPS},
        "count_by_group": {k: int((g == k).sum()) for k in GROUPS},
    }


def insight(frame, enter):
    """{sleeve: {"signals": breakeven, "all": breakeven}}, plus the sleeves pooled under ``"pooled"``."""
    out = {name: {"signals": breakeven(sample(rows, enter)), "all": breakeven(sample(rows, enter, False))}
           for name, rows in frame.groupby("sleeve", sort=False)}
    out["pooled"] = {"signals": breakeven(sample(frame, enter)), "all": breakeven(sample(frame, enter, False))}
    return out


def window_label(start, end):
    """A window in words: "2022" for a calendar year, else "Dec 2021 to Aug 2023"."""
    if (start.month, start.day, end.month, end.day) == (1, 1, 12, 31) and start.year == end.year:
        return f"{start.year}"
    return f"{start:%b %Y} to {end:%b %Y}"


def overlaps(frame, start, end, h):
    """Rows whose next quarter, credited on the sessions after ``executed`` to `h` days on, overlaps [start, end]."""
    return (frame["executed"] < end) & (frame["executed"] + pd.Timedelta(days=h) >= start)


def excluded(frame, enter, windows, h):
    """The signal statistics leaving out every quarter that overlaps each window: {name: {label, pooled, per}}.

    `windows` is ``evaluation.exclude`` ({name: [start, end]}); ``per`` is by sleeve.
    """
    out = {}
    for name, (start, end) in windows.items():
        start, end = pd.Timestamp(start), pd.Timestamp(end)
        rows = frame[~overlaps(frame, start, end, h)]
        out[name] = {"label": window_label(start, end), "start": start, "end": end,
                     "pooled": breakeven(sample(rows, enter)),
                     "per": {n: breakeven(sample(r, enter)) for n, r in rows.groupby("sleeve", sort=False)}}
    return out


def per_quarter(frame, h):
    """The median number of a sleeve's sessions inside one `h`-day quarter: how many sessions share each outcome."""
    counts = []
    for _, rows in frame.groupby("sleeve", sort=False):
        days = pd.DatetimeIndex(rows["session"].sort_values())
        counts.append(days.searchsorted(days + pd.Timedelta(days=h), side="right") - np.arange(len(days)))
    return int(np.median(np.concatenate(counts)))


def carry_filter(eps):
    """The diagnostic: per sleeve, the episode entries a "does not pay" filter would skip, and their next quarters."""
    rows = []
    for name, e in eps.groupby("sleeve", sort=False):
        e = e[e["pays"].notna() & e["next_total"].notna()]
        skip = group(e) == "no_pay"
        rows.append({"sleeve": name, "entries": len(e), "skipped": int(skip.sum()),
                     "skipped_next_bp": _mean(e.loc[skip, "next_total"]),
                     "kept_next_bp": _mean(e.loc[~skip, "next_total"]),
                     "all_sum_bp": float(e["next_total"].sum()),
                     "kept_sum_bp": float(e.loc[~skip, "next_total"].sum())})
    out = pd.DataFrame(rows)
    return out.assign(effect_bp=out["kept_sum_bp"] - out["all_sum_bp"])


def by_year(frame, columns, live="position"):
    """Sums of `columns` by sleeve and calendar year, over the rows where `live` is known."""
    rows = frame[frame[live].notna()]
    return rows.groupby(["sleeve", rows["session"].dt.year.rename("year")], sort=False)[columns].sum()


def convexity(units):
    """The full revaluation's residual (full - linear) of a unit receive, summed by year: session x sleeve, bp."""
    per = {name: u.assign(res=u["full_bp"] - u["total"]).groupby("session")["res"].sum(min_count=1)
           for name, u in units.items()}
    wide = pd.DataFrame(per)
    return wide.groupby(wide.index.year).sum(min_count=1).rename_axis("year")


def correlations(sleeves, frame):
    """Per currency with an outright and a curve sleeve: corr(level z, slope z) raw and orthogonal, and of their P&L."""
    rows = []
    singles = list(dict.fromkeys(s.ccys[0] for s in sleeves.values() if len(s.ccys) == 1))
    for ccy in singles:
        mine = {s.kind: s for s in sleeves.values() if s.ccys == (ccy,)}
        if not {"outright", "curve"} <= set(mine):
            continue
        level, slope = mine["outright"].component, mine["curve"].component
        wide = frame[frame["sleeve"].isin([mine["outright"].name, mine["curve"].name])]
        pnl = wide.pivot(index="session", columns="kind", values="pnl").where(
            wide.pivot(index="session", columns="kind", values="position").notna())
        unit = wide.pivot(index="session", columns="kind", values="unit_total")
        rows.append({"ccy": ccy, "level_raw_slope_z": level["z"].corr(slope["raw_z"]),
                     "level_orthogonal_slope_z": level["z"].corr(slope["z"]),
                     "curve_outright_pnl": pnl["curve"].corr(pnl["outright"]),
                     "curve_outright_unit": unit["curve"].corr(unit["outright"])})
    return pd.DataFrame(rows)


def positions(sleeve, row):
    """The legs of a UNIT-per-bp position on the side of `row` (the sleeve's latest), in each instrument's own units."""
    out = []
    day = row.name if isinstance(row.name, pd.Timestamp) else row["session"]
    for label, sign, leg in sleeve.legs:
        q = row["side"] * sign * UNIT
        native = float(instruments.native(leg, pd.Series(q, index=leg.frame.index)).loc[day])
        units = f"{abs(native):,.0f} contracts" if leg.contract is not None else f"{leg.ccy} {abs(native) / 1e6:,.1f}m"
        out.append({"leg": label, "side": SIDE[float(np.sign(q))], "instrument": leg_names(sleeve, leg).loc[day],
                    "dv01": f"{q:+,.0f}", "position": units})
    return out


def contracts(sleeves):
    """Every futures contract the sleeves trade: its DV01 and tick values derived, and its exchange's quotes.

    The quotes are data (``contracts.<c>.quoted``), so derived against quoted
    is a comparison with a published number, not with a rounding of our own.
    """
    rows = []
    for s in sleeves.values():
        for _, _, leg in s.legs:
            if leg.contract is None:
                continue
            c, q = leg.contract, leg.contract["quoted"]
            dv01, ticks = instruments.contract_dv01(c), instruments.tick_values(c)
            key = config.currency(leg.ccy)["expression"][config.SLEEVE_EXPRESSION[s.kind]]["contract"]
            rows.append({"name": _label(s, leg), "key": key, "ccy": leg.ccy, "exchange": c["exchange"],
                         "notional": c["notional"], "days": c["accrual"]["days"],
                         "year_days": c["accrual"]["year_days"], "dv01": dv01, "dv01_quoted": q["dv01"],
                         "ticks": {k: {"tick": c["tick"][k], "value": v, "quoted": q["tick"][k]}
                                   for k, v in ticks.items()}})
    return list({r["name"]: r for r in rows}.values())


def _contract_lines(ct):
    """The DV01 derivation of one contract, and how it compares with its exchange's quotes."""
    front, other = ct["ticks"]["front"], ct["ticks"]["other"]
    cent = round(ct["dv01"], 2) == ct["dv01_quoted"]
    per_tick = all(abs(ct["dv01_quoted"] * t["tick"] / 0.01 - t["quoted"]) < 1e-9 for t in (front, other))
    return (f"{ct['name']} DV01, from the contract spec in config: {ct['notional']:,.0f} x {ct['days']}/"
            f"{ct['year_days']} x 1bp = {ct['dv01']:.4f} {ct['ccy']} per bp a contract. {ct['exchange']} quotes "
            f"{ct['dv01_quoted']:.2f} (`contracts.{ct['key']}.quoted`), "
            + ("the derived value rounded to the cent" if cent else
               f"{ct['dv01_quoted'] - ct['dv01']:+.4f} from the derived value") +
            f". Ticks: {front['tick']:g} (front month) = {front['value']:.4f} and {other['tick']:g} = "
            f"{other['value']:.4f}; {ct['exchange']} quotes {front['quoted']:.4f} and {other['quoted']:.4f}"
            + (", its rounded DV01 times the tick" if per_tick else "") +
            ". No DV01 is typed in code (a test checks).")


# ---- the words ---------------------------------------------------------------------

def _and(words):
    """"a", "a and b", "a, b and c"."""
    words = list(words)
    return words[0] if len(words) == 1 else ", ".join(words[:-1]) + " and " + words[-1]


def pct(x):
    return "n/a" if pd.isna(x) else f"{x:.0%}"


def bp(x, digits=1):
    return "n/a" if pd.isna(x) else f"{x:+.{digits}f}"


def _range(stats, key, fmt=pct):
    """', from x (sleeve) to y (sleeve)' over the sleeves' signal statistics; empty with fewer than two sleeves."""
    vals = {n: v["signals"][key] for n, v in stats.items() if n != "pooled" and pd.notna(v["signals"][key])}
    if len(vals) < 2:
        return ""
    lo, hi = min(vals, key=vals.get), max(vals, key=vals.get)
    return f", from {fmt(vals[lo])} ({lo}) to {fmt(vals[hi])} ({hi})"


def example(eps):
    """The episode entry that shows the week's point most plainly: right on the rate, and the most carry and roll lost.

    Over entries whose next quarter's rate component was in the side's favour
    and whose total was negative; None if there are none.
    """
    e = eps[(eps["next_rate"] > 0) & (eps["next_total"] < 0)]
    if e.empty:
        return None
    return e.loc[(e["next_carry"] + e["next_roll"]).idxmin()]


def _example(eps):
    r = example(eps)
    if r is None:
        return ""
    return (f" The plainest case at an episode entry: {r['sleeve']}, {SIDE[float(r['side'])]} on "
            f"{r['entry'].day} {r['entry']:%b %Y} at z {r['z']:+.1f} ({r['instrument']}). The rate moved the "
            f"signal's way by "
            f"{bp(r['next_rate'])}bp over the quarter, carry and roll took {bp(r['next_carry'] + r['next_roll'])}bp, "
            f"and the quarter ended {bp(r['next_total'])}bp.")


def count(per, a, b, more=False):
    """(sleeves where a < b, or a > b with `more`; sleeves where both are known), over {sleeve: breakeven}."""
    known = [v for v in per.values() if pd.notna(v[a]) and pd.notna(v[b])]
    return sum((v[a] > v[b]) if more else (v[a] < v[b]) for v in known), len(known)


def flags(p):
    """How many of the breakeven's two flags did worse over the next quarter: bleeding, and not paying (0-2)."""
    return int(p["next_bleeding_bp"] < p["next_rest_bp"]) + int(p["next_no_pay_bp"] < p["next_pays_bp"])


VERDICTS = {
    2: ("The breakeven picked out the worse quarters", "In this sample the signals it flagged did worse."),
    1: ("The breakeven sorted the quarters only in part", "One of its two flags did worse, the other did not."),
    0: ("The breakeven did not pick out the losers", "In this sample carry and roll are a cost to charge "
        "against the edge, not a reason to stand aside."),
}
FLAGS = {2: "both flags did worse", 1: "one flag did worse", 0: "neither flag did worse"}


def judgement(full, without):
    """The verdict's (head, tail): the full sample's (`VERDICTS`), unless leaving out a window changes it.

    `full` is the pooled signal breakeven, `without` is `excluded`'s.
    """
    score = flags(full)
    for w in without.values():
        other = flags(w["pooled"])
        if other != score:
            return (f"The breakeven's verdict turns on {w['label']}",
                    f"In the full sample {FLAGS[score]}; without {w['label']} {FLAGS[other]}. Carry and roll are a "
                    "cost to charge against the edge either way; whether they are a reason to stand aside, this "
                    "sample cannot say.")
    return VERDICTS[score]


def _unfunded(b, rows):
    """The right-but-lost sessions on sleeves with no funded leg, as a sentence; empty if there are none."""
    names = [n for n, s in b.sleeves.items() if not any(leg.funded for _, _, leg in s.legs)]
    n = int(rows["sleeve"].isin(names).sum())
    if not n:
        return ""
    return (f" {n:,} of them are on the unfunded sleeves ({', '.join(names)}), where carry is 0: there right on "
            "the rate means the held contracts beat the frozen curve's roll, and the loss means their own rates "
            "moved against the side, by less than the roll implied.")


def _without(w):
    """One excluded window's line: bleeding and not paying against the rest, with the sleeve counts."""
    q, each = w["pooled"], w["per"]
    b_worse, b_n = count(each, "next_bleeding_bp", "next_rest_bp")
    n_worse, n_n = count(each, "next_no_pay_bp", "next_pays_bp")
    return (f"Leaving out every quarter that overlaps {w['label']} ({q['sessions']:,} signal sessions left): "
            f"bleeding {bp(q['next_bleeding_bp'])}bp against {bp(q['next_rest_bp'])}bp (worse in {b_worse} of "
            f"{b_n} sleeves), not paying {bp(q['next_no_pay_bp'])}bp against {bp(q['next_pays_bp'])}bp (worse in "
            f"{n_worse} of {n_n}).")


def _expected(stats, over, n_over, splits):
    """The expected-quarter bullet: E_h against the realized quarter, and each outright's closure split."""
    p = stats["pooled"]["signals"]
    high = p["expected_bp"] > p["next_bp"]
    text = (f"- **The expected quarter {'overstates' if high else 'understates'}.** {bp(p['expected_bp'])}bp a signal "
            f"session on average, against {bp(p['next_bp'])}bp realized (it is higher in {over} of the {n_over} "
            "sleeves).")
    if not splits:
        return text
    parts = []
    for name, sp in splits.items():
        s = stats[name]["signals"]
        parts.append(f"a quarter closed {sp['phi']:.2f} of the {name} gap, {sp['market']:.2f} by the market and "
                     f"{sp['rule']:+.2f} by the rule ({'toward' if sp['rule'] > 0 else 'away from'} the market), "
                     f"and E_h there is {bp(s['expected_bp'])}bp against {bp(s['next_bp'])}bp realized")
    return (text + " E_h counts every bp of the gap that closes as P&L, but only the market's part pays; the rule's "
            "part pays nothing. Over the whole sample " + "; ".join(parts) + ".")


def answer(b, stats, filt, without):
    """The report's opening bullets: the week's insight, in numbers, each worded by what the numbers say.

    `without` is `excluded`'s: the verdict on the breakeven reads it too.
    """
    p = stats["pooled"]["signals"]
    per = {k: v["signals"] for k, v in stats.items() if k != "pooled"}
    worse, n_worse = count(per, "next_bleeding_bp", "next_rest_bp")
    no_pay, n_no_pay = count(per, "next_no_pay_bp", "next_pays_bp")
    over, n_over = count(per, "expected_bp", "next_bp", more=True)
    head, tail = judgement(p, without)
    sig = sample(b.panel, b.book["positions"]["enter"])
    lost = sig[(sig["next_rate"] > 0) & (sig["next_total"] < 0)]
    h = b.book["carry"]["horizon_days"]
    lines = [
        f"- **A correct signal can still be a losing trade.** Of the {p['right_sessions']:,} signal sessions whose "
        f"next quarter went the signal's way on the rate, {pct(p['right_but_lost'])} "
        f"({p['right_but_lost_sessions']:,}) still lost money once carry and roll were counted"
        f"{_range(stats, 'right_but_lost')}. On those the rate made {bp(p['right_but_lost_rate_bp'])}bp a unit "
        f"on average and carry and roll took {bp(p['right_but_lost_carry_roll_bp'])}bp." + _unfunded(b, lost)
        + _example(b.episodes),
        f"- **Right but bleeding, known at the close.** On {pct(p['bleeding'])} of the {p['sessions']:,} signal "
        "sessions the instrument's carry and roll over the next quarter, if the curve stood still, ran against the "
        f"side{_range(stats, 'bleeding')}. {pct(p['no_pay'])} did not pay for their bleed: the expected quarter "
        "(the share of the gap that has historically closed, plus carry and roll on the rest) was negative"
        f"{_range(stats, 'no_pay')}.",
        f"- **{head}.** Bleeding signal sessions earned {bp(p['next_bleeding_bp'])}bp a unit over the next quarter, "
        f"the others {bp(p['next_rest_bp'])}bp; bleeding did worse in {worse} of the {n_worse} sleeves. Those that did "
        f"not pay earned {bp(p['next_no_pay_bp'])}bp, the rest {bp(p['next_pays_bp'])}bp (worse in {no_pay} of the "
        f"{n_no_pay}). " + "".join(_without(w) + " " for w in without.values()) + tail
        + f" The quarters overlap (about {per_quarter(b.panel, h)} sessions share each one), so these are "
        "descriptions, not tests.",
    ]
    skipped, entries = int(filt["skipped"].sum()), int(filt["entries"].sum())
    if skipped:
        eps = b.episodes[b.episodes["pays"].notna() & b.episodes["next_total"].notna()]
        skip = group(eps) == "no_pay"
        effect = filt["effect_bp"].sum()
        top = filt.loc[filt["effect_bp"].abs().idxmax()]
        entry_worse = eps.loc[skip, "next_total"].mean() < eps.loc[~skip, "next_total"].mean()
        agree = entry_worse == (p["next_no_pay_bp"] < p["next_pays_bp"])
        lines.append(
            f"- **The carry filter, a diagnostic.** At entry, where a filter would act, the {skipped} of {entries} "
            "episode entries that did not pay "
            f"earned {bp(eps.loc[skip, 'next_total'].mean())}bp over their next quarter against "
            f"{bp(eps.loc[~skip, 'next_total'].mean())}bp for the rest"
            f"{'' if agree else ', the other way from the sessions'}. Skipping them would have "
            f"{'added' if effect > 0 else 'cost'} {abs(effect):.0f}bp, {bp(top['effect_bp'], 0)}bp of it from "
            f"{int(top['skipped'])} {top['sleeve']} entries. {skipped} entries are too few to decide on: the carry "
            "filter stays a diagnostic (`positions.carry_filter: false`), and week 8 measures it under the "
            "hysteresis rule with costs.")
    lines.append(_expected(stats, over, n_over, b.splits))
    return lines


def _checks_table(b):
    c = b.checks
    rows = c.assign(direction=c["direction"].map(SIDE))
    rows = rows[["sleeve", "leg", "direction", "sessions", "identity_max_bp", "full_residual_max_bp",
                 "bound_at_max_bp", "outside_bound", "stale", "fx_stale"]]
    return rows.assign(identity_max_bp=rows["identity_max_bp"].map(lambda x: f"{x:.1e}"),
                       full_residual_max_bp=rows["full_residual_max_bp"].map(lambda x: f"{x:.3f}"),
                       bound_at_max_bp=rows["bound_at_max_bp"].map(lambda x: f"{x:.3f}"))


def _instruments_table(b):
    rows = []
    for name, s in b.sleeves.items():
        for label, sign, leg in s.legs:
            cfg = config.currency(leg.ccy)
            x = cfg["expression"][config.SLEEVE_EXPRESSION[s.kind]]
            k = ORDINAL[cfg["backtest"]["horizon"]]
            tenor = leg.frame["id"].iloc[-1]
            if leg.kind == "futures_month":
                marks, per = f"{cfg['market']['futures']['source']} {x['contract']} settles", "a contract"
                dv01 = f"{leg.frame['dv01'].iloc[-1]:,.4f}"
            elif leg.kind == "curve_forward":
                marks, per = f"{cfg['market']['curve']['source']} {cfg['market']['curve']['series']}", "1m notional"
                dv01 = f"{leg.frame['dv01'].iloc[-1] * 1e6:,.2f}"
            else:
                series = x["series"] if isinstance(x["series"], str) else ", ".join(x["series"].values())
                marks, per = f"{x['source']} {series}", "1m notional"
                dv01 = f"{leg.frame['dv01'].iloc[-1] * 1e6:,.2f}"
            rows.append({"sleeve": name, "leg": label, "on a receive": SIDE[float(sign)],
                         "instrument": DESCRIBE[leg.kind].format(label=x["label"], k=k, tenor=tenor),
                         "marks": marks, "funded": "yes" if leg.funded else "no",
                         "DV01 (latest)": f"{dv01} {leg.ccy} per bp, {per}"})
    return pd.DataFrame(rows)


def _current_table(b):
    now = latest(b.panel)
    rows = []
    for name, r in now.iterrows():
        rows.append({"sleeve": name, "session": r["session"], "z": f"{r['z']:+.2f}", "side": SIDE[float(r['side'])],
                     "instrument": r["instrument"], "gap_bp": bp(r["value_bp"]), "edge_bp": bp(r["edge_bp"]),
                     "carry_bp": bp(r["carry_h_bp"]), "roll_bp": bp(r["roll_h_bp"]), "CR_h_bp": bp(r["cr_h_bp"]),
                     "phi_h": f"{r['phi_h']:.2f}", "E_h_bp": bp(r["expected_bp"]), "verdict": verdict(r)})
    return pd.DataFrame(rows), now


def _stats_tables(stats):
    share, earned = [], []
    for name, v in stats.items():
        for which in ("signals", "all"):
            s = v[which]
            head = {"sleeve": name, "set": which, "sessions": f"{s['sessions']:,}"}
            share.append({**head, **{w: pct(s["shares"][k]) for k, w in GROUPS.items()},
                          "bleeds (CR_h < 0 < edge)": pct(s["bleeding"]), "right next quarter": pct(s["right"]),
                          "right but lost": pct(s["right_but_lost"])})
            earned.append({**head, "expected E_h": bp(s["expected_bp"]), "realized": bp(s["next_bp"]),
                           **{w: bp(s["next_by_group_bp"][k]) for k, w in GROUPS.items()},
                           "bleeding": bp(s["next_bleeding_bp"]), "not bleeding": bp(s["next_rest_bp"])})
    return pd.DataFrame(share), pd.DataFrame(earned)


FILTER_COLUMNS = {"skipped_next_bp": "skipped: mean", "kept_next_bp": "kept: mean", "all_sum_bp": "all: sum",
                  "kept_sum_bp": "kept: sum", "effect_bp": "the filter's effect"}


def _filter_table(filt):
    means = {c: filt[c].map(bp) for c in ["skipped_next_bp", "kept_next_bp"]}
    sums = {c: filt[c].map(lambda x: bp(x, 0)) for c in ["all_sum_bp", "kept_sum_bp", "effect_bp"]}
    return filt.assign(**means, **sums).rename(columns=FILTER_COLUMNS)


def _slope_words(b):
    """The slope component in words, from the book's ``signal`` block and the curve sleeves' currencies."""
    lo, hi = b.book["signal"]["slope"]
    k = {config.currency(c)["backtest"]["horizon"] for s in b.sleeves.values() if s.kind == "curve" for c in s.ccys}
    windows = {pd.Timedelta(config.currency(c)["signal"]["window"]).days
               for s in b.sleeves.values() if s.kind == "curve" for c in s.ccys}
    text = f"the gap at the {ORDINAL[hi]} meeting minus the gap at the {ORDINAL[lo]}"
    if b.book["signal"]["slope_orthogonal"]:
        text += (f", less the part the level gap (the {_and(ORDINAL[x] for x in sorted(k))} meeting's) explains "
                 f"over the trailing {' or '.join(str(d) for d in sorted(windows))} days")
    return text


