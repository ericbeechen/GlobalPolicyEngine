def _ink_on(fill):
    """Text colour for a label set inside `fill`: ink by the fill's luminance."""
    r, g, b = to_rgb(fill)
    return THEMES["light"]["ink"] if 0.2126 * r + 0.7152 * g + 0.0722 * b > 0.45 else THEMES["dark"]["ink"]


