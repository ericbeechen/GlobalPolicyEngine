"""The expression layer's report: what each sleeve trades, the checks on its P&L, and what holding it costs.

Generated by `scripts/build_expression.py`, never hand-edited: every number
comes from the sleeves (`strategy/expression.py`) and every sentence is a
template filled from them. `build` makes the book's panel (one row per sleeve
and session); the report, the figure, ``reports/results/expression.json`` (the
note's numbers) and ``reports/results/signals.csv`` (one row per signal
episode) are views of it.

The week's question is the plan's: can a correct signal still be a losing
trade? Four definitions carry the answer.

- A **signal** is a session with |z| >= ``positions.enter`` (1). An
  **episode** is a run of them under the book's hysteresis pair: it starts
  where |z| reaches ``enter`` and ends where z x side falls to ``exit`` (0), the
  rule week 8 trades.
- **The next quarter** of a session is what a unit position on its side,
  decided at its close, earns over the ``carry.horizon_days`` (91) after it
  executes: the sleeve's own P&L, re-selecting its instrument as the sleeve
  does, by component, no costs. It is an outcome, never an input: the
  breakeven on a session uses only what was known at its close.
- A quarter is **right** when its rate component is in the side's favour: the
  curve moved the way the signal said, against the frozen curve (the roll).
  **Right but lost** is a right quarter with a negative total: carry and roll
  took more than the move gave. On an unfunded leg (a futures month, a
  forward) carry is 0 and the total is the held contract's own rate change,
  so there a right quarter that lost is one where the contract's rate moved
  against the side, by less than the frozen curve implied.
- Each signal falls in one of three groups by its breakeven
  (`strategy/carry.py`). It **earns** carry and roll over the quarter (CR_h >=
  0), it **bleeds but pays** (CR_h < 0 and the expected quarter E_h >= 0), or
  it **does not pay** (E_h < 0). Shares and means are over the sessions with a
  phi_h (a year of closures first) and a complete next quarter, and those
  quarters overlap: 60-odd sessions share each one.

Quarters overlap and a few episodes (2022 above all) carry most of the P&L,
so the realized comparisons are descriptions, not tests: each is also shown
leaving out every quarter that overlaps a window of
``evaluation.exclude`` (`excluded`), and the verdict says when that changes it.
The expected quarter's closure is split into the market's move and the rule's
(`closure_split`): only the market's part of a closing gap pays.
"""

