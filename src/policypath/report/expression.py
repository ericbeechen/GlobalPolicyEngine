def signals(eps):
    """reports/results/signals.csv: one row per episode, derived numbers only."""
    cols = {"entry": "entry", "sleeve": "sleeve", "side": "side", "z": "z", "instrument": "instrument",
            "value_bp": "gap_bp", "edge_bp": "edge_bp", "carry_h_bp": "carry_h_bp", "roll_h_bp": "roll_h_bp",
            "cr_h_bp": "cr_h_bp", "phi_star": "phi_star", "phi_h": "phi_h", "expected_bp": "expected_bp",
            "bleeding": "bleeding", "pays": "pays", "next_total": "next_pnl_bp", "exit": "exit"}
    out = eps[list(cols)].rename(columns=cols)
    out = out.assign(next_carry_roll_bp=eps["next_carry"] + eps["next_roll"], next_rate_bp=eps["next_rate"],
                     side=eps["side"].map(SIDE))
    numbers = out.select_dtypes("number").columns
    return out.sort_values(["entry", "sleeve"]).round({c: 3 for c in numbers}).replace(-0.0, 0.0)


def _plain(x):
    if isinstance(x, dict):
        return {str(k): _plain(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [_plain(v) for v in x]
    if isinstance(x, pd.Timestamp):
        return f"{x:%Y-%m-%d}"
    if isinstance(x, (np.floating, float)):
        return None if np.isnan(x) else float(f"{x:.6g}")
    if isinstance(x, (np.integer, np.bool_)):
        return x.item()
    return x


def results(b, stats, filt, corr, without):
    """reports/results/expression.json: the numbers the note quotes, to six significant figures."""
    c = b.checks
    now = latest(b.panel)
    first, last = b.panel.dropna(subset=["z"])["session"].agg(["min", "max"])
    return _plain({
        "sessions": [first, last], "horizon_days": b.book["carry"]["horizon_days"],
        "enter": b.book["positions"]["enter"], "exit": b.book["positions"]["exit"],
        "breakeven": stats,
        "without": {name: {"window": [w["start"], w["end"]], "signals": w["pooled"], "per_sleeve": w["per"]}
                    for name, w in without.items()},
        "closure_split": b.splits,
        "carry_filter": filt.set_index("sleeve").to_dict("index"),
        "checks": {"identity_max_bp": c["identity_max_bp"].max(),
                   "full_residual_max_bp": c["full_residual_max_bp"].max(),
                   "outside_bound": int(c["outside_bound"].sum() // 2),
                   "legs": c[c["direction"] == 1].set_index(["sleeve", "leg"])[
                       ["sessions", "identity_max_bp", "full_residual_max_bp", "bound_at_max_bp", "stale",
                        "fx_stale"]].reset_index().to_dict("records"),
                   "reproduced": [{"sleeve": n, "backtest": ccy, "sessions": k, "max_bp": d}
                                  for n, ccy, k, d in b.reproduced]},
        "convexity_bp_per_year": convexity(b.units).mean().to_dict(),
        "contracts": contracts(b.sleeves),
        "correlations": corr.set_index("ccy").to_dict("index"),
        "episodes": len(b.episodes),
        "now": {name: {"session": r["session"], "z": r["z"], "side": SIDE[float(r["side"])],
                       "instrument": r["instrument"], "gap_bp": r["value_bp"], "edge_bp": r["edge_bp"],
                       "cr_h_bp": r["cr_h_bp"],
                       "expected_bp": r["expected_bp"], "verdict": verdict(r)} for name, r in now.iterrows()},
    })


def write(b, root, panel_root=panels.PANEL_DIR):
    """Every output of the build under repo `root` (the panel under `panel_root`). Returns the paths and the stats.

    Refuses (ValueError, nothing written) if a check failed (`failures`).
    """
    wrong = failures(b)
    if wrong:
        raise ValueError("the checks failed, so no report is written:\n" + "\n".join(wrong))
    root = Path(root)
    enter, h = b.book["positions"]["enter"], b.book["carry"]["horizon_days"]
    stats = insight(b.panel, enter)
    without = excluded(b.panel, enter, b.book["evaluation"]["exclude"], h)
    filt = carry_filter(b.episodes)
    corr = correlations(b.sleeves, b.panel)
    out = {"panel": Path(panel_root) / PANEL, "report": root / "reports" / "expression.md",
           "json": root / "reports" / "results" / "expression.json",
           "signals": root / "reports" / "results" / "signals.csv"}
    for p in out.values():
        p.parent.mkdir(parents=True, exist_ok=True)
    b.panel.to_parquet(out["panel"], index=False)
    out["report"].write_text(markdown(b, stats, filt, corr, without), encoding="utf-8")
    out["json"].write_text(json.dumps(results(b, stats, filt, corr, without), indent=1) + "\n", encoding="utf-8")
    signals(b.episodes).to_csv(out["signals"], index=False, date_format="%Y-%m-%d")
    figures = root / "reports" / "figures"
    figures.mkdir(parents=True, exist_ok=True)
    for theme in THEMES:
        p = figures / f"carry_{theme}.png"
        figure(stats, list(b.sleeves), h, enter, p, theme)
        out[f"figure_{theme}"] = p
    return out, stats, filt
