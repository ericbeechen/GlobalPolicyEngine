"""The model path against the market path: coverage, the gap at named moments, the crude backtest.

Generated by `scripts/build_model.py`, never hand-edited.
"""

import pandas as pd
from policypath.backtest import engine, policy
from policypath.report.coverage import table

def snapshot(day, paths, summaries, sessions, signal):
    """Everything the chart and the page say about one session."""
    s = sessions.set_index("session").loc[day]
    rule = summaries.set_index("session").loc[day]
    sig = signal[signal["session"] == day].set_index("k")[["gap_bp", "z", "window_mean_bp", "window_sd_bp"]]
    m = paths[paths["session"] == day].set_index("k").join(sig).reset_index()
    return {"session": day, "rate_now": s["rate_now"], "last_fixing": s["last_fixing"],
            "model_now": rule["r0"] + rule["spread_bp"] / 100.0, "rule": rule, "meetings": m}


def checks(sessions, summaries, paths, signal, meetings, spec):
    """Every section as a named DataFrame, a dict of headline numbers, and the backtest result."""
    k, n = spec["backtest"]["horizon"], spec["path"]["n_meetings"]
    # Days the gap should be able to explain (config ``report.moments``), each read on the first
    # session on or after it.
    moments = spec["report"]["moments"]
    ok = sessions[sessions["error"].isna()]
    gap = signal.pivot(index="session", columns="k", values="gap_bp")
    z = signal.pivot(index="session", columns="k", values="z")
    rule = summaries.set_index("session")

    at = [gap.index[gap.index >= pd.Timestamp(d)][0] for d, _ in moments]
    named = pd.DataFrame({
        "session": at, "moment": [label for _, label in moments],
        "gap_k1": gap.loc[at, 1].to_numpy(), f"gap_k{k}": gap.loc[at, k].to_numpy(),
        f"gap_k{n}": gap.loc[at, n].to_numpy(), f"z_k{k}": z.loc[at, k].to_numpy(),
        "inflation": rule.loc[at, "inflation"].to_numpy(), "u_gap": rule.loc[at, "u_gap"].to_numpy(),
        "rstar": rule.loc[at, "rstar"].to_numpy(), "notional": rule.loc[at, "notional"].to_numpy(),
    })

    by_k = {h: policy.run(signal, sessions, meetings, h, spec["backtest"]) for h in sorted(gap.columns)}
    stats = {h: engine.stats(r) for h, r in by_k.items()}
    result, summary = by_k[k], stats[k]
    sensitivity = pd.DataFrame([{"k": h, **{c: s[c] for c in ["total", "per_year", "vol", "sharpe",
                                                               "hit_rate", "max_drawdown"]}}
                                for h, s in stats.items()])
    live = result[result["position"].notna()]
    yearly = live.groupby(live.index.year).agg(pnl_bp=("pnl", "sum"), mean_abs_z=("position", lambda p: p.abs().mean()))
    yearly = yearly.reset_index(names="year")

    by_year = gap.groupby(gap.index.year).agg(["mean"])[[(1, "mean"), (k, "mean"), (n, "mean")]]
    by_year.columns = ["gap_k1_mean", f"gap_k{k}_mean", f"gap_k{n}_mean"]
    by_year = by_year.join(rule.groupby(rule.index.year)["at_elb"].mean().rename("share_at_elb"))
    by_year = by_year.reset_index(names="year")

    headline = {
        "panel_sessions": len(ok), "model_sessions": len(rule),
        "first_model": rule.index.min(), "last": rule.index.max(),
        "before_macro": int((ok["session"] < rule.index.min()).sum()),
        "at_elb": int(rule["at_elb"].sum()), "before_first_sep": int(rule["sep_date"].isna().sum()),
        "first_z": z[k].first_valid_index(), "k": k, "backtest": summary,
    }
    tables = {
        "The gap at named moments, bp (negative: the market prices less tightening than the rule)": named,
        "The gap by year, bp, and the share of sessions the rule sat on the floor": by_year,
        f"Crude backtest at k = {k}, by year (no costs)": yearly,
        "Horizon sensitivity (k = 4 was chosen before any of these were run; not a menu)": sensitivity,
    }
    return headline, tables, result


def markdown(ccy, headline, tables, today, cfg):
    """The report; the words that differ by currency come from `cfg` (its ``report.labels``, macro and rule)."""
    h, b, r = headline, headline["backtest"], today["rule"]
    m = today["meetings"]
    w = cfg["report"]["labels"]
    rstar = cfg["rule"]["rstar"]
    rstar_line = (f"- Sessions before the first {rstar['label']} (r* = {rstar['before_first_label']}): "
                  f"{h['before_first_sep']}"
                  if "before_first" in rstar else
                  f"- r* is a constant {rstar['constant']:+.1f}%, from config: no longer-run rate is published")
    source = (f"({rstar['label']} of {r['sep_date']:%Y-%m-%d})" if pd.notna(r["sep_date"]) else "(constant)")
    lines = [
        f"# Model path against market path: {ccy}",
        "",
        f"Generated by `scripts/build_model.py` for {h['first_model']:%Y-%m-%d} .. {h['last']:%Y-%m-%d}. "
        "Do not edit by hand. The rule, r* and the conditioning are explained in notes/DECISIONS.md "
        f"(2026-09-27); the inputs in [nowcast_{ccy}.md](nowcast_{ccy}.md).",
        "",
        f"- Sessions with a market path: {h['panel_sessions']}; with a model path: {h['model_sessions']} "
        f"(the first {h['before_macro']} precede the nowcast, {w['nowcast_start']}: {cfg['macro']['start']})",
        f"- Sessions where the rule's notional rate is below the ELB, so the model sits on the floor: {h['at_elb']}",
        rstar_line,
        f"- First z at k = {h['k']}: {h['first_z']:%Y-%m-%d} (two-year trailing window, a year of history first)",
        f"- Crude backtest at k = {h['k']}, {b['first']:%Y-%m} .. {b['last']:%Y-%m}, **no costs**: "
        f"{b['total']:+.0f}bp x z, Sharpe {b['sharpe']:.2f}, max drawdown {b['max_drawdown']:.0f}bp",
        "",
        f"## Latest session: {today['session']:%Y-%m-%d}",
        "",
        f"{w['inflation']} {r['inflation']:.2f}%, u - u* {r['u_gap']:+.2f}pp, r* {r['rstar']:.2f} "
        f"{source}: the rule's notional rate is {r['notional']:.2f}%. "
        f"{w['policy_rate']} in force {r['r0']:.3f}%, {w['rate']} - {w['policy_rate'].lower()} "
        f"{r['spread_bp']:+.1f}bp.",
        "",
        table(m[["k", "announcement_date", "effective_date", "market", "model", "gap_bp", "z",
                 "window_mean_bp", "window_sd_bp"]].rename(columns={"announcement_date": "announced",
                                                                  "effective_date": "effective"})),
        "",
    ]
    for title, df in tables.items():
        lines += [f"## {title}", "", table(df) if len(df) else "None.", ""]
    return "\n".join(lines)
