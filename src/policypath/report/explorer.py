"""reports/explorer.html: the pipeline, every session, who closes the gap and the decision log, in one page.

Generated by `scripts/build_explorer.py`, never hand-edited. One self-contained
file: the data it draws is embedded as JSON, the page draws its own charts
(the template beside this module, ``explorer.html``), and nothing loads from
the network, so it opens from disk in any browser.

- **The pipeline**: `config/explorer.yml`'s stages, each with what it does,
  its code, the script that builds it, the reports it writes, its numbers and
  the decision sections and tests behind it. The numbers are the numbers
  sheet's own rows (``reports/numbers.md``), named in the config by item or by
  table column, so a stage shows what the sheet shows. A path, an item, a
  column or a DECISIONS section the config names that does not exist stops
  the build, and so does a DECISIONS section no stage claims.
- **The time machine** (`machine`): every session of each enabled currency's
  model panel: the market's and the rule's rate after each of the next eight
  meetings and the days to each, the rate in force, the gap and z at the
  traded meeting with the band the z is measured on (its trailing mean plus
  and minus one sd), the rule's inputs and notional rate, the ELB state, and
  the side each sleeve's rule decides at the close (`report/portfolio.py`'s
  `setup`: the book's own rule and ELB treatment), from the first session the
  book counts. Rates are rounded to the basis point.
- **Who closes the gap**: reports/results/closure.json (`closure.py`).
- **The decision log** (`decisions`): notes/DECISIONS.md, row by row: every
  bold ID, the lags table and the forward tests, with the section each sits in
  and its kind: a headline (bold in the log), registered before its result,
  added after the run, proposed (awaiting the author), or a choice.
"""

import html
import json
from pathlib import Path
import re
import numpy as np
import pandas as pd
import yaml
from policypath import config, regimes
from policypath.report import portfolio
from policypath.report.figures import THEMES

MAP = config.CONFIG_DIR / "explorer.yml"
TEMPLATE = Path(__file__).with_name("explorer.html")
KINDS = ("measure", "strategy", "io")
BP = 100.0
LINK = re.compile(r"\[([^\]]+)\]\(([^)]+)\)")
CELL = re.compile(r"(?<!\\)\|")
SECTION = re.compile(r"## (.+?)(?:\s*\((.*)\))?\s*$")
ROW = re.compile(r"- \*\*([A-Z]{1,2}\d+)\*\*\.?\s*(?:\((\d{4}-\d{2}-\d{2})[^)]*\))?\.?\s*(.*)")
FORWARD = re.compile(r"- ([A-Z]\d+)\.\s+(.*)")
LAG = re.compile(r"\|\s*(L\d+)\s*\|\s*(.*?)\s*\|\s*(.*?)\s*\|\s*(.*?)\s*\|")


# ---- the numbers sheet ---------------------------------------------------------------

def _cells(line):
    return [c.strip().replace("\\|", "|") for c in CELL.split(line.strip().strip("|"))]


def sheet(text):
    """reports/numbers.md as (items, tables): {item: {value, source, note}} from its item tables, and the rest as
    [(header, rows)]."""
    items, tables, lines, i = {}, [], text.splitlines(), 0
    while i < len(lines):
        if lines[i].startswith("|") and i + 1 < len(lines) and re.match(r"\|\s*-", lines[i + 1]):
            head, rows, i = _cells(lines[i]), [], i + 2
            while i < len(lines) and lines[i].startswith("|"):
                rows.append(_cells(lines[i]))
                i += 1
            if head[:2] == ["Item", "Value"]:
                items |= {r[0]: {"value": r[1], "source": r[2], "note": r[3] if len(r) > 3 else ""} for r in rows}
            else:
                tables.append((head, rows))
            continue
        i += 1
    return items, tables


def plain(text):
    """Markdown cell text as plain text: links to their text, no bold or code marks."""
    return LINK.sub(r"\1", text).replace("**", "").replace("`", "")


def links(text):
    """A source cell as [{text, href}]: each markdown link (its line number dropped from the href, which is
    relative to reports/), or the plain text."""
    found = [{"text": t, "href": re.sub(r":\d+$", "", h)} for t, h in LINK.findall(text)]
    return found or ([{"text": plain(text), "href": None}] if text.strip() else [])


def stage_numbers(spec, items, tables, stage):
    """A stage's numbers: [{label, value, source, note}] for each item, and each row of each column, it names."""
    out = []
    for n in spec:
        if "item" in n:
            if n["item"] not in items:
                raise ValueError(f"config/explorer.yml, stage {stage}: reports/numbers.md has no item {n['item']!r}")
            x = items[n["item"]]
            out.append({"label": n["item"], "value": plain(x["value"]), "source": links(x["source"]),
                        "note": plain(x["note"])})
            continue
        head, rows = next(((h, r) for h, r in tables if n["column"] in h), (None, None))
        if head is None:
            raise ValueError(f"config/explorer.yml, stage {stage}: reports/numbers.md has no column {n['column']!r}")
        j, src = head.index(n["column"]), head.index("Source") if "Source" in head else None
        out += [{"label": f"{r[0]}, {n['column']}", "value": plain(r[j]),
                 "source": links(r[src]) if src is not None else [], "note": ""} for r in rows]
    return out


# ---- the decision log ----------------------------------------------------------------

def _html(text):
    """A DECISIONS row's markdown as safe HTML: escaped, then code, bold and the italic Why."""
    t = html.escape(text, quote=False)
    t = re.sub(r"`([^`]+)`", r"<code>\1</code>", t)
    t = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", t)
    return re.sub(r"\*(Why[^*]*?:)\*", r"<em>\1</em>", t)


def _kind(rid, text):
    if re.search(r"(?i)not registered|added after the run", text):
        return "after"
    if re.search(r"(?i)pre-registered|^\*\*(fixed|stated) before", text) or rid.startswith("H"):
        return "registered"
    if re.match(r"\*\*Proposed\b", text):
        return "proposed"
    return "headline" if text.startswith("**") else "choice"


def decisions(text):
    """notes/DECISIONS.md as (sections, rows): its section names in order, and each row as {id, section, date,
    kind, html, text, refs}. A row's date is its own or else its section's."""
    sections, rows, section, date = [], [], None, None
    for line in text.splitlines():
        m = SECTION.match(line)
        if m:
            section = m.group(1).strip()
            sections.append(section)
            d = re.search(r"\d{4}-\d{2}-\d{2}", m.group(2) or "")
            date = d.group(0) if d else None
            continue
        if section is None:
            continue
        r, f, lag = ROW.match(line), FORWARD.match(line), LAG.match(line)
        if r:
            rid, own, body = r.group(1), r.group(2), r.group(3)
        elif f:
            rid, own, body = f.group(1), None, f.group(2)
        elif lag:
            rid, own, body = lag.group(1), None, f"{lag.group(2)}: {lag.group(3)}. {lag.group(4)}".strip()
        else:
            continue
        rows.append({"id": rid, "section": section, "date": own or date, "kind": _kind(rid, body),
                     "html": _html(body), "text": re.sub(r"\*(Why[^*]*?:)\*", r"\1", plain(body)),
                     "refs": re.findall(r"`([^`]+)`", body)[:4]})
    return sections, rows


# ---- the stages -----------------------------------------------------------------------

def _rel(path):
    """A repo path as the page links it, from reports/."""
    return f"../{path}"


def stages(spec, root, items, tables, sections, rows, ccys):
    """The map's stages, every name in `spec` checked (module docstring), with each stage's numbers and decisions."""
    keys = [s["key"] for s in spec]
    claimed, out = {}, []
    for s in spec:
        where = f"config/explorer.yml, stage {s['key']}"
        if s["kind"] not in KINDS:
            raise ValueError(f"{where}: kind {s['kind']!r} is not one of {KINDS}")
        missing = [p for p in (*s["code"], *s["built_by"], *s["tests"]) if not (root / p).exists()]
        writes = []
        for w in s["writes"]:
            names = [w.format(ccy=c) for c in ccys] if "{ccy}" in w else [w]
            have = [n for n in names if (root / "reports" / n).exists()]
            missing += [] if have else [f"reports/{w}"]
            writes += have
        if missing:
            raise ValueError(f"{where}: {missing} do not exist")
        for sec in s["decisions"]:
            if sec not in sections:
                raise ValueError(f"{where}: notes/DECISIONS.md has no section {sec!r}")
            if sec in claimed:
                raise ValueError(f"{where}: section {sec!r} is already on stage {claimed[sec]}")
            claimed[sec] = s["key"]
        unknown = [f for f in s.get("feeds", []) if f not in keys]
        if unknown:
            raise ValueError(f"{where}: feeds {unknown}, which are not stages")
        out.append({"key": s["key"], "row": s["row"], "kind": s["kind"], "title": s["title"],
                    "subtitle": s["subtitle"], "what": s["what"], "see": s.get("see"), "feeds": s.get("feeds", []),
                    "code": [{"text": p.removeprefix("src/policypath/"), "href": _rel(p)} for p in s["code"]],
                    "built_by": [{"text": p, "href": _rel(p)} for p in s["built_by"]],
                    "writes": [{"text": w, "href": w} for w in writes],
                    "tests": [{"text": Path(p).name, "href": _rel(p)} for p in s["tests"]],
                    "numbers": stage_numbers(s.get("numbers") or [], items, tables, s["key"]),
                    "decisions": [{"section": sec, "rows": sum(r["section"] == sec for r in rows)}
                                  for sec in s["decisions"]]})
    orphans = [sec for sec in sections if sec not in claimed]
    if orphans:
        raise ValueError(f"notes/DECISIONS.md sections on no stage of config/explorer.yml: {orphans}")
    return out


# ---- the time machine -----------------------------------------------------------------

def _schedule(v):
    """A config value or dated schedule as [[from or None, value], ...]."""
    if isinstance(v, list):
        return [[f"{pd.Timestamp(s['from']):%Y-%m-%d}", s["value"]] for s in v]
    return [[None, v]]


def _ints(a):
    a = np.asarray(a, dtype=float)
    return [None if not np.isfinite(x) else int(round(x)) for x in a.ravel()]


def _round(a, places=2):
    a = np.asarray(a, dtype=float)
    return [None if not np.isfinite(x) else round(float(x), places) for x in a]


def _rows(a, width):
    flat = _ints(a)
    return [flat[i:i + width] for i in range(0, len(flat), width)]


def machine(paths, signal, model, cfg, sides=None, first=None):
    """One currency's sessions for the time machine, column by column (module docstring).

    `sides` is the book's decided side per sleeve by book close (a frame, or
    None for none); a session takes the side of the last book close on or
    before it, and none before `first`, the first session the book counts.
    """
    sessions = pd.DatetimeIndex(sorted(model["session"].unique()))
    k = cfg["backtest"]["horizon"]
    wide = {c: paths.pivot(index="session", columns="k", values=c).reindex(sessions)
            for c in ("market", "model", "announcement_date")}
    n_meet = wide["market"].shape[1]
    ahead = (wide["announcement_date"].to_numpy(dtype="datetime64[ns]") - sessions.to_numpy()[:, None]) \
        / np.timedelta64(1, "D")
    sig = signal[signal["k"] == k].set_index("session").reindex(sessions)
    mo = model.set_index("session").reindex(sessions)
    rule, labels = cfg["rule"], cfg["report"]["labels"]
    out = {"t0": f"{sessions[0]:%Y-%m-%d}", "k": k, "meetings": n_meet,
           "d": [int(x) for x in (sessions - sessions[0]).days],
           "mk": _rows(wide["market"].to_numpy() * BP, n_meet), "md": _rows(wide["model"].to_numpy() * BP, n_meet),
           "ah": _rows(ahead, n_meet), "r0": _ints(mo["r0"] * BP), "g": _ints(sig["gap_bp"]), "z": _round(sig["z"]),
           "lo": _ints(sig["window_mean_bp"] - sig["window_sd_bp"]),
           "hi": _ints(sig["window_mean_bp"] + sig["window_sd_bp"]),
           "pi": _round(mo["inflation"]), "ug": _round(mo["u_gap"]), "rs": _round(mo["rstar"]),
           "nt": _round(mo["notional"]),
           "elb": [int(x) for x in regimes.elb_state(model).reindex(sessions, fill_value=False)],
           "labels": {key: labels[key] for key in ("market", "rate", "rule", "policy", "policy_rate", "bank")},
           "params": {"target": _schedule(rule["inflation_target"]),
                      "a": rule["coefficients"]["inflation_gap"], "b": rule["coefficients"]["unemployment_gap"],
                      "inertia": rule["inertia"], "per_quarter": _schedule(rule["meetings_per_quarter"]),
                      "elb": _schedule(rule["elb"])},
           "first_counted": None if first is None else f"{pd.Timestamp(first):%Y-%m-%d}"}
    moments = []
    for day, label in cfg["report"].get("moments", []):
        i = int(sessions.searchsorted(pd.Timestamp(day)))
        if i < len(sessions):
            moments.append([i, label])
    out["moments"] = moments
    if sides is None:
        out["sd"] = []
    else:
        on = sides.sort_index().reindex(sessions, method="ffill").fillna(0.0)
        if first is not None:
            on.loc[on.index < pd.Timestamp(first)] = 0.0
        out["sd"] = _rows(np.sign(on.to_numpy()), on.shape[1])
    return out


def book_sides(world=None):
    """The book's decided side per sleeve at each book close: `report/portfolio.py`'s `setup`, sleeves in book order."""
    return portfolio.setup(world).g


# ---- the page --------------------------------------------------------------------------

def theme_css():
    """The house themes (`figures.THEMES`, `portfolio.CATEGORICAL`) as the page's CSS variables, light and dark.

    The page sets ``data-theme`` on load from the reader's setting (or their last choice), so dark is its own
    block, not a media query."""
    def block(theme):
        t = THEMES[theme]
        return (f"--surface:{t['surface']};--ink:{t['ink']};--ink2:{t['secondary']};--muted:{t['muted']};"
                f"--grid:{t['grid']};--axis:{t['axis']};"
                + "".join(f"--s{i + 1}:{c};" for i, c in enumerate(portfolio.CATEGORICAL[theme])))
    return f":root{{{block('light')}}}\n:root[data-theme=dark]{{{block('dark')}}}"


def page(data):
    """The page: the template with the themes and `data` (made safe inside a script tag) filled in."""
    text = TEMPLATE.read_text(encoding="utf-8")
    blob = json.dumps(data, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")
    return text.replace("/*__THEME__*/", theme_css()).replace("/*__DATA__*/null", blob)


def payload(root, machines, closure, sleeves):
    """Everything the page draws: the map, the sessions (`machines`, {ccy: `machine`}), who closes the gap
    (`closure`, closure.json's content) and the decision log."""
    root = Path(root)
    spec = yaml.safe_load(MAP.read_text(encoding="utf-8"))
    items, tables = sheet((root / "reports" / "numbers.md").read_text(encoding="utf-8"))
    sections, rows = decisions((root / "notes" / "DECISIONS.md").read_text(encoding="utf-8"))
    ccys = config.enabled()
    return {"title": spec["title"], "stages": stages(spec["stages"], root, items, tables, sections, rows, ccys),
            "machine": machines, "closure": closure, "sleeves": list(sleeves),
            "decisions": {"sections": sections, "rows": rows},
            "spans": {c: {"first": m["t0"], "last": f"{pd.Timestamp(m['t0']) + pd.Timedelta(days=m['d'][-1]):%Y-%m-%d}"}
                      for c, m in machines.items()}}


def write(root, data):
    """reports/explorer.html under repo `root`. Returns its path."""
    out = Path(root) / "reports" / "explorer.html"
    out.write_text(page(data), encoding="utf-8")
    return out
