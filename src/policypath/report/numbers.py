def sample(r):
    m = r.json("metrics")
    book = _perf(m)["book"]
    first = m["first_counted"]
    trades = {p["name"]: p["trades"] for p in m["performance"]}
    entries = {s: v["entries"] for s, v in m["filter"].items()}
    late = {s: entries[s] - trades[s] for s in entries if entries[s] != trades[s]}
    note = ("An entry is decided at a close and becomes a trade from the next session. "
            + ("Entries the rule made at a close whose trade has not started yet: "
               + ", ".join(f"{s} {k}" for s, k in late.items()) + "." if late else "Every entry is a trade."))
    return [
        Row("Book sample", f"{book['first']} to {book['last']}, {book['sessions']:,} sessions, {book['years']:.1f} years",
            r.cite(METRICS, f"counted from {first}"),
            f"The book runs from {m['days'][0]}; sessions count from {first}."),
        Row("Trades, book", f"{trades['book']}", r.cite(METRICS, "| book |", section="Performance"),
            "A run of one side, from the close that opens it. By sleeve: "
            + ", ".join(f"{s} {t}" for s, t in trades.items() if s != "book") + "."),
        Row("Entries, book (the carry filter's count)", f"{sum(entries.values())}",
            r.cite(METRICS, f"of the rule's {sum(entries.values())} entries"), note),
    ]


