"""reports/numbers.md: every number the note quotes, each with the report line that prints it.

Reads only what the build scripts have already written: reports/results/*.json
and the markdown reports beside it. It needs no data and no strategy chain, so
it runs in well under a second. Each value is formatted from the JSON (or
parsed from a report that has no JSON), then looked up in the report that
prints it. If the report does not print it, the build stops. A report
regenerated without its JSON, or the other way round, cannot pass silently.

A few numbers no build script computes: a one-off study, a hand check, a
statement about a test. They are listed as static, with the README or
DECISIONS line that records them. That line must still exist, or the build
stops too.
"""

