def level(r):
    lg = r.json("metrics")["level_gap"]
    rows = []
    for ccy in ("USD", "GBP"):
        g = lg[ccy]
        years = {int(y): v for y, v in g["years"].items()}
        below = [y for y, v in years.items() if v < 0]
        lo, hi = min(years, key=years.get), max(years, key=years.get)
        above = [y for y in sorted(years) if years[y] > 0]
        tail = sorted(years)[-len(above):] == above if above else False
        extra = f" Above from {above[0]}: " + ", ".join(bp(years[y]) for y in above) + "." if above and tail else ""
        rows.append(Row(f"{ccy} below the rule at meeting {g['k'][1]}",
                        f"{len(below)} of {len(years)} years, {bp(years[lo])}bp ({lo}) to {bp(years[hi])}bp ({hi})",
                        r.cite(METRICS, f"| {lo} |", bp(years[lo]), section="The level the z removes"),
                        f"{min(years)} to {max(years)}, outside the ELB state, years with 60 or more sessions. "
                        f"r* {g['rstar']}.{extra}"))
        rows.append(Row(f"{ccy} by regime, meeting {g['k'][1]}",
                        ", ".join(f"{x['regime']} {bp(x['mean'][str(g['k'][1])])}bp ({x['sessions']:,})"
                                  for x in g["regimes"]),
                        r.cite(METRICS, f"| {ccy} | {g['regimes'][0]['regime']} |", section="The level the z removes"),
                        "Mean gap, market minus rule; sessions in brackets."))
    return rows


def ic_table(r):
    m = r.json("metrics")["ic"]
    out = []
    for s, v in m.items():
        rows = {x["h"]: x for x in v["rate"]["ex_elb"]}
        cells = [f"{rows[h]['ic']:+.3f} ({rows[h]['t']:+.1f})" for h in sorted(rows)]
        h21 = rows[21]
        line = r.line(METRICS, f"| {s} | rate | outside the ELB |", *cells, section="The IC")
        out.append([s, *cells, f"{h21['sessions']:,}", f"{h21['offsets_sessions']:,}",
                    f"{abs(h21['ic'] / h21['t']):.3f}",
                    f"{h21['offsets_mean']:+.3f} [{h21['offsets_min']:+.2f}, {h21['offsets_max']:+.2f}]",
                    link(METRICS, line)])
    return out


