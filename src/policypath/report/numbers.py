@dataclass
class Row:
    item: str
    value: str
    source: str
    sample: str = ""


class Reports:
    """The generated reports under repo `root`, read once each, with line lookups that stop the build on a miss."""

    def __init__(self, root):
        self.root = Path(root)
        self._text = {}

    def text(self, rel):
        if rel not in self._text:
            self._text[rel] = (self.root / rel).read_text(encoding="utf-8").splitlines()
        return self._text[rel]

    def json(self, name):
        return json.loads((self.root / "reports" / "results" / f"{name}.json").read_text(encoding="utf-8"))

    def _span(self, rel, section):
        lines = self.text(rel)
        if section is None:
            return 0, len(lines)
        start = next((i for i, l in enumerate(lines) if l.startswith("#") and l.lstrip("#").strip() == section), None)
        if start is None:
            raise ValueError(f"{rel}: no section '{section}'")
        end = next((i for i in range(start + 1, len(lines)) if re.match(r"#{1,%d} " % _depth(lines[start]), lines[i])),
                   len(lines))
        return start, end

    def line(self, rel, *needles, section=None):
        """The 1-based number of the first line in `rel` (within `section`, a heading's text) holding every needle."""
        lo, hi = self._span(rel, section)
        for i in range(lo, hi):
            if all(n in self.text(rel)[i] for n in needles):
                return i + 1
        where = f" under '{section}'" if section else ""
        raise ValueError(f"{rel}{where}: no line prints {' and '.join(repr(n) for n in needles)}")

    def grab(self, rel, pattern, section=None):
        """(the match, its 1-based line) for the first line in `rel` matching `pattern`."""
        lo, hi = self._span(rel, section)
        for i in range(lo, hi):
            m = re.search(pattern, self.text(rel)[i])
            if m:
                return m, i + 1
        raise ValueError(f"{rel}: no line matches {pattern!r}")

    def cite(self, rel, *needles, section=None):
        return link(rel, self.line(rel, *needles, section=section))


def _depth(heading):
    return len(heading) - len(heading.lstrip("#"))


def link(rel, n):
    """A markdown link to line `n` of repo-relative `rel`, written from reports/numbers.md."""
    name = Path(rel).name
    href = name if rel.startswith("reports/") else f"../{rel}"
    return f"[{name}:{n}]({href}:{n})"


def bp(x):
    return f"{x:+.0f}"


def thousands(x):
    return f"{x / 1000:.0f}k"


