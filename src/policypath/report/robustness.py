"""The robustness report: the headline book with one choice at a time moved off the chosen specification.

Generated by `scripts/build_robustness.py`, never hand-edited: every number
comes from the rows run here, and every sentence is a template filled from
them. Numbers are from the build of 2026-09-29 (reports/robustness.md).

**What is run.** Every row of ``robustness.choices`` (`strategy/robustness.py`,
13 rows over 8 choices) is the headline book (`report/portfolio.py`
`headline`: the configured construction, shrunk, every sleeve, no drawdown
control, at the chosen ELB treatment and the configured costs) on the row's
signal, and each sleeve alone as `report/costs.py` runs it (`simulate`:
vol-scaled, the book's rule). A row's sleeves are the baseline's legs with the
row's components, ELB state and carry gate (`report/costs.py` `inputs(like=)`),
so the unit P&L, sigma, the covariance (the baseline's `Risk`, reused) and the
costs are the baseline's; `build` stops if a row's unit P&L is not.

**The cells.** Primary: the book's net Sharpe over the common sample, the
book sessions on which every row has an eligible signal (`robustness.eligible`;
a book session counts where any sleeve's does, as the book counts its
sessions): 2,866 from 2014-05-05 (the constant dollar r* keeps the dollar
model in the ELB state to May 2014, the chosen one to Jan 2014), where SE(SR)
is 0.32 at the chosen specification's -0.62. The sleeves are run alone, not read off their part of
the book: the book's vol target is shared, so a sleeve's part moves with every
other sleeve's side, and a row that changes one currency would move the other
currency's sleeves; alone, those cells are the chosen ones exactly. Each is over
its own common sample (the sterling sleeves' from Aug 2016, where every row's
sterling model leaves the ELB state; the -2.6 r* row, in it on more sessions
after that, takes the GBP outright's from 2,294 to 2,208). Secondary: gross Sharpe; each row on
its own sample; IC(21) of each sleeve's z on the rate component of its unit P&L
(a signal-level number, free of sizing, costs and the book), over the sessions
every row has a z outside its ELB state, where the model has no view; and, for
the estimated rows, the same cells from the first estimate on (2017-01-03 for
the book, the later of the two currencies').

**The paired SE** (`robustness.paired_se`), beside every move: two cells over
the same sessions share most of their positions, so the noise in their
difference is far below the SE of either Sharpe (0.03 for the NSS row, 0.22
for the 365-day window, against 0.32). It is iid, and for a difference that is
no bound: its Newey-West version (Bartlett weights to 21 sessions) is lower on
10 of the 13 rows and puts two in another band (the carry filter at 2.30
paired SEs against 1.90 iid). The reading sorts the choices by the iid one,
says where the other differs, and how many moves beyond one paired SE noise
alone would give (4.1 of 13; 4 are). Each sleeve's largest move carries its
own paired SE: the book's insensitivity to r* (GBP) and the coefficients hides
the GBP outright's (1.3 and 1.6 paired SEs).

**The note on r*** gives its shares over the sessions every row counts for the
currency's outright (2,208 for sterling), with every session's beside them:
the whole sample counts the years both models sit flat in the ELB state, where
no side can differ (the -2.6 row changes the GBP outright's side on 16.8% of
the counted sessions, 10.6% of all). The z is the chosen one's only on the 185
(-2.6) and 1,043 (-0.6) counted sessions with no floored goal in the trailing
730 days. The HLW row says how much of the common sample has a current
vintage: 66% (Taylor's 2% before March 2016 and the 2020Q2 vintage, held to
May 2023, are the rest).

**The IC's t** is Newey-West to 21 lags (spec section 6), which covers the
forward windows' overlap and not the z's persistence (the rank products'
autocorrelation at lag 21 is 0.33 for the USD outright, 0.12 for the GBP
outright), so the non-overlapping check (`metrics.ic_offsets`) is beside it;
its mean has the IC's sign in all 70 row-sleeve cells.

**The headline** is read from reports/results/portfolio.json, not from the
grid's own run: the build stops unless the chosen specification on its own
sample is it.
"""

