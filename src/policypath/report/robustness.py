def range_lines(g, s):
    """One generated line per choice: the chosen value's cell, each alternative's with its move and paired SE, the
    range against one SE, and the sleeve the choice moves most."""
    base, se = _net(s, BASE), s["net"][BASE]["book"][1]
    out = []
    for name, chosen, rows in choices(g):
        vals = [base, *(_net(s, r.key) for r in rows)]
        spread = max(vals) - min(vals)
        move = max(((r, n) for r in rows for n in g.runs[BASE]), key=lambda x: abs(_delta(s, x[0].key, x[1])))
        out.append(f"- **{name}**: {chosen}* {sr(base)}; "
                   + "; ".join(f"{r.label} {sr(_net(s, r.key))} ({_delta(s, r.key):+.2f}, paired SE "
                               f"{s['paired'][r.key]['book']:.2f})" for r in rows)
                   + f". Range {spread:.2f}, {'under' if spread < se else 'over'} one SE ({se:.2f}). The sleeve it "
                   f"moves most: {move[1]}, {_delta(s, move[0].key, move[1]):+.2f} at {move[0].label}.")
    return out


def answer(g, s):
    """The report's opening: the verdict and the bullets, each worded by what the numbers say."""
    lines = [_design_words(g, s), _move_words(g, s), _reading(g, s), _sleeve_words(g, s), _slope_words(g, s),
             _gross_words(g, s),
             *(_rstar_words(g, s) or []), _ic_words(g, s), _estimated_words(g, s), _own_words(g, s)]
    return [_head(g, s), "", *[x for x in lines if x]]


# ---- the tables --------------------------------------------------------------------

def _cell(c, se=True):
    return sr(c[0], c[1] if se else None)


def _grid_table(g, s, part="net"):
    names = list(g.runs[BASE])
    rows = []
    for name, chosen, alts in choices(g):
        for i, (label, key) in enumerate([(f"{chosen}*", BASE), *((r.label, r.key) for r in alts)]):
            c = s[part][key]
            row = {"choice": name if i == 0 else "", "value": label, "book": _cell(c["book"], key == BASE)}
            if part == "net":
                row |= {"change": "" if key == BASE else f"{_delta(s, key):+.2f}",
                        "paired SE": "" if key == BASE else f"{s['paired'][key]['book']:.2f}",
                        "Newey-West": "" if key == BASE else f"{s['paired_hac'][key]['book']:.2f}"}
            rows.append(row | {n: _cell(c[n], False) for n in names})
    return pd.DataFrame(rows)


def _sample_line(g, s):
    sm = s["sample"]
    base = s["net"][BASE]
    return (f"Common sample: {sm['book']['sessions']:,} book sessions, {sm['book']['first']:%Y-%m-%d} to "
            f"{sm['book']['last']:%Y-%m-%d} ({sm['book']['years']:.1f} years); **SE(SR) there is "
            f"{base['book'][1]:.2f}** at the chosen specification's {sr(base['book'][0])}. Each sleeve over its own "
            "common sample: " + _and(f"{n} {sm[n]['sessions']:,} sessions from {sm[n]['first']:%b %Y} (SE "
                                     f"{base[n][1]:.2f})" for n in g.runs[BASE]) + ". * the chosen value.")


def _own_table(g, s):
    ccys = list(g.elb[BASE])
    rows = []
    for r in g.rows:
        o, og = s["own"][r.key]["book"], s["own_gross"][r.key]["book"]
        on = g.eligible[r.key]["book"]
        rows.append({"row": r.words(), "sessions counted": f"{o[2]:,}", "from": f"{on[on].index.min():%Y-%m-%d}",
                     "net": _cell(o), "gross": _cell(og),
                     **{f"ELB-state sessions ({c})": f"{g.elb[r.key][c]:,}" for c in ccys}})
    return pd.DataFrame(rows)


def _ic_table(g, s):
    return pd.DataFrame([{"row": r.words(), **{n: f"{v[0]:+.2f} ({v[1]:+.1f})" for n, v in s["ic"][r.key].items()}}
                         for r in g.rows])


def _ic_line(g, s):
    n = s["ic"][BASE]
    return ("Sessions: " + _and(f"{k} {v[2]:,}" for k, v in n.items()) + ".")


def _persistent(s):
    """The sleeves whose rank products stay positively autocorrelated past the IC's horizon, in words."""
    names = [n for n, x in s["ic_persistence"].items() if x > 0]
    return _and(names) if names else "no sleeve"


def _ic_offsets_table(g, s):
    return pd.DataFrame([{"row": r.words(), **{n: f"{v[0]:+.2f} ({v[1]:+.2f} to {v[2]:+.2f})"
                                                for n, v in s["ic_offsets"][r.key].items()}} for r in g.rows])


def _estimated_table(g, s):
    e = s["estimated"]
    names = ["book", *g.runs[BASE]]
    rows = [{"row": r.words(), **{n: _cell(e["cells"][r.key][n], n == "book") for n in names}}
            for r in g.rows if r.key == BASE or r.key in e["keys"]]
    return pd.DataFrame(rows)


def _moves_table(g):
    rows = []
    for r in g.rows:
        for ccy, m in g.moves[r.key].items():
            rows.append({"row": r.words(), "currency": ccy,
                         "gap change, mean (sd)": f"{m['mean_change_bp']:+.1f} ({m['sd_change_bp']:.1f})",
                         "latest gap": f"{m['latest_row_bp']:+.1f} ({m['latest_change_bp']:+.1f})",
                         "corr(z)": f"{m['corr_z']:.3f}", "z changes sign": pct1(m["sign_changes"]),
                         "r* offset, mean (sd)": f"{m['rstar_offset_mean']:+.2f} ({m['rstar_offset_sd']:.2f})",
                         "goal floored: chosen, row, differ": f"{m['floored_base']:.0%}, {m['floored_row']:.0%}, "
                                                              f"{m['floored_differ']:.1%}",
                         "counted: z changes sign; floored, chosen and row; floor-free":
                             f"{pct1(m.get('sign_changes_traded'))}; {pct1(m.get('floored_base_traded'))}, "
                             f"{pct1(m.get('floored_row_traded'))}; {m.get('floor_free', 0):,} of "
                             f"{m.get('traded_sessions', 0):,}",
                         "ELB-state sessions": f"{g.elb[BASE][ccy]:,} to {g.elb[r.key][ccy]:,}"})
    return pd.DataFrame(rows)


def _sides_table(g):
    return pd.DataFrame([{"row": r.words(), **{n: f"{pct1(v[0])} ({pct1(v[1])})" for n, v in g.sides[r.key].items()}}
                         for r in g.rows if r.key != BASE])


