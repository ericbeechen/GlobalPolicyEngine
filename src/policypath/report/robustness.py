def _cells_json(c):
    return {n: {"sr": v[0], "se": v[1], "sessions": v[2]} for n, v in c.items()}


def results(g, s):
    """reports/results/robustness.json: the numbers the note quotes, to six significant figures."""
    e = s["estimated"]
    rows = {}
    for r in g.rows:
        k = r.key
        rows[k] = {"choice": r.choice, "label": r.label, "net": _cells_json(s["net"][k]),
                   "gross": _cells_json(s["gross"][k]), "own": _cells_json(s["own"][k]),
                   "own_gross": _cells_json(s["own_gross"][k]), "paired_se": s["paired"][k],
                   "change": {n: s["net"][k][n][0] - s["net"][BASE][n][0] for n in s["net"][k]},
                   "paired_se_newey_west": s["paired_hac"][k],
                   "ic": {n: {"ic": v[0], "t": v[1], "sessions": v[2]} for n, v in s["ic"][k].items()},
                   "ic_offsets": {n: {"mean": v[0], "low": v[1], "high": v[2], "fewest_sessions": v[3]}
                                  for n, v in s["ic_offsets"][k].items()},
                   "moves": g.moves[k],
                   "side_changes": {n: {"all": v[0], "counted": v[1]} for n, v in g.sides[k].items()},
                   "elb_sessions": g.elb[k],
                   "first_estimate": g.first[k]}
        if e["keys"] and (k == BASE or k in e["keys"]):
            rows[k]["from_first_estimate"] = _cells_json(e["cells"][k])
    two, one, mid = _choice_verdicts(g, s)
    return _plain({
        "spec": {"headline": g.book["portfolio"]["headline"], "treatment": g.setups[BASE].spec.treatment,
                 "ic_horizon": g.book["robustness"]["ic_horizon"], "paired_se_lags": robustness.PAIRED_LAGS,
                 "design": "one at a time"},
        "ic_persistence": s["ic_persistence"],
        "sample": s["sample"],
        "choices": [{"name": n, "chosen": c, "rows": [r.key for r in rs]} for n, c, rs in choices(g)],
        "sensitive": {"over_two_paired_se": two, "one_to_two": mid, "under_one_paired_se": one},
        "from_first_estimate": e["start"],
        "rows": rows,
    })


def write(g, root, s=None):
    """Every output of the build under repo `root`. Returns the paths."""
    s = summary(g) if s is None else s
    root = Path(root)
    out = {"report": root / "reports" / "robustness.md", "json": root / "reports" / "results" / "robustness.json"}
    for p in out.values():
        p.parent.mkdir(parents=True, exist_ok=True)
    out["report"].write_text(markdown(g, s), encoding="utf-8")
    out["json"].write_text(json.dumps(results(g, s), indent=1) + "\n", encoding="utf-8")
    figures = root / "reports" / "figures"
    figures.mkdir(parents=True, exist_ok=True)
    for theme in THEMES:
        p = figures / f"robustness_{theme}.png"
        figure(g, s, p, theme)
        out[f"figure_{theme}"] = p
    return out
