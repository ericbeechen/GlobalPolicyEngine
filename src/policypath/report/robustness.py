@dataclass
class Grid:
    """Every row run: `rows` in order, and by row key the book's `Setup` and headline `Book`, the sleeves'
    stand-alone `Run`s, and the sessions each row has an eligible signal on (``book`` on the book calendar, each sleeve on its
    own). `common` is their intersection over the rows; `ic_common` the sessions every row has a z outside its ELB
    state on (the IC's). `moves` is {key: {ccy: `robustness.moves`, on the currency's outright's common sample}},
    `sides` {key: {sleeve: (share of sessions whose side changes, the same over its common sample)}}, `onto`
    {key: {ccy: (sessions added, dropped)}}, `models` {key: {ccy: model panel}}, `elb` {key: {ccy: ELB-state
    sessions}} and `first` {key: {ccy: first estimate}}."""
    book: dict
    rows: list
    setups: dict
    books: dict
    runs: dict
    eligible: dict
    common: dict
    ic_common: dict
    moves: dict
    sides: dict
    onto: dict
    models: dict
    elb: dict
    first: dict
    risk: books.Risk


def _book_eligible(st, b):
    """The book sessions with an eligible signal: those a sleeve's eligible session is credited to, from the book's
    start (as the book counts its sessions)."""
    days, start = st.days, b.run.start
    out = np.zeros(len(days), dtype=bool)
    for i in st.inputs.values():
        s = i.sleeve
        e = robustness.eligible(s.component["z"], i.state, st.spec.treatment, s.lag) & (s.sessions >= start)
        out |= portfolio.to_book(e.astype(int), days).to_numpy() > 0
    return pd.Series(out & (days >= start), index=days)


def _sleeve_eligible(i, treatment):
    s = i.sleeve
    return robustness.eligible(s.component["z"], i.state, treatment, s.lag) & (s.sessions >= i.start)


def _row_inputs(world, row, base, legs, signal):
    """A row's book config, currency blocks, view, and each sleeve's stand-alone `Inputs` on the baseline's legs."""
    book = robustness.book_of(row, world.book)
    cfgs = {c: robustness.block(c, world.cfg(c), over) for c, over in row.currencies.items()}
    placed = {c: robustness.onto(s, world.panel(c, "signal")) for c, (_, s) in signal.items()}
    panels = {c: {"model": signal[c][0], "signal": placed[c][0]} for c in signal}
    view = robustness.View(world, legs, book=book, cfgs=cfgs, panels=panels)
    specs = {s["name"]: s for s in book["sleeves"]}
    inp = {}
    for n, i in base.items():
        if not robustness.touches(row, i.sleeve):
            inp[n] = i
            continue
        sleeve = expression.sleeve(specs[n], view)
        if sleeve.component["z"].first_valid_index() is None:
            raise RuntimeError(f"row {row.key}: the {n} sleeve has no z on any session")
        inp[n] = sleeves.inputs(sleeve, view, book, like=i)
    return book, view, inp, {c: p[1:] for c, p in placed.items()}


def build(world=None, signals=None, store=None, log=None):
    """Every row of the grid, run: a `Grid`.

    `signals` is `robustness.signals`' result ({key: {ccy: (model, signal)}});
    by default it is built from `world` (the real one by default) through
    `store` (`robustness.Store`).
    """
    world = expression.World() if world is None else world
    book = world.book
    grid = robustness.rows(book)
    if signals is None:
        signals = robustness.signals(world, grid, store, log=log)
    legs = {}
    view0 = robustness.View(world, legs, build=True)
    base = {n: sleeves.inputs(s, view0, book) for n, s in expression.build(view0).items()}
    days = sleeves._book_days(world, book)
    st0 = books.from_inputs(book, days, base)
    rk = books.risk_of(st0, list(base))
    k = {c: world.cfg(c)["backtest"]["horizon"] for c in robustness.book_currencies(book)}
    out = {name: {} for name in ("setups", "books", "runs", "eligible", "moves", "sides", "onto", "models", "elb",
                                 "first")}
    views = {}
    for row in grid:
        if row.key == BASE:
            b_book, view, inp, placed = book, view0, base, {}
        else:
            b_book, view, inp, placed = _row_inputs(world, row, base, legs, signals[row.key])
        st = st0 if row.key == BASE else books.from_inputs(b_book, days, inp)
        if not st.units.equals(st0.units) or any(inp[n].u is not base[n].u for n in base):
            raise RuntimeError(f"row {row.key}: the unit P&L is not the baseline's")
        b = books.run_book(st, rk, books.headline(b_book))
        runs = {n: sleeves.simulate(i, sleeves.chosen(b_book), b_book) for n, i in inp.items()}
        out["setups"][row.key], out["books"][row.key], out["runs"][row.key] = st, b, runs
        out["eligible"][row.key] = {"book": _book_eligible(st, b),
                                    **{n: _sleeve_eligible(i, st.spec.treatment) for n, i in inp.items()}}
        models = out["models"][row.key] = {c: view.panel(c, "model") for c in k}
        out["elb"][row.key] = {c: int(regimes.elb_state(m).sum()) for c, m in models.items()}
        out["first"][row.key] = {c: robustness.first_estimate(m) for c, m in models.items()}
        out["onto"][row.key] = placed
        views[row.key] = view
    names = ["book", *base]
    common = {n: robustness.common(out["eligible"][r.key][n] for r in grid) for n in names}
    ic_common = {n: robustness.common(_ic_sample(out["setups"][r.key].inputs[n]) for r in grid) for n in base}
    for row in grid:
        view, models = views[row.key], out["models"][row.key]
        traded = {c: common[n] if (n := _outright_in(base, c)) else None for c in row.currencies}
        out["moves"][row.key] = {c: robustness.moves(world.panel(c, "signal"), view.panel(c, "signal"), k[c],
                                                     world.panel(c, "model"), models[c], traded[c],
                                                     view.cfg(c)["signal"]["window"]) for c in row.currencies}
        out["sides"][row.key] = {n: _side_changes(st0, out["setups"][row.key], n, common[n]) for n in base}
    g = Grid(book, grid, out["setups"], out["books"], out["runs"], out["eligible"], common, ic_common, out["moves"],
             out["sides"], out["onto"], out["models"], out["elb"], out["first"], rk)
    check(g)
    return g


def _ic_sample(i):
    """A sleeve's sessions with a z, outside the ELB state: where the signal says something."""
    return i.sleeve.component["z"].notna() & ~i.state.reindex(i.sleeve.sessions, fill_value=False)


def _side_changes(st0, st, name, on):
    """The share of a sleeve's sessions with a z in both on which the row decides another side than the baseline:
    (over every such session, over those in `on`, the sleeve's common sample). Every session counts years in
    which both are flat in the ELB state and cannot differ; the common sample is where the sleeve trades."""
    z0, z1 = st0.inputs[name].sleeve.component["z"], st.inputs[name].sleeve.component["z"]
    both = z0.notna() & z1.notna()
    differ = st0.side[name] != st.side[name]
    traded = both & on.reindex(both.index, fill_value=False)
    return tuple(float(differ[m].mean()) if m.any() else np.nan for m in (both, traded))


def check(g):
    """Raise if the grid's invariants fail: every row's eligible sessions are ones its book and runs count; no row
    adds or drops a session; the common samples are not empty."""
    for row in g.rows:
        b, e = g.books[row.key], g.eligible[row.key]
        if (e["book"] & ~b.run.daily["kept"]).any():
            raise RuntimeError(f"row {row.key}: an eligible book session the book does not count")
        for n, r in g.runs[row.key].items():
            if (e[n] & ~r.daily["kept"]).any():
                raise RuntimeError(f"row {row.key}: an eligible {n} session the sleeve does not count")
        moved = {c: p for c, p in g.onto[row.key].items() if any(p)}
        if moved:
            raise RuntimeError(f"row {row.key}: sessions added or dropped against the baseline: {moved}")
    empty = [n for n, m in g.common.items() if not m.any()]
    if empty:
        raise RuntimeError(f"no session every row counts for {empty}")


# ---- the numbers -------------------------------------------------------------------

def periods(g):
    """Sessions a year: the book's, and each sleeve's (the baseline run's), used for every row's cell."""
    base = robustness.BASELINE.key
    return {"book": g.books[base].run.periods, **{n: r.periods for n, r in g.runs[base].items()}}


def _pnl(g, key, name, net=True):
    d = g.books[key].run.daily if name == "book" else g.runs[key][name].daily
    return d["gross"] - d["cost"] if net else d["gross"]


def cells(g, mask=None, own=False, net=True):
    """{row key: {book and sleeve: (Sharpe, SE, sessions)}} over the common samples (or each row's own with `own`),
    each intersected with `mask` ({name: bool series}) if given."""
    per = periods(g)
    out = {}
    for row in g.rows:
        out[row.key] = {}
        for n in ["book", *g.runs[row.key]]:
            m = g.eligible[row.key][n] if own else g.common[n]
            if mask is not None:
                m = m & mask[n].reindex(m.index, fill_value=False)
            out[row.key][n] = robustness.cell(_pnl(g, row.key, n, net), m, per[n])
    return out


def _rate(i):
    """A sleeve's rate component of unit P&L by session (bp): what its IC is on."""
    return i.u.groupby("session")["rate"].sum(min_count=1).reindex(i.sleeve.sessions)


def ics(g, how=robustness.ic):
    """{row key: {sleeve: (IC, t, sessions)}}: IC(``robustness.ic_horizon``) on the rate component, over the IC's
    common sample; with `how` another function of the same arguments (`robustness.ic_offsets`, `ic_persistence`)."""
    h = g.book["robustness"]["ic_horizon"]
    return {row.key: {n: how(i.sleeve.component["z"], _rate(i), h, i.sleeve.lag, g.ic_common[n])
                      for n, i in g.setups[row.key].inputs.items()} for row in g.rows}


def estimated(g):
    """The rows with estimated coefficients, the first estimate each window starts at, and their cells from it.

    Returns (keys, {name: window start}, cells): the baseline and those rows
    over the common samples from the latest first estimate among the rows
    and the currencies a book or sleeve trades.
    """
    keys = [r.key for r in g.rows if any(v is not None for v in g.first[r.key].values())]
    if not keys:
        return [], {}, {}
    base = g.setups[robustness.BASELINE.key]
    ccys = {"book": robustness.book_currencies(g.book), **{n: list(i.sleeve.ccys) for n, i in base.inputs.items()}}
    start = {n: max(g.first[k][c] for k in keys for c in cs if g.first[k][c] is not None) for n, cs in ccys.items()}
    mask = {n: pd.Series(g.common[n].index >= start[n], index=g.common[n].index) for n in start}
    return keys, start, cells(g, mask)


def summary(g, published=None):
    """Every number the report prints: the cells (net and gross; common and own samples), the paired SEs (iid and
    Newey-West), the ICs and their non-overlapping check, the estimated rows' window, and each common sample's size.

    `published` is the headline book as reports/results/portfolio.json has it (`published_headline`). Given, the
    chosen specification on its own sample must be it, net Sharpe to the JSON's six figures and sessions, or this
    raises: the report then says so from the file, not from its own run.
    """
    per = periods(g)
    names = ["book", *g.runs[BASE]]
    paired, hac = ({r.key: {n: robustness.paired_se(_pnl(g, r.key, n), _pnl(g, BASE, n), g.common[n], per[n], lags)
                            for n in names} for r in g.rows} for lags in (None, robustness.PAIRED_LAGS))
    keys, start, est = estimated(g)
    samples = {}
    for n in names:
        on = g.common[n][g.common[n]].index
        samples[n] = {"sessions": len(on), "first": on.min(), "last": on.max(), "years": len(on) / per[n]}
    own = cells(g, own=True)
    if published is not None:
        got = (float(f"{own[BASE]['book'][0]:.6g}"), own[BASE]["book"][2])
        if got != (published["net_sr"], published["sessions"]):
            raise RuntimeError(f"the chosen specification nets {got[0]} over {got[1]:,} sessions on its own sample; "
                               f"reports/results/portfolio.json's headline {published['net_sr']} over "
                               f"{published['sessions']:,}: rebuild it (scripts/build_portfolio.py)")
    return {"periods": per, "net": cells(g), "gross": cells(g, net=False), "own": own,
            "own_gross": cells(g, own=True, net=False), "paired": paired, "paired_hac": hac, "ic": ics(g),
            "ic_offsets": ics(g, robustness.ic_offsets), "ic_persistence": ics(g, robustness.ic_persistence)[BASE],
            "estimated": {"keys": keys, "start": start, "cells": est}, "sample": samples, "published": published}


def published_headline(root, book):
    """The headline book's numbers in reports/results/portfolio.json under repo `root` (`summary`'s check)."""
    books_json = json.loads((Path(root) / "reports" / "results" / "portfolio.json").read_text(encoding="utf-8"))["books"]
    return books_json[books._key(books.headline(book))]


def choices(g):
    """The grid's choices in config order: (name, chosen value, [its `Row`s])."""
    by = {r.key: r for r in g.rows}
    return [(c["name"], c["chosen"], [by[r["key"]] for r in c["rows"]]) for c in g.book["robustness"]["choices"]]


def _outright_in(inputs, ccy):
    """The outright sleeve of one currency among `inputs` ({name: `Inputs`}), or None."""
    for n, i in inputs.items():
        if i.sleeve.kind == "outright" and i.sleeve.ccys == (ccy,):
            return n
    return None


def _outright(g, ccy):
    return _outright_in(g.setups[BASE].inputs, ccy)


def _net(s, key, name="book"):
    return s["net"][key][name][0]


def _delta(s, key, name="book"):
    return _net(s, key, name) - _net(s, BASE, name)


def _moved(s, key, name="book", se="paired"):
    """|delta| over its paired SE (``paired``: iid; ``paired_hac``: Newey-West); 0 where the row leaves the cell."""
    x, d = s[se][key][name], abs(_delta(s, key, name))
    return d / x if x > 0 else 0.0 if d == 0 else np.inf


def _band(moved):
    return "over two" if moved > 2 else "under one" if moved < 1 else "one to two"


def _sign(values):
    pos, n = sum(v > 0 for v in values), len(values)
    return "positive in every row" if pos == n else "negative in every row" if pos == 0 else f"positive in {pos} of {n}"


