# ---- the figure --------------------------------------------------------------------

def figure(g, s, path, theme="light"):
    """Every row's net Sharpe over the common sample around the chosen specification's, with its paired SE."""
    t = _style(theme)
    color = t["series"][0]
    base, se = s["net"][BASE]["book"][:2]
    labels, values, errors, y, heads = [], [], [], [], []
    at = 0.0
    for name, _, rows in choices(g):
        heads.append((at, name))
        for r in rows:
            at += 1.0
            labels.append(r.label)
            values.append(_net(s, r.key))
            errors.append(s["paired"][r.key]["book"])
            y.append(at)
        at += 1.4
    fig, ax = plt.subplots(figsize=(8.2, 0.24 * at + 1.4))
    ax.axvspan(base - se, base + se, color=t["grid"], lw=0, zorder=0)
    ax.axvline(0.0, color=t["axis"], lw=1, zorder=1)
    ax.axvline(base, color=t["ink"], lw=1.4, zorder=2)
    ax.errorbar(values, y, xerr=errors, fmt="none", ecolor=color, elinewidth=1.4, capsize=0, zorder=3)
    ax.plot(values, y, "o", ms=7, color=color, mec=t["surface"], mew=1.5, zorder=4)
    ax.set_yticks(y, labels, fontsize=8)
    for h, name in heads:
        ax.text(-0.02, h + 0.1, name, transform=ax.get_yaxis_transform(), ha="right", va="center", fontsize=8.5,
                fontweight="bold", color=t["ink"])
    ax.set_ylim(at - 0.6, -0.8)
    lo, hi = min([*values, base - se, 0.0]), max([*values, base + se, 0.0])
    ax.set_xlim(lo - 0.1, hi + 0.1)
    ax.grid(axis="y", visible=False)
    ax.grid(axis="x", visible=True, color=t["grid"], lw=0.8)
    ax.tick_params(axis="both", length=0, labelsize=8)
    ax.set_xlabel("net Sharpe of the headline book over the common sample", fontsize=8)
    sm = s["sample"]["book"]
    top = ("No single choice turns the book's loss into a gain" if max(values + [base]) <= 0 else
           "Every row earns" if min(values + [base]) > 0 else "The book's sign turns on the choice")
    ax.set_title(f"{top}: {len(values)} rows, net {min(values):+.2f} to {max(values):+.2f}", loc="left", x=-0.42,
                 fontsize=12, fontweight="bold", color=t["ink"], pad=28)
    ax.text(-0.42, 1.0, f"One choice at a time, over the {sm['sessions']:,} book sessions every row counts "
            f"({sm['first']:%b %Y} to {sm['last']:%b %Y}).\nLine: the chosen specification ({base:+.2f}); band: its "
            f"SE ({se:.2f}); whiskers: each row's paired SE against it.", transform=ax.transAxes, fontsize=8.5,
            color=t["secondary"], va="bottom")
    fig.savefig(path, dpi=150, bbox_inches="tight")
    plt.close(fig)


